package ai

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
)

// repairPrefix — начало добавки ко второй попытке. Вынесен константой, потому что
// по нему тест отличает починку от первого запроса.
const repairPrefix = "Предыдущий ответ отвергнут проверкой: "

// repairSuffix — что делать с замечанием. Отдельной строкой, чтобы модель не
// принялась объяснять ошибку словами вместо того, чтобы вернуть документ.
const repairSuffix = "\nИсправь ровно это и верни JSON целиком, без пояснений."

// ErrRejected — модель дважды вернула документ, который не прошёл проверку
// потребителя. Причина последней попытки обёрнута внутрь: она уезжает в 422, потому
// что автору формы полезно знать, ЧТО не собралось.
var ErrRejected = errors.New("ai: ответ модели не прошёл проверку")

// AskJSON — вызов модели с одной попыткой починки: ответ, не принятый check,
// возвращается модели вместе с текстом замечания.
//
// Почему цикл здесь, а не у потребителя: политика повторов у подсистемы одна
// (клиент ретраит транспорт и пустой ответ, здесь ретраится СМЫСЛ), и разложенная
// по вызывающим она разъедется — один потребитель будет чинить дважды, другой ни
// разу. Про формы этот код по-прежнему не знает: что считать валидным, решает check.
//
// Повтор ровно один — по тому же доводу, что и в клиенте: генерация стоит денег, а
// модель, не понявшая замечание со второго раза, не поймёт его и с четвёртого.
func AskJSON(ctx context.Context, g Generator, req Request, check func(json.RawMessage) error) (json.RawMessage, error) {
	first, err := g.Generate(ctx, req)
	if err != nil {
		return nil, err
	}
	firstErr := check(first)
	if firstErr == nil {
		return first, nil
	}

	repair := req
	repair.User = req.User + "\n\n" + repairPrefix + firstErr.Error() + repairSuffix
	second, err := g.Generate(ctx, repair)
	if err != nil {
		// Транспорт отказал на починке — наружу идёт причина ОТКАЗА МОДЕЛИ, а не
		// транспорта: первая попытка уже показала, что провайдер отвечает, и
		// «провайдер недоступен» отправило бы искать не там.
		return nil, fmt.Errorf("%w: %v", ErrRejected, firstErr)
	}
	if err := check(second); err != nil {
		return nil, fmt.Errorf("%w: %v", ErrRejected, err)
	}
	return second, nil
}
