package ai

import (
	"context"
	"encoding/json"
	"errors"
)

// Request — один вызов модели: инструкция, текст автора и форма ответа.
type Request struct {
	// System — инструкция модели: что она собирает и по каким правилам.
	System string
	// User — текст автора: описание формы либо просьба её поправить.
	User string
	// History — предыдущие реплики разговора, от старых к новым, БЕЗ последней
	// (она и есть User). Едут отдельными сообщениями, а не склейкой в System:
	// у совместимого входа роли — часть протокола, и модель по ним отличает свои
	// прошлые слова от слов автора.
	//
	// Потолок держит вызывающий: контекст растёт линейно, и без него каждое
	// следующее сообщение разговора дороже предыдущего (ADR §10).
	History []Turn
	// SchemaName и Schema — JSON Schema ответа. Пусто — модель просят вернуть
	// произвольный JSON (режим json_object); задано — вход обязан удержать
	// ответ в схеме сам (json_schema).
	//
	// Схема НЕ заменяет проверку у потребителя: даже удержанный в схеме документ
	// может быть бессмысленным (шкала от 8 до 3), и последним рубежом остаётся
	// domain.ValidateSchema.
	SchemaName string
	Schema     json.RawMessage
	// MaxTokens — потолок ответа. Считается ВМЕСТЕ с рассуждением модели
	// (reasoning_content), а не только с видимым текстом: у рассуждающих моделей
	// тесный потолок означает пустой content при finish_reason=length. Замер
	// 2026-09-01: план из трёх вопросов — 433 токена ответа, из них большая часть
	// рассуждение.
	MaxTokens int
}

// Turn — одна реплика разговора.
type Turn struct {
	// Assistant — сказал это ассистент (иначе автор).
	Assistant bool
	Text      string
}

// Generator превращает запрос в ответ модели. Реализации: Client (совместимый с
// OpenAI вход), Disabled (провайдер не настроен на контуре) и Fake (тесты).
//
// Ответ отдаётся сырым: разбирать его — работа потребителя, который знает, чего
// просил.
type Generator interface {
	Generate(ctx context.Context, req Request) (json.RawMessage, error)
}

var (
	// ErrDisabled — подсистема выключена на контуре (AI_TRANSPORT=off либо ключ не
	// задан). Не сбой: контур без провайдера обязан работать, а ручки — отвечать
	// 404, как непрописанный провайдер OAuth.
	ErrDisabled = errors.New("ai: генерация на этом контуре не настроена")
	// ErrEmptyAnswer — модель не вернула текста ответа. Штатная причина —
	// исчерпанный потолок токенов (весь бюджет ушёл в рассуждение), поэтому
	// ошибка отдельная: она ретраится, а не разбирается как пустой документ.
	ErrEmptyAnswer = errors.New("ai: модель не вернула ответ")
	// ErrTruncated — ответ оборван потолком токенов: `finish_reason=length` при
	// непустом тексте.
	//
	// ЭТО НЕ «ПОТОЛОК МАЛ», А ВЫРОЖДЕНИЕ МОДЕЛИ, и знать разницу важнее всего
	// остального в этом файле. Замер 2026-09-02 (qwen3.6-35b-a3b, строгая схема,
	// сборка формы из пяти вопросов с оформлением): годный ответ — 818–1273 токена;
	// вырожденный — весь потолок целиком, из которого 95% символов пробелы и
	// переводы строки одним забегом на 15 тысяч знаков, начатым посреди пункта.
	// Пробел между лексемами JSON законен всегда, поэтому строгая схема такой забег
	// не обрывает. Частота зависит от температуры и ею же сбита с 75% попыток до
	// ~17% — таблица замера в комментарии к `temperature` (openai.go).
	//
	// Отсюда обращение: РЕТРАИТСЯ (вырождение недетерминированное, второй такой же
	// запрос обычно проходит), но НЕ ЧИНИТСЯ второй попыткой AskJSON — чинить нечего,
	// замечание к обрубку модели не поможет, а запрос только удлинит.
	//
	// МИНА: обрыв виден ТОЛЬКО по finish_reason. Текст в ответе есть, он похож на
	// настоящий, и без этой проверки обрубок JSON уезжает потребителю как годный
	// ответ — а тот сообщает автору, что не разобрал модель.
	ErrTruncated = errors.New("ai: ответ модели не поместился в потолок токенов")
	// ErrProvider — провайдер отказал или недоступен. Причину видит лог; наружу
	// она не идёт: у автора формы нет способа что-либо с ней сделать.
	ErrProvider = errors.New("ai: провайдер недоступен")
)

// Disabled — генератор контура без провайдера. Отдельный тип, а не nil-проверки у
// потребителей: composition root подставляет его один раз, и «выключено» перестаёт
// быть особым случаем в каждой ручке.
type Disabled struct{}

func (Disabled) Generate(context.Context, Request) (json.RawMessage, error) {
	return nil, ErrDisabled
}

var _ Generator = Disabled{}
