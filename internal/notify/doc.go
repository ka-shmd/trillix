// Package notify — уведомления кабинета: лента адресованных событий пространства.
//
// Рамка (ADR §10): строка таблицы notifications — ПОВОД, адресованный человеку,
// а не намерение доставки. Доставкой наружу заняты outbox (письма) и очереди по
// целям (интеграции); здесь наружу не уходит ничего — кабинет читает свою же БД.
//
// Три вещи, из которых состоит модуль:
//
//   - РЕЕСТР ПОВОДОВ (kinds.go) — единственное место, где повод описан целиком:
//     кому адресован (действие, а не роль), какой у него текст, куда ведёт ссылка
//     и снимается ли он отбоем. Экран берёт готовую строку; второй реализации
//     текста не существует — именно это делает будущий канал в мессенджер
//     приделкой, а не переделкой (спека §13). Рендер сообщения встанет сюда же,
//     когда канал придёт: заводить его сейчас без потребителя незачем.
//   - ПОСТАНОВКА И ОТБОЙ (service.go) — Notify размножает повод на адресатов
//     одним утверждением, Clear гасит непрочитанные строки повода-препятствия.
//   - ЧТЕНИЕ (service.go) — лента, счётчик непрочитанных, отметки прочтения.
//
// Слои — как в auth: Service (логика) → Store (доступ к данным поверх sqlc).
// Права спрашиваются у workspaces через интерфейс Access, объявленный здесь же,
// на стороне потребителя.
