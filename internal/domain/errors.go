package domain

import "errors"

// Доменные ошибки-сентинелы. Единственное место маппинга на HTTP-статусы —
// httpserver/respond.go; handler'ы свои http.Error не пишут (internal/CLAUDE.md).
// Сервисы возвращают эти ошибки (при необходимости обёрнутые контекстом через %w).
var (
	ErrNotFound     = errors.New("not found")
	ErrForbidden    = errors.New("forbidden")
	ErrValidation   = errors.New("validation failed")
	ErrUnauthorized = errors.New("unauthorized")

	// ErrConsentRequired — сессия есть, но действующая редакция Пользовательского
	// соглашения не принята: кабинет закрыт до экрана «Завершение регистрации» или
	// «Условия обновились» (docs/design/signup-consent.md §3.2). Маппится в 403
	// consent_required — отдельным кодом, потому что кабинет по нему уводит на экран
	// согласия, а не показывает «нет доступа».
	ErrConsentRequired = errors.New("consent required")
	ErrRateLimited     = errors.New("too many requests")

	// ErrTooLarge — тело запроса превысило потолок (MaxBytesReader). Маппится в 413.
	// Приём ответа ограничивает тело 256 КБ (ARCHITECTURE §4.4, инвариант 3).
	ErrTooLarge = errors.New("request entity too large")

	// ErrConflict — оптимистичная блокировка: клиент прислал устаревший updated_at,
	// ресурс изменён параллельно (другая вкладка). Маппится в 409 (ARCHITECTURE §5.1).
	ErrConflict = errors.New("conflict")

	// ErrFormClosed — форма больше не принимает ответы (снята вручную, наступила дата
	// закрытия или достигнут лимит; фаза 8.5 шаг 4). Маппится в 410 Gone — форма была
	// публичной, поэтому её существование не скрывается (инвариант 5 распространяется
	// только на черновик → 404). Рендерер по этому коду показывает «приём закрыт».
	ErrFormClosed = errors.New("form closed")

	// ErrFormLocked — форма закрыта паролем, а токена разблокировки в запросе нет
	// (или он не годен). Маппится в 401 form_locked. Не 403 и не 404: форма
	// опубликована, её существование не скрывается (решение владельца 2026-09-01,
	// design/form-password.md §2.3), а человеку есть что предъявить — пароль.
	//
	// ⚠ МИНА: эту ошибку обязан отдавать КАЖДЫЙ публичный вход по slug, а не только
	// отдача формы. С фазы 27 их шесть: отдача формы, приём ответа, автосохранение,
	// выдача слота файла, выдача свободного времени и холд. Общего middleware здесь нет и быть не может — решение принимается
	// по строке формы, а не по маршруту; список входов — design/form-password.md §3.3.
	ErrFormLocked = errors.New("form locked")

	// ErrLinkExpired — одноразовая ссылка больше не годна: по ней уже вошли либо
	// вышел срок (приглашение в пространство, фаза 18). Маппится в 410 Gone —
	// ссылка была настоящей, её существование не скрывается, а действие у
	// человека одно в обоих случаях: попросить новую. Различать «использована» и
	// «протухла» в ответе незачем, и это заодно не даёт перебором выяснять,
	// какие токены существовали.
	ErrLinkExpired = errors.New("link expired")

	// ErrWorkspaceFrozen — пространство заморожено: тариф ВЛАДЕЛЬЦА больше не
	// покрывает столько пространств (фаза 18, ADR §10). Маппится в 402 с кодом
	// workspace_frozen — отдельным от plan_required, потому что совет человеку
	// другой: не «оплатите возможность», а «данные целы, верните тариф».
	// Заморожен только кабинет: опубликованные формы продолжают принимать
	// ответы — отказ респонденту теряет данные клиента за неоплату владельцем.
	ErrWorkspaceFrozen = errors.New("workspace frozen")

	// ErrPlanRequired — возможность закрыта тарифом воркспейса (фаза 17).
	// Маппится в 402 Payment Required. Ставится ТОЛЬКО на чтении (воронка,
	// источники): приём ответа респондента не отказывает ни при каком состоянии
	// подписки — там исчерпанная квота помечает строку, а не отвергает её
	// (ADR §10). Тело ответа несёт настоящее число (сколько людей не дошло),
	// чтобы плашка апгрейда не рекламировала пустоту.
	ErrPlanRequired = errors.New("plan required")

	// ErrUnavailable — возможность на этом контуре не настроена или временно не
	// может отработать (печать PDF: контейнера принтера нет в dev; все слоты печати
	// заняты). Маппится в 503. Отличается от 500 тем, что это НЕ поломка: повтор
	// позже (или другой контур) сработает, и автору так и говорится — обёрнутым
	// человеческим текстом, как у ErrConflict.
	ErrUnavailable = errors.New("temporarily unavailable")

	// Аутентификация.
	ErrEmailTaken         = errors.New("email already registered")
	ErrInvalidCredentials = errors.New("invalid email or password")
)
