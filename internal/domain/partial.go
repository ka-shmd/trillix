package domain

import "encoding/json"

// Черновик ответа: что респондент набрал и не отправил (спека
// design/analytics-tally.md §10). Здесь — единственное правило, которое у черновика
// доменное: что вообще имеет право в нём лежать.

// FilterDraftAnswers оставляет в черновике только ключи отвечаемых блоков этой
// версии схемы.
//
// Живёт в домене, а не в сервисе, по той же причине, что и остальные правила про
// состав вопросов: знание «какой блок собирает ответ» принадлежит типу блока, и
// вторая его копия в чужом пакете разошлась бы при добавлении нового типа.
//
// ФАЙЛЫ ОТБРАСЫВАЮТСЯ вместе с неизвестными ключами, и это не мелочь: слот файла
// выдаётся отдельным потоком и живёт сутки, если ответ так и не пришёл. Сохранённая
// в черновике ссылка пережила бы чистку сирот и осталась битой — черновик показывал
// бы владельцу файл, которого уже нет.
//
// Неизвестные ключи выбрасываются МОЛЧА: схема могла смениться между открытием
// формы и автосохранением, и ронять из-за этого сохранение незачем — черновик
// неполон по определению.
func FilterDraftAnswers(schema FormSchema, in map[string]json.RawMessage) map[string]json.RawMessage {
	out := make(map[string]json.RawMessage, len(in))
	for _, b := range schema.Blocks {
		if !b.Type.isAnswerable() || b.Type == BlockFile {
			continue
		}
		if v, ok := in[b.ID]; ok {
			out[b.ID] = v
		}
	}
	return out
}
