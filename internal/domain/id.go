package domain

import (
	"fmt"

	"github.com/google/uuid"
)

// NewID возвращает новый UUIDv7 — идентификатор, упорядоченный по времени создания
// (старшие 48 бит — Unix-время в миллисекундах), поэтому дружелюбный к btree-индексам,
// в отличие от случайного UUIDv4. Единая точка генерации id для всех сущностей.
//
// uuid.NewV7 гарантирует строгую монотонность даже в пределах одной миллисекунды
// (12-битная последовательность, инкрементируемая при совпадении времени). Ошибку
// возвращает лишь при отказе системного источника случайности — событие
// катастрофическое и невосстановимое, поэтому здесь паника, а не проброс ошибки
// в каждый вызывающий код.
func NewID() uuid.UUID {
	id, err := uuid.NewV7()
	if err != nil {
		panic(fmt.Errorf("domain: generate uuidv7: %w", err))
	}
	return id
}
