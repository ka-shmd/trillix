package domain

// VisitInsights — счётчики визитов за окно наблюдения: то, что стоит карточками
// над всеми вкладками Insights (спека design/analytics-tally.md §5).
//
// Числа про ответы сюда не входят и входить не могут: ответы и визиты — два
// независимых множества (ANALYTICS.md §1), и складывать их в одну структуру
// значит однажды поделить одно на другое.
type VisitInsights struct {
	// Visits — визитов за период.
	Visits int
	// Submitted — из них закончившихся ответом. Конверсия считается отсюда, а не
	// делением числа ответов на число визитов.
	Submitted int
	// UniqueVisitors — сколько РАЗНЫХ посетителей за период (суточный ключ, ADR §10).
	// Визиты без ключа (нет адреса, нет секрета контура) не считаются вовсе: такой
	// визит не человек и не «ещё один человек».
	//
	// За период длиннее суток число ЗАВЫШЕНО: ключ ротируется, и один человек,
	// заходивший три дня подряд, выглядит тремя. Граница записана в ANALYTICS.md —
	// на экран она не выносится (решение владельца).
	UniqueVisitors int
	// TimedVisits — сколько визитов вошло в медиану: те, от кого доехал не один
	// бикон. Наружу уходит не ради показа, а чтобы экран отличил «0 секунд» от
	// «данных нет» и во втором случае нарисовал прочерк.
	TimedVisits int
	// MedianDurationSec — медианная длительность визита в секундах. Ноль при
	// TimedVisits == 0 — это «нет данных», а не «нулевая длительность».
	MedianDurationSec float64
	// TimedCompletions и CompletionDurationSec — то же самое, но только по визитам,
	// закончившимся ответом: «сколько занимает заполнить форму». Всегда больше
	// длительности визита, в которую входят ушедшие через три секунды.
	TimedCompletions      int
	CompletionDurationSec float64
}
