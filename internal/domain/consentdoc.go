// Типовые документы согласия и политики обработки персональных данных.
//
// Что в них обязано быть — docs/design/privacy-consent.md §2: оператор и его адрес,
// цель, перечень данных, действия и способы, срок, порядок отзыва (ч. 4 ст. 9 152-ФЗ);
// у политики — ещё правовое основание, права субъекта и меры защиты (ст. 18.1, 19).
//
// Абзаца об обработчике по поручению (Trillix) в шаблоне нет: у сервиса пока нет
// юрлица, реквизиты которого можно назвать (TECH-DEBT, TD-87). О передаче ответов
// интеграциям формы (Google Таблицы, вебхуки) шаблон молчит, а п. 4.3 политики обещает
// не раскрывать данные третьим лицам — открытый вопрос к юристу (TECH-DEBT, TD-88).
//
// ⚠ МИНА: ТЕКСТ ВЕРСИИ ШАБЛОНА НЕ ПРАВИТСЯ НА МЕСТЕ. Ревизия запоминает версию, которой
// собирались её документы, и по ней страница документа восстанавливает текст, с которым
// соглашался человек. Исправление формулировки — новая версия (новая ветка в
// renderConsentTemplate и ConsentTemplateVersion += 1), старые остаются как есть. Сторож —
// TestConsentTemplateV1_Frozen (отпечаток текста версии 1).

// ConsentTemplateVersion — версия шаблона, которой собираются новые ревизии.
const ConsentTemplateVersion = 1

// Формулировки по умолчанию для пустых цели и срока. Подставляются в оба документа,
// поэтому читаются и после «Цель обработки:», и после «Срок обработки:».
const (
	DefaultConsentPurpose   = "рассмотрение ответа, отправленного через Форму, и связь по вопросам, связанным с ним"
	DefaultConsentRetention = "до достижения цели обработки или до отзыва согласия"
)

// ConsentDocInput — то, из чего собирается документ помимо настроек ревизии.
type ConsentDocInput struct {
	// FormTitle — заголовок формы той версии, по которой показывается документ.
	FormTitle string
	// DataItems — названия вопросов той же версии: перечень данных в согласии.
	// Берутся из версии, а не хранятся в ревизии: добавленный вопрос попадает в
	// согласие сам, и ревизия от правки формы не протухает.
	DataItems []string
}

// ConsentDocument — документ, готовый к показу: заголовок и текст абзацами через
// перевод строки. Разметки в тексте нет — он рендерится текстом (инвариант 4).
type ConsentDocument struct {
	Title string
	Text  string
}

// RenderConsentDocument собирает документ ревизии. У своих документов шаблон не
// участвует: документ — вставленный автором текст как есть.
func RenderConsentDocument(kind ConsentDocKind, s ConsentSettings, template int, in ConsentDocInput) (ConsentDocument, error) {
	var custom, title string
	switch kind {
	case ConsentDocConsent:
		custom, title = s.ConsentText, "Согласие на обработку персональных данных"
	case ConsentDocPolicy:
		custom, title = s.PolicyText, "Политика обработки персональных данных"
	default:
		return ConsentDocument{}, fmt.Errorf("%w: неизвестный документ %q", ErrValidation, kind)
	}
	if s.Documents == ConsentDocCustom {
		return ConsentDocument{Title: title, Text: custom}, nil
	}
	text, err := renderConsentTemplate(kind, s, template, in)
	if err != nil {
		return ConsentDocument{}, err
	}
	return ConsentDocument{Title: title, Text: text}, nil
}

func renderConsentTemplate(kind ConsentDocKind, s ConsentSettings, template int, in ConsentDocInput) (string, error) {
	switch template {
	case 1:
		if kind == ConsentDocConsent {
			return consentTemplateV1(s, in), nil
		}
		return policyTemplateV1(s, in), nil
	default:
		return "", fmt.Errorf("consent template version %d is unknown", template)
	}
}

// operatorLine — «ООО «Ромашка», ИНН 7700000000, адрес: …». ИНН необязателен.
func operatorLine(o ConsentOperator) string {
	var b strings.Builder
	b.WriteString(o.Name)
	if o.INN != "" {
		b.WriteString(", ИНН ")
		b.WriteString(o.INN)
	}
	if o.Address != "" {
		b.WriteString(", адрес: ")
		b.WriteString(o.Address)
	}
	return b.String()
}

func formName(title string) string {
	if t := strings.TrimSpace(title); t != "" {
		return "«" + t + "»"
	}
	return "без названия"
}

func dataList(items []string) string {
	clean := make([]string, 0, len(items))
	for _, it := range items {
		if t := strings.TrimSpace(it); t != "" {
			clean = append(clean, "«"+t+"»")
		}
	}
	if len(clean) == 0 {
		return "сведения, указанные в Форме"
	}
	return "сведения, указанные в Форме: " + strings.Join(clean, "; ")
}

func orDefault(v, def string) string {
	if v == "" {
		return def
	}
	return v
}

