// Видимостей две. ПРИВАТНЫЙ шаблон принадлежит пространству и виден только его
// участникам; ПУБЛИЧНЫЙ не принадлежит никому, виден всем и заводится ручкой
// администратора сервиса (экрана у неё пока нет — приложение для админов будет
// отдельной работой). Встроенных шаблонов как отдельного вида не существует:
// шесть заготовок, живших статикой на фронте, залиты той же админской ручкой.
//
// Шаблон КОПИРУЕТСЯ в форму, а не связывается с ней: правка шаблона уже
// созданные формы не трогает, а идентификаторы документа при копировании
// выдаются заново (domain.NewSchemaIDs).
