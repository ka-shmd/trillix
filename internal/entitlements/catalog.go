// Package entitlements — единственное место, где код спрашивает «можно ли».
//
// Три уровня, которые обычно слипаются в один `if plan == "free"`, здесь
// разведены (ADR §10, спека docs/design/billing.md §4):
//
//   - КАКИЕ гейты бывают — этот файл (код: компилятор ловит опечатку в ключе);
//   - ЧТО даёт каждый план — данные (plans.limits): меняется UPDATE'ом без выкатки;
//   - ГДЕ гейт применяется — вызов Check* в сервис-методе.
//
// Отсюда цена изменений, ради которой всё и затевалось: добавить возможность в
// платный тариф — строка здесь + строка в limits каждого плана + вызов в сервисе;
// открыть возможность всем — ОДИН UPDATE, код не трогается вовсе (вызов Check*
// остаётся на месте и с этого момента всегда разрешает — он же выключатель обратно).
//
// `if plan == …` вне этого пакета запрещён (internal/CLAUDE.md): рассыпанные
// проверки означают, что через полгода на вопрос «что входит в Pro» отвечает
// только греп, а страница тарифов начинает врать.
package entitlements

// Key — ключ возможности. Совпадает с ключом в plans.limits.
type Key string

const (
	// SubmissionsPerMonth — сколько ответов воркспейс принимает за расчётный
	// период. Основной рычаг монетизации: гейт стоит на уже созданной ценности.
	SubmissionsPerMonth Key = "submissions_per_month"
	// Workspaces — сколько пространств может завести аккаунт. Считаются те,
	// которыми он ВЛАДЕЕТ, а не те, где состоит: иначе владелец Pro не смог бы
	// позвать ни одного человека с Free — а звать он будет именно их (ADR §10).
	Workspaces Key = "workspaces"
	// MembersPerWorkspace — сколько человек помещается в пространство (считая
	// владельца). Гейт стоит на приглашении: «позвать коллегу» — это и есть
	// момент, когда команда становится командой.
	MembersPerWorkspace Key = "members_per_workspace"
	// AnalyticsFunnel — воронка отвала: на каком вопросе уходят.
	AnalyticsFunnel Key = "analytics_funnel"
	// AnalyticsSources — источники трафика (utm и referer): секция «Источники» на
	// вкладке «Визиты». Гейт закрывает ОДНУ секцию, а не всю вкладку: график,
	// устройства и браузеры платными не объявлялись, и 402 на весь запрос унёс бы
	// их заодно.
	AnalyticsSources Key = "analytics_sources"
	// SubmissionsPartial — сбор и показ ЧАСТИЧНЫХ ответов: того, что респондент
	// набрал и не отправил.
	//
	// ЕДИНСТВЕННЫЙ КЛЮЧ, КОТОРЫЙ ГЕЙТИТ СБОР, А НЕ ПОКАЗ, и это записанное
	// исключение (ADR §10, решение владельца 2026-08-24). Аналитика собирается у
	// всех планов, потому что визиты — счётчики; черновик же содержимое чужого
	// ответа, и собирать его ради владельца, который его не увидит, — цена без
	// выгоды. К тому же респондента о сборе предупреждают: сбор «для всех» вешал
	// бы предупреждение и на бесплатные формы, которым он не нужен.
	//
	// Спрашивается ДВАЖДЫ: при включении тумблера формы и при отдаче публичной
	// формы (даунгрейд обязан останавливать сбор — тот же приём, что у бейджа).
	SubmissionsPartial Key = "submissions_partial"
	// FormDesignCustom — свои значения оформления: цвета, шрифт, ширина, кегль,
	// скругление, кнопка (фаза 22). ОБЕ ТЕМЫ, светлая и тёмная, бесплатны
	// намеренно: гейт ставится на созданную ценность, а не на настройку, и право
	// выбрать одну из двух тем — это право завести пустую папку. Новичок должен
	// получить «выглядит прилично» даром; платят за «выглядит как мы».
	//
	// Спрашивается на ПУБЛИКАЦИИ, а не на сохранении: автосейв не имеет права
	// вернуть 402 посреди набора (спека design/theme.md §9.3).
	FormDesignCustom Key = "form_design_custom"
	// FormCustomCSS — свой CSS формы. Отдельным ключом от остального оформления и
	// дороже: это не настройка, а доступ к вёрстке. Ключ заведён, точки применения
	// ещё нет — она приезжает слайсом 7.
	FormCustomCSS Key = "form_custom_css"
	// FormBranding — право снять бейдж «Сделано в Trillix» с публичной формы.
	//
	// ГЕЙТ ДРУГОЙ ПРИРОДЫ, чем у оформления, и это осознанно: цвет уехал в снапшот
	// и обязан пережить даунгрейд (за него платили тогда), а бейдж — свойство
	// ВЫДАЧИ, а не документа. Лежи он в снапшоте, один месяц оплаты навсегда снял
	// бы бейдж со всех опубликованных в этот месяц форм — это не подписка, а
	// разовая покупка. Поэтому спрашивается при отдаче публичной формы.
	FormBranding Key = "form_branding"
	// StoragePerWorkspace — сколько БАЙТ файлов в ответах помещается в пространство
	// (фаза 24). Единственный ключ, чей расход тратит не автор, а посторонний:
	// файлы кладёт респондент, поэтому без верхней границы у публичной формы её нет
	// вовсе. Заведён безлимитным у всех планов — включается одним UPDATE (§6
	// BILLING.md), как и остальные гейты.
	StoragePerWorkspace Key = "storage_per_workspace"
	// FormLinkPreview — своя карточка ссылки формы: имя площадки, заголовок,
	// описание, картинка и иконка в превью, которое рисуют мессенджеры и соцсети.
	//
	// ГЕЙТ ПРИРОДЫ БЕЙДЖА, а не оформления: спрашивается ПРИ ОТДАЧЕ публичной
	// страницы, а не при сохранении карточки. Настроить и увидеть предпросмотр
	// может кто угодно (иначе за возможность платят вслепую), но на саму ссылку
	// карточка действует, только пока тариф её разрешает; даунгрейд возвращает
	// дефолты, апгрейд оживляет уже сохранённое, ничего не стирая.
	FormLinkPreview Key = "form_link_preview"
	// FormNotifyEmail — право настроить письмо о новом ответе: имя отправителя,
	// Reply-To, тема, текст (миграция 0042) и PDF-вложение (2026-08-30).
	//
	// ГЕЙТ ПРИРОДЫ БЕЙДЖА: спрашивается и при сохранении, и при ОТПРАВКЕ письма.
	// При сохранении — потому что кабинет держит сам контрол (поля не редактируются
	// на бесплатном плане, EMBED §10 описывает тот же приём у бейджа); при отправке
	// — потому что месяц оплаты не покупает свой текст навсегда: даунгрейд обязан
	// вернуть дефолтный шаблон, ничего не стирая, и апгрейд оживит сохранённое.
	FormNotifyEmail Key = "form_notify_email"
	// FormRespondentEmail — право СЛАТЬ письмо респонденту после отправки формы
	// (миграция 0046, docs/design/respondent-email.md).
	//
	// Свой ключ, а не FormNotifyEmail, и разница не в жадности. Там платной
	// является ПЕРЕБИВКА письма владельцу — само письмо бесплатно, владелец пишет
	// сам себе. Здесь платной становится сама ОТПРАВКА: адрес приезжает ответом,
	// письмо уходит с нашего домена на адрес, который ввёл кто угодно, и на
	// бесплатном тарифе это открытый канал рассылки. Общий ключ означал бы, что
	// снятие гейта с одного письма молча открывает другое.
	//
	// ГЕЙТ ПРИРОДЫ БЕЙДЖА: спрашивается и при сохранении бланка, и при отправке
	// каждого письма — даунгрейд гасит отправку, ничего не стирая.
	FormRespondentEmail Key = "form_respondent_email"
	// FormCounters — счётчики аналитики автора на форме: Яндекс Метрика (фаза 29
	// DEV-PLAN, миграция 0067, docs/design/yandex-metrika.md §5). Назван по функции,
	// а не по провайдеру: VK Pixel и GA, появившись, встанут под тот же ключ.
	//
	// ГЕЙТ ПРИРОДЫ БЕЙДЖА: спрашивается при отдаче публичной формы, а не при
	// сохранении. Сохранить счётчик бэк даёт на любом тарифе (контрол держит
	// кабинет); на страницу формы номер уезжает, только пока тариф разрешает, —
	// даунгрейд снимает счётчик сам, апгрейд возвращает сохранённое.
	FormCounters Key = "form_counters"

	// AIGenerations — сколько раз за месяц можно обратиться к ассистенту (фаза 26,
	// миграции 0048 и 0049). Квота, а не тумблер: каждый вызов стоит денег снаружи,
	// и вопрос здесь «сколько», а не «можно ли».
	//
	// Единица расхода — СООБЩЕНИЕ автора (0049), поэтому и заголовок про сообщения:
	// автор видит его дважды — на странице тарифа и под вводом в шторке ассистента.
	// Имя ключа осталось прежним: переименование стоило бы миграции ради красоты.
	//
	// Безлимита у этого ключа не бывает ни на одном плане — null означал бы
	// открытый счёт у провайдера, оплачиваемый нами. Отсюда же единственный в
	// каталоге АККАУНТНЫЙ счётчик у воркспейс-ключа (0053, ADR §10): пока расход
	// копился в workspace_usage, тот же открытый счёт открывался кнопкой «Новое
	// пространство» — конечный лимит умножался числом пространств, а их число
	// планами не ограничено.
	AIGenerations Key = "ai_generations"

	// BookingSchedulesMax — сколько расписаний записи можно завести в пространстве
	// (фаза 27, миграция 0051). Квота, а не тумблер: сама запись на время тарифом
	// не закрыта — это не объём, а способ работы, — а вот число независимых потоков
	// занятости («Мария», «Пётр», «второй кабинет») растёт вместе с бизнесом.
	//
	// Приезжает ОТКРЫТЫМ (null) на всех планах: гейт заведён заранее, чтобы
	// включаться одним UPDATE без выкатки, а не переделкой сервиса.
	BookingSchedulesMax Key = "booking_schedules_max"
)

// Kind — как читать значение ключа в plans.limits.
type Kind uint8

const (
	// Quota — число (или null = безлимит): «сколько можно».
	Quota Kind = iota + 1
	// Toggle — булев: «можно или нет».
	Toggle
)

// Scope — чей план разрешает возможность. Разделение не косметическое:
// аккаунт-уровневый лимит воркспейсом невыразим (нового воркспейса ещё нет,
// а старый к нему отношения не имеет), поэтому его разрешает план личного
// воркспейса-якоря — ADR §10.
type Scope uint8

const (
	// WorkspaceScope — спрашивается у плана самого воркспейса (CheckWorkspace).
	WorkspaceScope Scope = iota + 1
	// AccountScope — спрашивается у подписки самого аккаунта (CheckAccount):
	// нового воркспейса ещё нет, а старый к нему отношения не имеет.
	AccountScope
)

// Meter — откуда берётся израсходованное. Не выводится из Kind: Workspaces —
// тоже Quota, но её счётчик другой природы (число строк здесь и сейчас, а не
// расход, накопленный за расчётный период).
type Meter uint8

const (
	// NoMeter — расход не считается: Decision.Used всегда 0.
	NoMeter Meter = iota
	// SubmissionsMeter — расход берётся из workspace_usage.submissions за период.
	SubmissionsMeter
	// MembersMeter — израсходовано = сколько человек уже в пространстве.
	// Периода нет: выгнал участника — место освободилось сразу.
	MembersMeter
	// StorageMeter — израсходовано = сумма размеров ЗАЯВЛЕННЫХ файлов пространства.
	// Периода нет, как у мест: удалил ответ — место в хранилище освободилось сразу.
	StorageMeter
	// WorkspacesMeter — израсходовано = сколько пространств аккаунт уже держит
	// (строки workspace_members с role='owner'). Периода у этого счётчика нет:
	// удалил пространство — освободилось место, ждать первого числа не нужно.
	WorkspacesMeter
	// AIGenerationsAccountMeter — расход берётся из account_usage.ai_generations
	// ВЛАДЕЛЬЦА пространства за период. Свой счётчик, а не SubmissionsMeter:
	// обнуляются они вместе (период один), но считают разное, и общая колонка
	// означала бы, что ответы съедают сообщения ассистенту.
	//
	// АККАУНТНЫЙ, в отличие от всех соседей по этому списку, и это единственная
	// причина, по которой имя такое длинное: платит аккаунт, а не пространство
	// (0053). Заводя следующую квоту, спроси не «чей план», а «чей КОШЕЛЁК»: пока
	// счётчик стоял на пространстве, конечный лимит умножался их числом.
	AIGenerationsAccountMeter
	// SchedulesMeter — израсходовано = сколько расписаний в пространстве СЕЙЧАС.
	// Периода нет, как у мест и хранилища: удалил расписание — место освободилось
	// сразу, ждать первого числа не нужно.
	SchedulesMeter
)

// AccountWide — лежит ли счётчик этого метра на АККАУНТЕ, а не на пространстве.
//
// Свойство метра, а не Scope: Scope отвечает, чей ПЛАН разрешает возможность, —
// вопрос здесь другой, где копится РАСХОД. Разошлись эти два ответа ровно один
// раз (ai_generations: спрашивают у пространства, считают на аккаунт), и страница
// тарифа обязана их различать — иначе одно и то же число нарисуется в строке
// каждого пространства.
func (m Meter) AccountWide() bool {
	return m == WorkspacesMeter || m == AIGenerationsAccountMeter
}

// Feature — описание возможности.
type Feature struct {
	Kind  Kind
	Scope Scope
	Meter Meter
	// Title — как возможность называется человеку (страница «Тариф»).
	Title string
}

