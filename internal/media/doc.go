// Package media — приём и хранение картинок: элементы формы (лейаут-блок image,
// обложка, логотип) и аватар пользователя (docs/design/s3-media.md). Автор
// загружает картинку в билдере; сервис проверяет членство в воркспейсе (через
// forms), валидирует (PNG/JPEG, гард размеров), пере-кодирует (снимая EXIF/GPS),
// кладёт в public-read бакет через слой blob и возвращает стабильный ключ
// (workspaceID/<sha256>.ext), который билдер пишет в settings.imageKey блока.
//
// Аватар отличается от прочих картинок только неймспейсом ключа (avatars/) и
// тем, что членство для него не проверяется: он принадлежит человеку, а не
// пространству, и право на него доказывает сессия — её проверяет auth, который
// же и владеет колонкой users.avatar_key.
//
// Первый доменный потребитель слоя blob (слой-2). Раздача картинок респонденту —
// мимо приложения (Caddy→бакет), поэтому здесь только запись (PutObject).
