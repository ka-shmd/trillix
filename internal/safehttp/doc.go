// Package safehttp — исходящие запросы по адресу, который дал пользователь
// (вебхуки, фаза 28 `DEV-PLAN`; картинка обложки по ссылке). Единственная дорога
// продукта к чужому адресу:
// остальные внешние вызовы (Google, S3, SMTP, модель) ходят по адресам из
// конфига.
//
// Защита от SSRF держится на ОДНОЙ проверке — адреса, к которому реально идёт
// соединение (`net.Dialer.Control`): она видит IP уже после резолва, в момент
// connect, и смена DNS её не обходит. Validate при сохранении — только ради
// внятного отказа сразу, а не через сутки поломки. Правила и отвергнутые
// варианты — ADR §10, спека docs/design/webhooks.md §8.
//
// Выключателя в конфиге нет: разрешающий Guard (AllowAll) подставляют только
// тесты — так же, как ratelimit.AllowAll (инвариант безопасности 6).
