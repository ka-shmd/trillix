// Package answerfiles — файлы, приложенные респондентом к ответу (блок file,
// docs/design/answer-files.md). Второй доменный потребитель слоя blob после media
// и первый, кто выдаёт право записи в бакет ПОСТОРОННЕМУ.
//
// Байты через процесс не идут: сервис выписывает presigned-адрес на один ключ,
// один размер и пять минут, а браузер кладёт файл в хранилище сам. Отсюда три
// правила, которые здесь нельзя нарушить.
//
//  1. Ключ объекта формирует СЕРВЕР. Имя, присланное клиентом, — данные: оно
//     хранится в строке, показывается автору и уезжает в Content-Disposition, но
//     в ключ не попадает ни в каком виде.
//  2. Всё, что ограничивает загрузку, входит в подпись. Проверка, оставшаяся на
//     нашей стороне, для владельца адреса не существует.
//  3. Файлы ответов НЕ обрабатываются: ни декодирования картинок, ни распаковки
//     архивов — в отличие от media, который картинки пересобирает. Превью в
//     таблице ответов означало бы декодер для чужих байтов.
//
// Бакет свой и приватный: у картинок форм и файлов респондентов несовместимые
// политики (те раздаются анонимно, эти — только по короткой подписи и только
// вложением).
