// Package mail — транзакционный outbox и доставка писем во внешний мир.
//
// Рамка (ADR §10): outbox — узкий механизм НАДЁЖНОЙ ДОСТАВКИ НАРУЖУ, а не шина
// событий. Строка таблицы outbox — намерение доставки («доставить payload по
// каналу channel»), которое продюсер пишет в ТОЙ ЖЕ транзакции, что и своё
// изменение состояния (классический transactional outbox: атомарности между БД
// и внешним сервисом нет, поэтому событие фиксируется в БД, а доставка — отдельно).
//
// Диспетчер (Service.Dispatch, гоняется periodic-задачей) — тупой единообразный
// релей: выбирает готовые строки, по channel отдаёт их нужному транспорту
// (сейчас единственный — email через Mailer), при успехе помечает sent_at, при
// сбое растит attempts и откладывает по экспоненциальному бэкоффу. Никакой
// бизнес-логики на потребителе: это держит модель ретраев/идемпотентности единой
// для всех будущих каналов (вебхуки — фаза 15, телега — потом).
//
// Слои — как в auth: Service (логика диспетчеризации и бэкофф) → Store (доступ к
// данным поверх sqlc). Транспорт (Mailer) инжектируется: dev — LogMailer (пишет
// в лог, провайдер не нужен), прод — HTTP-клиент провайдера (слайс E почтовой
// фазы). Смена провайдера — одна реализация Mailer.
