// Package booking — расписания записи на время: сущности пространства, ручные
// блокировки и брони (фаза 27, docs/design/booking.md).
//
// Модуль держит обе половины записи. Кабинетную: завести расписание, поправить,
// удалить, закрыть время руками, посмотреть ближайшие записи и отменить одну
// (service.go, handler.go). И публичную: свободное время, холд, подтверждение брони
// в приёме ответа и отмена по ссылке из письма (public.go, confirm.go, cancel.go).
// Разделение проходит не по данным, а по доверию: у кабинетной половины право даёт
// сессия и workspaces.Can, у публичной — slug формы, id клиента и подписанный токен
// отмены.
//
// Расчёт свободного времени модулю не принадлежит: это чистая функция
// domain.FreeSlots, а модуль лишь приносит ей занятое. Так же устроена и проверка
// правила — domain.ValidateSchedule.
