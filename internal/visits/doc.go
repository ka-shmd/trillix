// Package visits — визиты публичной формы (фаза 8.5, шаг 6): знаменатель к числу
// ответов («N просмотров → M ответов») и фундамент воронки «на каком вопросе ушли».
//
// Визит считает рендерер биконами (navigator.sendBeacon), а не сервер на выдаче
// формы (ADR §10): серверный счёт занижен кэшем GET формы (max-age=60/ETag/304),
// считает краулеров вместо людей и принципиально не может сказать, докуда дошёл
// ушедший. Публичная ручка POST /public/v1/forms/{slug}/visits — третья на запись,
// поэтому собрана по образцу приёма ответа: лимит размера тела, своё ведро
// rate-limit по IP, тот же HMAC-токен формы.
//
// Приватность — часть контракта модуля: IP не пишется ни в открытом виде, ни в
// хеше; cookie и localStorage рендерер не заводит, id визита живёт в памяти
// страницы и умирает с ней — человек между визитами не узнаётся сознательно.
//
// Опубликованную форму модуль получает через коллаборатор Forms (интерфейс сервиса
// forms) — прямого доступа к чужому repo нет (internal/CLAUDE.md).
