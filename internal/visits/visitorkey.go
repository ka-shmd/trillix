package visits

import (
	"crypto/hmac"
	"crypto/sha256"
	"time"

	"github.com/google/uuid"
)

// visitorKeyLen — сколько байт хеша кладём в строку визита. 16 байт (128 бит)
// исключают случайные столкновения на любом мыслимом числе визитов и вдвое
// экономят место против полного sha256.
const visitorKeyLen = 16

// visitorKeyLabel — метка назначения при выводе секрета аналитики из секрета
// токена формы. Ради неё вывод и делается: ключ посетителя и подпись формы —
// РАЗНЫЕ ключи, и знание одного не даёт другого. Менять метку нельзя — она входит
// в вычисление, и другая строка обнулит сравнимость собранных ключей.
const visitorKeyLabel = "trillix/visitor-key/v1"

// deriveVisitorSecret выводит секрет аналитики из секрета токена формы.
//
// Отдельной переменной окружения у этого секрета НЕТ намеренно (решение владельца
// 2026-08-24): FORM_TOKEN_SECRET уже есть на каждом контуре, уже разный у dev и
// прода и уже достаточной длины — заводить вторую строку в конфиге значило бы
// брать с владельца плату настройкой за одну карточку.
//
// Разделение по назначению обязательно: без метки один и тот же байтовый ключ
// подписывал бы токены форм и считал посетителей, и утечка любого из применений
// била бы по обоим. HMAC с меткой даёт ключ, из которого исходный не выводится.
//
// Цена, принятая явно: смена FORM_TOKEN_SECRET меняет и ключи посетителей —
// уникальные по разные стороны смены становятся несравнимы (число за период,
// накрывающий её, завышено). Данные при этом целы.
func deriveVisitorSecret(formTokenSecret []byte) []byte {
	if len(formTokenSecret) == 0 {
		return nil
	}
	h := hmac.New(sha256.New, formTokenSecret)
	h.Write([]byte(visitorKeyLabel))
	return h.Sum(nil)
}

// visitorKey — суточный ключ посетителя (спека design/analytics-tally.md §6).
//
//	key = sha256( hmac(secret, YYYY-MM-DD) ‖ form_id ‖ ip ‖ user-agent )[:16]
//
// Три составляющие, и каждая закрывает свой сценарий:
//
//   - СОЛЬ ДНЯ (hmac от секрета контура и даты) — ключ живёт сутки. Постоянная соль
//     дала бы сквозной псевдоним через месяцы и через все формы продукта, то есть
//     профиль посетителя вместо счётчика. Вчерашняя соль нигде не хранится, поэтому
//     связать вчерашнего посетителя с сегодняшним не можем и мы сами.
//   - form_id — один человек на двух формах даёт два разных ключа. Без него ключ
//     сшивал бы аудиторию разных владельцев в одно множество.
//   - ip + user-agent — то немногое, что отличает людей без cookie и localStorage.
//     Мера грубая (офис за одним NAT с одинаковыми браузерами схлопнется в одного),
//     и это записанная погрешность, а не недосмотр.
//
// Пустой IP (заголовка не было, локальный контур) даёт nil: считать всех безадресных
// одним человеком значило бы врать в меньшую сторону, а каждого своим — в большую.
// Честнее не считать их вовсе — карточка показывает знаменатель.
func visitorKey(secret []byte, formID uuid.UUID, ip, userAgent string, at time.Time) []byte {
	if len(secret) == 0 || ip == "" {
		return nil
	}
	day := hmac.New(sha256.New, secret)
	day.Write([]byte(at.UTC().Format(time.DateOnly)))
	salt := day.Sum(nil)

	h := sha256.New()
	h.Write(salt)
	h.Write(formID[:])
	h.Write([]byte(ip))
	h.Write([]byte(userAgent))
	return h.Sum(nil)[:visitorKeyLen]
}
