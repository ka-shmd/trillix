// Колонок в одном ряду (секции). Зеркалит MaxColumns. Потолок — про ВИД, а не про
// устройство: раскладчику всё равно, сколько колонок, но при ширине формы 700px
// четыре колонки дают по 154px, а шесть — по 90px, где не читается уже ничего, кроме
// галочки. Четыре — последнее число, при котором в колонку помещается короткое поле
// с подписью. Что читается в такой колонке, решает автор формы (ADR §10); редактор
// ограничивает только то, за чем не уследить глазами, — число колонок.
