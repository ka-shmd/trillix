import { z } from 'zod'
import {
  FILE_FAMILIES,
  MAX_COLUMNS,
  MAX_ID_LEN,
  MAX_IMAGE_KEY_LEN,
  MAX_OPTION_LABEL_LEN,
  MAX_OPTIONS,
  MAX_PLACEHOLDER_LEN,
} from './limits'

// Настройки блока — ОДИН объект на все типы, а не объединение по типу.
//
// Фаза 16 разнесла свойства типов по файлам, но форму документа на проводе не тронула
// (спека §3.6, условие 1): ключи те же, `strictObject` тот же, дискриминированное
// объединение по типу отклонено — оно меняет пути ошибок и форму зеркала в Go, то есть
// это смена контракта под видом уборки. Из реестра типов выводится не форма настроек, а
// проверка «этому типу этот ключ разрешён» (OWNED_SETTINGS ниже).

// НОМЕР КОЛОНКИ секции, считая с единицы: элемент стоит в 1-й, 2-й… колонке текущего
// ряда, отсутствие ключа = полная ширина и конец секции. Секция сущностью схемы не
// является — её выводит раскладчик, как groupId выводит regroup.
//
// Нумерация с ЕДИНИЦЫ, а не с нуля: в Go тот же ключ живёт с `omitempty`, и нулевой
// индекс молча исчез бы при сериализации, превратив первую колонку в полную ширину.
//
// До 2026-08-10 значений было два ('left'/'right'), и это был единственный предел,
// мешавший ряду из трёх и более элементов (решение владельца: до четырёх колонок).
// Верхнюю границу держит MAX_COLUMNS — она про вид, а не про устройство.
export const columnSchema = z.number().int().min(1).max(MAX_COLUMNS)

// Стабильный id блока/опции: непустой, в пределах длины. Формат (blk_/opt_) не
// навязываем — id генерируется клиентом, важны непустота и уникальность.
export const idSchema = z.string().min(1).max(MAX_ID_LEN)

// Вариант выбора у choice-блока.
export const optionSchema = z.strictObject({
  id: idSchema,
  label: z.string().max(MAX_OPTION_LABEL_LEN),
  // Тот же номер колонки, что у блока (спека §5.1): тот же диапазон и тот же
  // раскладчик. Открыта ли секция — не валидируется, как и у блока: флаг инертен,
  // а не невалиден. У опций dropdown инертен всегда (список живёт в нативном
  // select) — и потому не запрещён.
  column: columnSchema.optional(),
})
export type Option = z.infer<typeof optionSchema>

// Типоспецифичные настройки. Пустой объект — валидное состояние блока без настроек.
// Лишние ключи запрещены (strictObject).
export const settingsSchema = z.strictObject({
  options: z.array(optionSchema).max(MAX_OPTIONS).optional(),
  // Плейсхолдер поля ввода (текстовые типы). У остальных ИГНОРИРУЕТСЯ, а не
  // запрещается — см. OWNED_SETTINGS ниже.
  placeholder: z.string().max(MAX_PLACEHOLDER_LEN).optional(),
  // Картинка (тип image): ключ объекта в бакете.
  imageKey: z.string().max(MAX_IMAGE_KEY_LEN).optional(),
  // Диапазон шкалы (тип scale). Оба конца или ни одного — правило самого типа
  // (blocks/scale.ts, issues); «ни одного» — недособранный черновик, как choice без
  // опций.
  scaleMin: z.number().int().optional(),
  scaleMax: z.number().int().optional(),
  // Настройки блока file (фаза 24). Диапазон проверяет сам тип (blocks/file.ts,
  // issues), как и у шкалы: здесь — форма значения, там — правило типа. Отсутствие
  // ключа читается как дефолт (DEFAULT_MAX_FILES/DEFAULT_MAX_FILE_SIZE_MIB), и
  // указатель-подобной пары «не задано против задано 0», как у scaleMin, тут не
  // нужно: ни нуля файлов, ни файла нулевого размера не бывает.
  maxFiles: z.number().int().optional(),
  maxFileSize: z.number().int().optional(),
  // Семейства типов, которые автор пускает в вопрос. Пусто (и отсутствие ключа) =
  // все разрешённые продуктом. Белый список MIME живёт только в Go: он — граница
  // безопасности, и второй его экземпляр здесь означал бы, что она разъедется.
  accept: z.array(z.enum(FILE_FAMILIES)).max(FILE_FAMILIES.length).optional(),
  // Колонка секции: номер 1..MAX_COLUMNS = «я в этой колонке текущей секции»,
  // отсутствие ключа = полная ширина и КОНЕЦ секции. Ширина не хранится
  // вовсе, её выводит раскладчик. Запрещён только заголовку формы (canShareRow);
  // кросс-блочное условие «секция открыта» намеренно не валидируется — инертный флаг
  // легален, иначе undo и промежуточные состояния драга ловили бы 422.
  column: columnSchema.optional(),
})
export type Settings = z.infer<typeof settingsSchema>

// Ключ настроек, ЗАКРЕПЛЁННЫЙ за типом: его наличие у типа, который им не владеет, —
// ошибка схемы. Владение объявляет сам тип (ownSettings в его файле), а инвентарь
// ключей живёт здесь: ключ — свойство общего мешка настроек, а не одного типа.
export type OwnedSettingKey =
  | 'options'
  | 'imageKey'
  | 'scaleMin'
  | 'scaleMax'
  | 'maxFiles'
  | 'maxFileSize'
  | 'accept'

// Инвентарь закреплённых ключей: как называть ключ в сообщении и что считать его
// НАЛИЧИЕМ. Оба поля переносят сегодняшнее поведение дословно, и ни одно не
// декоративно:
//
//   • noun — сообщение остаётся тем же текстом («тип X не имеет опций»), что до
//     фазы 16, поэтому тесты обеих сторон краснеют только там, где правило реально
//     изменилось;
//   • present — у ключей РАЗНОЕ понятие пустоты, и это не небрежность: options: []
//     у не-choice блока законны (пустой список = ничего не задано), imageKey: ''
//     тоже, а scaleMin: 0 — заданное значение (значимый нуль, см. fields/README.md).
//     Одна общая проверка `!= null` начала бы отвергать документы, которые сегодня
//     принимаются, — то есть сломала бы критерий этапа 16.1.
//
// Порядок важен: пара scaleMin/scaleMax делит noun, и по нему же дедуплицируется
// сообщение (§ниже, ownedSettingIssues) — как сегодня, где обе шкальные настройки на
// чужом типе дают ОДНО замечание.
export const OWNED_SETTINGS: ReadonlyArray<{
  key: OwnedSettingKey
  noun: string
  present: (v: unknown) => boolean
}> = [
  { key: 'options', noun: 'опций', present: (v) => Array.isArray(v) && v.length > 0 },
  { key: 'imageKey', noun: 'картинки', present: (v) => Boolean(v) },
  { key: 'scaleMin', noun: 'шкалы', present: (v) => v !== undefined },
  { key: 'scaleMax', noun: 'шкалы', present: (v) => v !== undefined },
  // Три ключа блока file делят одно существительное — как пара шкалы: на чужом типе
  // они дают ОДНО замечание, а не три про одно и то же.
  { key: 'maxFiles', noun: 'файлов', present: (v) => v !== undefined },
  { key: 'maxFileSize', noun: 'файлов', present: (v) => v !== undefined },
  { key: 'accept', noun: 'файлов', present: (v) => Array.isArray(v) && v.length > 0 },
]
