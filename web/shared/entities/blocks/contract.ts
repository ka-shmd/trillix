import { type OwnedSettingKey, type Settings } from './settings'

// Контракт файла типа блока (фаза 16, спека §3). Один файл на тип, один и тот же
// интерфейс у всех — и исчерпывающий Record в index.ts, поэтому забытый тип не
// «ведёт себя как соседний», а не компилируется.
//
// Здесь живут только СВОЙСТВА типа. Отношения блоков (regroup, ряды, планирование
// дропа, контракт фокуса, карта клавиш) остаются в общем коде: правило про двух
// участников, уехавшее в файл одного из них, расходится половинами и молча (спека §3.4).

// Порядок значений — контрактный: z.enum строится из этого кортежа, и он же задаёт
// порядок обхода в тестах паритета с Go. Три семьи подряд, чтобы список читался.
export const BLOCK_TYPES = [
  // отвечаемые
  'short_text',
  'long_text',
  'email',
  'phone',
  'number',
  'scale',
  'single_choice',
  'dropdown',
  'multi_choice',
  'date',
  'consent',
  // файл в ответе (фаза 24): значение — массив id загрузок, выданных сервером.
  // Ни имени, ни размера, ни MIME в ответе нет — это утверждения клиента, а правда
  // о файле лежит в submission_files и проверена у хранилища.
  'file',
  // подписи
  'title',
  'label',
  // контент
  'heading',
  'text',
  'image',
  // разрыв страницы (фаза 19): граница между страницами многостраничной формы.
  // Контент, а не отдельная семья: он не собирает ответ, и все правила неотвечаемого
  // блока (вне CSV, вне сводки, вне модели вопросов) — ровно те, что ему нужны.
  // Страница СУЩНОСТЬЮ схемы не является: её выводит splitPages (@fields/groups), как
  // groupId выводит regroup, а двухколоночную секцию — packCells.
  'page_break',
  // условная логика: «когда <условие> → тогда <действия>». Контент по той же причине,
  // что и разрыв страницы, — ответа не собирает; респонденту не показывается вовсе.
  // Позиция значима только для перехода и «скрыть кнопку»: у них цель — страница, на
  // которой блок стоит. Остальные действия от его места не зависят (ADR §10).
  'logic',
  // заголовок ФОРМЫ (фаза 15): первая строка документа, <h1> у респондента. Отдельный
  // тип, а не 'title': тот — подпись ВОПРОСА, из которой аналитика берёт имя колонки
  // CSV и шага воронки.
  'form_title',
] as const

export type BlockType = (typeof BLOCK_TYPES)[number]

// Семья типа — единственный источник трёх предикатов сразу (isAnswerable/isCaption/
// isContent), которые до фазы 16 были тремя независимыми наборами:
//   • 'answer'  — собирает ответ (включая consent);
//   • 'caption' — подпись вопроса (title/label): его text — имя вопроса для аналитики;
//   • 'content' — оформление (heading/text/image) и заголовок формы.
// Неотвечаемые — это 'caption' + 'content': забыть тип в старом наборе CONTENT_TYPES
// значило молча сделать его отвечаемым (колонка в выгрузке и шаг воронки, которых
// автор не создавал). Теперь «забыть» нечего: семья обязательна.
export type BlockFamily = 'answer' | 'caption' | 'content'

// Замечание валидатора от самого типа: сообщение и путь внутри блока. Zod-независимо
// намеренно — тот же список пригодится, когда правило понадобится вне схемы.
export type SchemaIssue = { message: string; path: (string | number)[] }

export interface BlockKindContract {
  family: BlockFamily
  // Тип несёт собственное поле text: подписи, контентные абзацы/заголовки, заголовок
  // формы и consent (текст согласия рядом с галочкой). У прочих text обязан быть пуст.
  carriesText: boolean
  // Типу разрешено делить ряд (ADR §10). Разрешено всем, кроме заголовка формы: он
  // рисуется вне потока вопросов, соседей по ряду у него не бывает.
  canShareRow: boolean
  // Ключи настроек, закреплённые за типом (инвентарь — settings.ts). Наличие такого
  // ключа у типа, который им не владеет, — ошибка схемы.
  ownSettings: readonly OwnedSettingKey[]
  // Плейсхолдер — подсказка РЕДАКТОРА, а не правило схемы: у остальных типов ключ
  // игнорируется и НЕ запрещается (так было до фазы 16, и менять это здесь нельзя —
  // документы с плейсхолдером у шкалы валидны и сегодня).
  supportsPlaceholder: boolean
  // Правило ВСТАВКИ редактора, зеркала в Go нет намеренно (EDITOR.md §1): список
  // вариантов или шкала без вопроса — не вопрос, а мусор на полотне, поэтому вставка
  // приводит такой тип со своим заголовком. Но блок без подписи ОСТАЁТСЯ валидным:
  // кросс-блочное условие в валидаторе ловило бы 422 на undo и на промежуточных
  // состояниях драга.
  requiresCaption: boolean
  // Кардинальность выбора: 'single' — ответ строка-id, 'multi' — массив id. Отсюда
  // выводятся isChoiceType и isSingleChoiceType. Отдельного «я choice» флага нет
  // намеренно: dropdown, забытый в старом наборе SINGLE_CHOICE_TYPES, молча уезжал в
  // ветку multi и ждал массив вместо строки.
  choice?: 'single' | 'multi'
  // Правила самого типа поверх формы настроек (диапазон шкалы, уникальность id
  // вариантов). Вызывается только когда у блока есть настройки.
  issues?: (settings: Settings) => SchemaIssue[]
}
