// Индикатор шагов многостраничной формы (фаза 19) — общий вывод для рендерера и превью
// билдера, по тому же доводу, что у хрома страницы: место и вид индикатора автор обязан
// видеть ровно те, что увидит респондент. До этого разметка стояла двумя копиями, и
// расхождение между ними не покраснело бы нигде.
//
// Полоска РАЗРЕЗАНА по шагам (решение владельца 2026-08-05): отдельная линия под каждую
// страницу вместо одной сплошной. Сплошная показывает «сколько пройдено», разрезанная —
// ещё и «сколько всего осталось штук», а это и есть вопрос, который человек задаёт себе
// на длинной форме.
//
// КЛИКАБЕЛЬНОСТЬ ЛИНИЙ — ЗА НАСТРОЙКОЙ ФОРМЫ (`allowBack`, колонка 0055): передан
// `onGo` — линии пройденных шагов кнопки, не передан — индикатор чистый счётчик, и
// нажимать в нём нечего. Дефолт настройки выключен, поэтому по умолчанию поверхности
// получают ровно тот индикатор, что стоял с 2026-08-22 по 2026-09-07.
//
// Кликабельны только ПРОЙДЕННЫЕ шаги, и никогда те, что впереди: возврат свободен,
// вперёд — только через «Далее» с проверкой текущей страницы. Кликабельный шаг вперёд
// был бы оглавлением со скачком, которое обесценивает пошаговую валидацию.
//
// ⚠ МИНА: условие кнопки — `i < page`, а НЕ «дальний достигнутый шаг». С `i <= reached`
// человек, вернувшийся на первую страницу, получал кликабельную линию второй и уходил
// туда мимо «Далее» — то есть мимо валидации текущей страницы, ради которой пошаговость
// и заведена (дефект найден ночным e2e, TD-57/TD-58).
//
// Недостигнутый шаг — не отключённая кнопка, а вообще не кнопка: отключённая обещает,
// что вот-вот станет доступной, и ловит Tab на том, чего нажать нельзя.

export function StepBar({
  pages,
  page,
  onGo,
}: {
  // Сколько всего страниц и на какой мы сейчас (индексы с нуля).
  pages: number
  page: number
  // Ход назад по клику; не передан — линии некликабельны вовсе.
  onGo?: (next: number) => void
}) {
  if (pages < 2) return null // индикатор из одной линии — шум, а не индикатор
  const label = `Шаг ${page + 1} из ${pages}`
  return (
    <div className="rf-progress">
      {/* Подписи под линиями нет (решение владельца 2026-08-05): номер шага читается из
          самих линий. Но для скринридера линии — пустые прямоугольники, поэтому счёт
          остаётся ДВАЖДЫ и оба раза невидимо: именем списка (где я сейчас, если прийти
          сюда Tab'ом) и живой областью ниже (что изменилось, когда шаг сменился). */}
      <ol className="rf-steps" aria-label={label}>
        {Array.from({ length: pages }, (_, i) => {
          const state = i === page ? 'current' : i < page ? 'done' : 'ahead'
          const cls = `rf-step-mark rf-step-mark--${state}`
          const clickable = onGo !== undefined && i < page
          return (
            <li key={i} className="rf-step-cell" aria-current={i === page ? 'step' : undefined}>
              {clickable ? (
                <button
                  type="button"
                  className={`${cls} rf-step-link`}
                  onClick={() => onGo(i)}
                  aria-label={`Вернуться к шагу ${i + 1} из ${pages}`}
                />
              ) : (
                <span className={cls} />
              )}
            </li>
          )
        })}
      </ol>
      <p className="rf-sr-only" role="status">
        {label}
      </p>
    </div>
  )
}
