// Индикатор шагов многостраничной формы (фаза 19) — общий вывод для рендерера и превью
// билдера, по тому же доводу, что у хрома страницы: место и вид индикатора автор обязан
// видеть ровно те, что увидит респондент. До этого разметка стояла двумя копиями, и
// расхождение между ними не покраснело бы нигде.
//
// Полоска РАЗРЕЗАНА по шагам (решение владельца 2026-08-05): отдельная линия под каждую
// страницу вместо одной сплошной. Сплошная показывает «сколько пройдено», разрезанная —
// ещё и «сколько всего осталось штук», а это и есть вопрос, который человек задаёт себе
// на длинной форме.
//
// КЛИКАБЕЛЬНОСТЬ — только назад, по уже пройденным шагам. Это не полумера, а то же
// решение владельца, что и у кнопок: «Назад» свободен, вперёд — только через «Далее» с
// проверкой текущей страницы. Кликабельный шаг вперёд был бы оглавлением со скачком,
// которое обесценивает пошаговую валидацию (и осложнит условные переходы, когда они
// придут). Недостигнутый шаг поэтому не кнопка ВОВСЕ, а не отключённая кнопка: Tab не
// должен спотыкаться о то, чего нажать нельзя.

export function StepBar({
  pages,
  page,
  reached,
  onGo,
}: {
  // Сколько всего страниц и на какой мы сейчас (индексы с нуля).
  pages: number
  page: number
  // Самый дальний достигнутый шаг: до него включительно можно вернуться кликом.
  reached: number
  onGo: (next: number) => void
}) {
  if (pages < 2) return null // «Шаг 1 из 1» — шум, а не индикатор
  return (
    <div className="rf-progress">
      <ol className="rf-steps">
        {Array.from({ length: pages }, (_, i) => {
          const state = i === page ? 'current' : i < page ? 'done' : 'ahead'
          const cls = `rf-step-mark rf-step-mark--${state}`
          // Вернуться можно на любой пройденный шаг, кроме текущего.
          const clickable = i <= reached && i !== page
          return (
            <li key={i} className="rf-step-cell" aria-current={i === page ? 'step' : undefined}>
              {clickable ? (
                <button
                  type="button"
                  className={`${cls} rf-step-link`}
                  onClick={() => onGo(i)}
                  aria-label={`Вернуться к шагу ${i + 1} из ${pages}`}
                />
              ) : (
                <span className={cls} />
              )}
            </li>
          )
        })}
      </ol>
      {/* role=status озвучивает смену шага скринридеру без ручного управления фокусом.
          Он же — единственный текстовый носитель прогресса: линии декоративны. */}
      <p className="rf-step" role="status">
        Шаг {page + 1} из {pages}
      </p>
    </div>
  )
}
