// Индикатор шагов многостраничной формы (фаза 19) — общий вывод для рендерера и превью
// билдера, по тому же доводу, что у хрома страницы: место и вид индикатора автор обязан
// видеть ровно те, что увидит респондент. До этого разметка стояла двумя копиями, и
// расхождение между ними не покраснело бы нигде.
//
// Полоска РАЗРЕЗАНА по шагам (решение владельца 2026-08-05): отдельная линия под каждую
// страницу вместо одной сплошной. Сплошная показывает «сколько пройдено», разрезанная —
// ещё и «сколько всего осталось штук», а это и есть вопрос, который человек задаёт себе
// на длинной форме.
//
// ИНДИКАТОР НЕКЛИКАБЕЛЕН ЦЕЛИКОМ (решение владельца 2026-08-22): хода назад в форме нет
// вовсе — ни кнопкой, ни по линии шага, ни системной «Назад» браузера (историю шагов
// рендерер не пишет). Линия пройденного шага кнопкой возврата НЕ становится: индикатор
// считает («где я и сколько всего»), а не управляет.
//
// Шаг — не отключённая кнопка, а вообще не кнопка: отключённая обещает, что вот-вот
// станет доступной, и ловит Tab на том, чего нажать нельзя.

export function StepBar({
  pages,
  page,
}: {
  // Сколько всего страниц и на какой мы сейчас (индексы с нуля).
  pages: number
  page: number
}) {
  if (pages < 2) return null // индикатор из одной линии — шум, а не индикатор
  const label = `Шаг ${page + 1} из ${pages}`
  return (
    <div className="rf-progress">
      {/* Подписи под линиями нет (решение владельца 2026-08-05): номер шага читается из
          самих линий. Но для скринридера линии — пустые прямоугольники, поэтому счёт
          остаётся ДВАЖДЫ и оба раза невидимо: именем списка (где я сейчас, если прийти
          сюда Tab'ом) и живой областью ниже (что изменилось, когда шаг сменился). */}
      <ol className="rf-steps" aria-label={label}>
        {Array.from({ length: pages }, (_, i) => {
          const state = i === page ? 'current' : i < page ? 'done' : 'ahead'
          return (
            <li key={i} className="rf-step-cell" aria-current={i === page ? 'step' : undefined}>
              <span className={`rf-step-mark rf-step-mark--${state}`} />
            </li>
          )
        })}
      </ol>
      <p className="rf-sr-only" role="status">
        {label}
      </p>
    </div>
  )
}
