// Публичный URL картинки блока из её ключа в бакете. Относительный `/media/<key>`
// раздаётся same-origin (в проде — Caddy, в dev — vite-proxy; deploy/Caddyfile,
// docs/design/s3-media.md §8), поэтому одинаков для кабинета и рендерера и
// покрывается CSP `img-src 'self'`. Ключ — S3-безопасный (workspaceID/<sha256>.ext),
// дополнительного кодирования не требует.

// ПРЕФИКС — ради ОДНОЙ поверхности: печатной страницы ответа (ADR §10). Её открывает
// браузер контейнера `printer`, для которого весь мир — это api: раздачи Caddy он не
// видит, и картинки едут через /internal/print/media. Всем остальным префикс пуст, и
// адрес получается прежний, байт в байт.
//
// Модульная переменная, а не аргумент функции: mediaSrc зовут из полудюжины мест
// трёх поверхностей, и протаскивать через них базу значило бы менять сигнатуры ради
// одного потребителя, который выставляет её один раз при старте страницы.
let base = ''

// setMediaBase выставляет префикс адресов картинок. Зовётся ДО первой отрисовки
// (web/renderer/src/print/main.tsx); пустая строка возвращает поведение по умолчанию.
export function setMediaBase(next: string): void {
  base = next
}

export function mediaSrc(imageKey: string): string {
  return `${base}/media/${imageKey}`
}
