// Метаданные группы для рендера (v2, фаза 8.7): подпись группы и признак
// обязательности её поля. Раскладчик блоков (FormView/PreviewPane) считает их один
// раз и раздаёт в BlockField: блок-подпись берёт required для звёздочки, поле —
// caption для aria. Зеркалит domain.groupCaptions в Go: title перебивает label,
// пустой текст не в счёт; required — если хоть одно поле группы обязательно.
export type GroupMeta = { caption: string; required: boolean }

// Раскладка блоков по группам в порядке потока: блоки одного вопроса несут общий
// groupId и идут подряд (regroup держит группу односвязной). Возвращает группы в
// порядке первого вхождения, внутри — блоки в исходном порядке. Единый источник
// разбиения для всех поверхностей: рендерер и превью оборачивают каждую группу в
// .rf-group (вертикальный ритм 12px — и внутри вопроса, и между вопросами), полотно
// редактора строит из этого же ту же вложенность (`SlashEditor.groups`), а стор
// раскладывает им же полотно, когда двигает группы целиком (`moveGroup`,
// `reorderGroups`, `placeInRow`).
export function groupBlocks<T extends { groupId: string }>(blocks: T[]): { id: string; blocks: T[] }[] {
  const out: { id: string; blocks: T[] }[] = []
  for (const b of blocks) {
    const last = out[out.length - 1]
    if (last && last.id === b.groupId) last.blocks.push(b)
    else out.push({ id: b.groupId, blocks: [b] })
  }
  return out
}

// splitFormTitle — заголовок формы отдельно от остального документа (фаза 15).
// Блок form_title живёт первым в списке блоков (инвариант схемы), но РИСУЕТСЯ вне
// потока вопросов: `<h1 class="rf-title">` перед `.rf-form`, как он рисовался и до
// фазы. Иначе он попал бы внутрь `.rf-form` и получил её ритм (12px между
// вопросами) вместо своего (48px заголовок→форма) — то самое расхождение
// редактора с превью, которого этап 13.3 добился нулём.
//
// Один помощник на все три поверхности: разъедься они здесь, и заголовок поехал бы
// на одной из них — ровно тот класс расхождений, ради которого раскладчик общий.
export function splitFormTitle<T extends { type: BlockType }>(blocks: T[]): { title: T | null; rest: T[] } {
  const i = blocks.findIndex((b) => b.type === 'form_title')
  if (i < 0) return { title: null, rest: blocks }
  return { title: blocks[i]!, rest: [...blocks.slice(0, i), ...blocks.slice(i + 1)] }
}

// splitPages — страницы формы (фаза 19). Разрыв (`page_break`) — граница, а не элемент:
// в возвращённых страницах его нет, страницы идут в порядке документа, и на выходе их
// всегда хотя бы одна (форма без разрывов — это одна страница, то есть ровно поведение
// до фазы).
//
// ПУСТЫЕ СТРАНИЦЫ ВЫКИДЫВАЮТСЯ ЗДЕСЬ, а не запрещаются валидатором. Разрыв первым
// блоком, два подряд, разрыв последним — законные промежуточные состояния набора,
// драга и undo; кросс-блочное правило в схеме ловило бы на них 422, как ловило бы на
// инертном бите ряда (formSchema.ts, packCells). Инертный разрыв убирает стор, мусор на
// экране — этот раскладчик, и обе уборки идут ПОСЛЕ валидности, а не вместо неё.
//
// Один помощник на три поверхности, по тому же доводу, что splitFormTitle: разъедься
// разбиение — и автор увидел бы в превью не те страницы, что респондент.
export function splitPages<T extends { type: BlockType }>(blocks: T[]): T[][] {
  return splitPagesWithClosers(blocks).map((p) => p.blocks)
}

// Страница вместе с ЗАКРЫВАЮЩИМ её разрывом (null у последней). Нужна условной логике
// (фаза 21): переходы «куда уходим с этой страницы» живут на закрывающем разрыве, и
// достать его иначе можно было бы только вторым разбором документа — то есть второй
// копией правил о том, какой разрыв инертен.
//
// Разбиение остаётся ОДНИМ: splitPages выражен через эту функцию, а не рядом с ней.
export type PageRun<T> = { blocks: T[]; closer: T | null }

export function splitPagesWithClosers<T extends { type: BlockType }>(blocks: T[]): PageRun<T>[] {
  const pages: PageRun<T>[] = []
  let cur: T[] = []
  for (const b of blocks) {
    if (b.type !== 'page_break') {
      cur.push(b)
      continue
    }
    // Инертный разрыв (первым блоком, второй подряд): страницы не открывает и не
    // закрывает — правило то же, по которому пустые страницы не доезжают до экрана.
    if (cur.length === 0) continue
    pages.push({ blocks: cur, closer: b })
    cur = []
  }
  if (cur.length > 0) pages.push({ blocks: cur, closer: null })
  return pages.length > 0 ? pages : [{ blocks: [], closer: null }]
}

// pageNumbers — какую страницу открывает каждый разрыв. Нужен полотну редактора: метка
// «Страница 3» на разделителе обязана считаться ТЕМ ЖЕ разбиением, которым respondent'у
// режется форма, иначе автор увидит на полотне номера, которых у респондента нет.
//
// Разрыва нет в карте — он ИНЕРТЕН и страницы не открывает: два подряд, разрыв в самом
// конце (за ним пусто) и разрыв до первого блока (страницы перед ним нет вовсе). Инертный
// разрыв законен и НЕ удаляется: за ним автор ещё допишет блоки, и стирать набранное
// «в порядке уборки» редактор не вправе — в отличие от бита ряда, который не содержимое,
// а выводимая метаданная.
export function pageNumbers<T extends { id: string; type: BlockType }>(
  blocks: T[],
): Map<string, number> {
  const out = new Map<string, number>()
  let openedBy: string | null = null
  let filled = false
  let page = 0
  const closeSegment = () => {
    if (!filled) return
    page++
    // Первая страница ничьим разрывом не открыта: разрыв, за которым она оказалась,
    // стоит выше всего содержимого и не делит ничего.
    if (openedBy !== null && page > 1) out.set(openedBy, page)
  }
  for (const b of blocks) {
    if (b.type === 'page_break') {
      closeSegment()
      openedBy = b.id
      filled = false
      continue
    }
    filled = true
  }
  closeSegment()
  return out
}

// ИМЯ СТРАНИЦЫ: своё (settings.pageName разрыва, её открывшего) либо «Страница N».
//
// Одна точка подстановки дефолта на все поверхности — по тому же доводу, что и у
// splitPages: разъедься она, и подпись разделителя на полотне разошлась бы с тем, как
// страница называется в аналитике. Первая страница ничьим разрывом не открыта (opener
// null), поэтому имени у неё не бывает вовсе — только номер.
//
// Пустая строка и отсутствие ключа значат одно и то же: имени нет. Так автор стирает
// имя, не оставляя в документе пустого ключа со особым смыслом.
export function pageName<T extends { settings?: { pageName?: string } }>(
  opener: T | null,
  number: number,
): string {
  return opener?.settings?.pageName?.trim() || `Страница ${number}`
}

// ЭКРАН ПОСЛЕ ОТПРАВКИ — ХВОСТ ДОКУМЕНТА за разрывом с флагом. Отсюда всё остальное:
// «за ним не бывает страниц» — это и есть «он хвост», а не отдельное правило.
//
// Флаг ЛЕГАЛЕН только там, где может подействовать (thankYouIssue ниже), и редактор не
// даёт его поставить в других местах, а уже стоящий снимает канон стора
// (normalizeThankYou). Схема при этом кросс-блочных правил по-прежнему не знает: 422 на
// промежуточном состоянии драга дороже, чем уборка в сторе.

// thankYouIssue — что МЕШАЕТ пометить этот разрыв экраном после отправки. null — ничто.
//
//   'not-last' — за разрывом есть ещё страница, а экран после отправки бывает только
//                хвостом: иначе «Далее» вело бы с него в форму, из которой ответ уже ушёл;
//   'question' — за разрывом стоит отвечаемый блок, а ответ с экрана, показанного ПОСЛЕ
//                отправки, физически никуда не уйдёт.
//
// «За разрывом пока пусто» помехой НЕ считается: страница, которую автор сейчас наберёт, —
// обычное состояние набора, а запрет на неё означал бы, что вставить экран нельзя вовсе
// (свежий разрыв всегда пуст). Такой флаг законен и просто ещё не действует — ровно как
// инертный бит колонки.
//
// Порядок проверок значим: документ с вопросом на ЧУЖОЙ странице ниже подходит под оба
// условия, и назвать его надо тем, что автор поймёт, — «ниже есть ещё страница».
export function thankYouIssue<T extends { id: string; type: BlockType }>(
  blocks: T[],
  breakId: string,
): 'not-last' | 'question' | null {
  const i = blocks.findIndex((b) => b.id === breakId)
  if (i < 0) return null
  const tail = blocks.slice(i + 1)
  // Больше одной страницы в хвосте = за разрывом есть ещё страница. Хвостовые инертные
  // разрывы страниц не открывают и помехой не являются — их splitPages и не считает.
  if (splitPagesWithClosers(tail).length > 1) return 'not-last'
  return tail.some((b) => isAnswerableType(b.type)) ? 'question' : null
}

// thankYouOpener — разрыв, за которым лежит ДЕЙСТВУЮЩИЙ экран после отправки, либо null.
// Действует = флаг стоит, ставить его тут можно (thankYouIssue) и за ним есть хотя бы один
// блок: пустой экран показывать нечем, и рендерер в этом случае берёт свою заглушку.
export function thankYouOpener<T extends { id: string; type: BlockType }>(blocks: T[]): T | null {
  return findThankYou(blocks)?.opener ?? null
}

// Ищем ПОСЛЕДНИЙ подходящий разрыв: экран после отправки один, и он хвост документа.
// Поиск с конца, а не «разрыв последней страницы», потому что подряд идущие разрывы
// (законное состояние набора) делают «последнюю страницу» неоднозначной: закрывает её
// первый из них, а номер получает второй.
function findThankYou<T extends { id: string; type: BlockType }>(
  blocks: T[],
): { opener: T; blocks: T[] } | null {
  for (let i = blocks.length - 1; i >= 0; i--) {
    const b = blocks[i]!
    if (b.type !== 'page_break') continue
    if (!hasThankYouFlag(b) || thankYouIssue(blocks, b.id) !== null) continue
    // Разрывы внутри хвоста инертны по построению (иначе было бы 'not-last'), поэтому
    // просто выбрасываем их: границ внутри экрана после отправки не бывает.
    const page = blocks.slice(i + 1).filter((x) => x.type !== 'page_break')
    return page.length > 0 ? { opener: b, blocks: page } : null
  }
  return null
}

// Флаг читается через хелпер, а не полем в дженерике: `settings` есть у всех блоков, но
// сужать сигнатуру до «блок с настройками» незачем — функции выше про раскладку.
function hasThankYouFlag(block: unknown): boolean {
  return (block as { settings?: { thankYou?: boolean } }).settings?.thankYou === true
}

// splitThankYou — документ, разрезанный на ФОРМУ и ЭКРАН ПОСЛЕ ОТПРАВКИ.
//
// Резать нужно ДО всего остального (planForm, splitPages, индикатор шагов, переходы
// условной логики): экран после отправки — не шаг формы, и стоит ему попасть в список
// страниц, как «Далее» поведёт на него мимо отправки, индикатор посчитает шаг, которого
// нет, а переход условной логики получит цель, с которой ответ уже не уйдёт. Один разрез
// в одном месте вместо оговорки «кроме последней» в каждом из них.
//
// Экрана нет (флага нет, ставить его тут нельзя, за ним пусто) → thankYou === null и
// blocks возвращаются как есть, то есть ровно поведение до задачи.
export function splitThankYou<T extends { id: string; type: BlockType }>(
  blocks: T[],
): { blocks: T[]; thankYou: T[] | null } {
  const found = findThankYou(blocks)
  if (found === null) return { blocks: [...blocks], thankYou: null }
  const cut = blocks.indexOf(found.opener)
  // Формой остаётся всё ДО разрыва: за ним начинается экран, и хвостовые инертные разрывы
  // внутри него — тоже его часть, а не забытый мусор формы.
  return { blocks: blocks.slice(0, cut), thankYou: found.blocks }
}

// Ряд — это КОЛОНКИ, а колонка — стопка элементов. Полноширинный ряд = одна колонка с
// одним элементом; СЕКЦИЯ = от двух до MAX_COLUMNS непустых колонок, в каждой сколько
// угодно элементов.
export type Row<T> = T[][]

// Ядро упаковки (спека §11.3) — автомат по потоку с одним состоянием: «открытая
// секция». Ключ — НОМЕР КОЛОНКИ, считая с единицы:
//
//   ключа нет  → секция закрывается, элемент во всю ширину;
//   1          → в первую колонку; секции нет — открываю;
//   n > 1      → в n-ю колонку; секции нет — открываю, ЗАБРАВ предыдущий
//                полноширинный элемент в первую колонку.
//
// Колонок до MAX_COLUMNS, и отдельной проверки потолка здесь НЕТ: новая колонка
// открывается только номером выше уже достигнутого, а номера выше потолка не
// принимает контракт. Одна граница, а не две расходящиеся.
//
// «Забрать предыдущего» — не костыль совместимости, а нужный жест: «поставь этот блок
// справа от того» не должно требовать сначала помечать левый. Так же читается
// промежуточный результат жеста: первая колонка там неявная. Забирать некого (элемент
// первый, пара недопустима) → ключ инертен, но НЕ невалиден: кросс-блочное условие не
// валидируется ни в Zod, ни в Go, иначе undo и промежуточные состояния драга ловили бы
// 422. Инертный бит убирает стор (normalizeColumns), а не валидатор.
//
// СЕКЦИИ С ПУСТОЙ КОЛОНКОЙ НЕ БЫВАЕТ: одинокая единица даёт ряд из одной колонки, то
// есть ту же полную ширину, и её ключ стор снимет как инертный. Дыр не бывает по той
// же причине: номер выше СЛЕДУЮЩЕЙ свободной колонки прижимается к ней, а не
// оставляет за собой пустую (канон потом перенумерует).
//
// Порядок документа неприкосновенен: конкатенация колонок равна исходному списку, а
// значит и порядок DOM, Tab и чтения скринридером. Колоночный порядок внутри секции
// (вся первая колонка, затем вся вторая, …) держит стор нормализацией — раскладчик
// принимает любой и в перестановку не вмешивается.
//
// Одно ядро на ДВА слоя: группы (packRows) и варианты (packOptionRows). Допустимость
// пары спрашивается у canPair(левый, правый); левым для всей колонки остаётся тот, кто
// секцию открыл.
function packCells<T>(
  items: T[],
  bitOf: (i: T) => ColumnBit | undefined,
  canPair: (left: T, right: T) => boolean,
): Row<T>[] {
  const rows: Row<T>[] = []
  // Открытая секция — тот же массив, что лежит в rows: дописываем в него по месту.
  let section: Row<T> | null = null
  for (const item of items) {
    const bit = bitOf(item)
    if (bit === undefined) {
      section = null
      rows.push([[item]])
      continue
    }
    // Номер НИЖЕ уже достигнутой колонки закрывает секцию и открывает новую. Канон
    // внутри секции колоночный (сперва вся первая колонка, потом вся вторая, …),
    // поэтому «первая колонка после второй» может значить только начало следующей
    // секции. Без этого правила две соседние секции в явной форме склеивались бы в
    // одну — и у формы, собранной раньше, два ряда молча становились бы одним.
    if (section !== null && bit < section.length) section = null
    if (section === null) {
      if (bit <= 1) {
        section = [[item]]
        rows.push(section)
        continue
      }
      // Номер > 1 без открытой секции: забрать предыдущий полноширинный элемент.
      const prev = rows[rows.length - 1]
      const prevSolo = prev?.length === 1 && prev[0]!.length === 1 ? prev[0]![0]! : undefined
      if (prevSolo === undefined || !canPair(prevSolo, item)) {
        rows.push([[item]]) // забирать некого → ключ инертен
        continue
      }
      section = prev!
    }
    const opener = section[0]![0]!
    if (!canPair(opener, item)) {
      // Пара недопустима (тип не делит ряд): секция закрывается,
      // элемент уходит своим рядом, ключ инертен.
      section = null
      rows.push([[item]])
      continue
    }
    // Дыр не бывает: номер выше следующей свободной колонки прижимается к ней.
    const col = Math.min(bit, section.length + 1)
    if (col <= section.length) section[col - 1]!.push(item)
    else section.push([item])
  }
  return rows
}

// Ключ колонки значим только на ПЕРВОМ блоке группы: он ставит в колонку вопрос
// целиком, остальные строки едут с ним. Ряда ВНУТРИ вопроса нет (ADR §10, 2026-09-14):
// поле в другой колонке, чем подпись, в вопрос не входит — это решает regroup в сторе,
// и сюда группы приходят уже разобранными. Ключ на не первом блоке инертен.
type ColumnBit = number
type RowCell = { type: BlockType; settings?: { column?: ColumnBit; columnWidth?: number } }

const bitOfBlock = (b: RowCell | undefined): ColumnBit | undefined => b?.settings?.column

// Группы в ряды. Обёртка .rf-row достаётся только ряду из двоих, ряд из одного
// рендерится без неё (лишний div не меняет вид, но шумит в DOM). Единый раскладчик всех
// трёх поверхностей — поверх groupBlocks.
export function packRows<T extends { blocks: RowCell[] }>(groups: T[]): Row<T>[] {
  return packCells(
    groups,
    (g) => bitOfBlock(g.blocks[0]),
    (l, r) => groupCanPair(l.blocks) && groupCanPair(r.blocks),
  )
}

// groupCanPair — МОЖЕТ ЛИ ГРУППА СТОЯТЬ В ЯЧЕЙКЕ РЯДА: разрешает ли делить ряд тип её
// первого блока (contract.ts, зеркало canShareRow в Go).
//
// Экспортируется, и спрашивать им обязаны ВСЕ три стороны — раскладчик (здесь), команда
// (`placeInRow`) и приглашение жеста (`inviteRowId`, `rowPosition`, `rowCandidate`
// полотна). Разойдясь, они дают жест, молча не делающий ничего: приглашение обещает ряд,
// которого команда не сделает. Типов с `canShareRow: false` два — заголовок формы (в
// раскладку не попадает, стор вырезает его `rowGroups`) и РАЗРЫВ СТРАНИЦЫ, которого
// вырезать нельзя: он ГРАНИЦА и обязан закрывать секцию, иначе она склеится через него
// и разъедется на две страницы.
//
// Типовое условие нужно и самому раскладчику: правило «номер > 1 забирает предыдущий
// полноширинный элемент» (packCells) иначе утащило бы разрыв в левую колонку — а такого
