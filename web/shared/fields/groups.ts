// Метаданные группы для рендера (v2, фаза 8.7): подпись группы и признак
// обязательности её поля. Раскладчик блоков (FormView/PreviewPane) считает их один
// раз и раздаёт в BlockField: блок-подпись берёт required для звёздочки, поле —
// caption для aria. Зеркалит domain.groupCaptions в Go: title перебивает label,
// пустой текст не в счёт; required — если хоть одно поле группы обязательно.
export type GroupMeta = { caption: string; required: boolean }

// Раскладка блоков по группам в порядке потока: блоки одного вопроса несут общий
// groupId и идут подряд (regroup держит группу односвязной). Возвращает группы в
// порядке первого вхождения, внутри — блоки в исходном порядке. Единый источник
// разбиения для всех поверхностей: рендерер и превью оборачивают каждую группу в
// .rf-group (ритм внутри вопроса 14px против 28px между — этап 13.3), полотно
// редактора строит из этого же ту же вложенность (`SlashEditor.groups`), а стор
// раскладывает им же полотно, когда двигает группы целиком (`moveGroup`,
// `reorderGroups`, `placeInRow`).
export function groupBlocks<T extends { groupId: string }>(blocks: T[]): { id: string; blocks: T[] }[] {
  const out: { id: string; blocks: T[] }[] = []
  for (const b of blocks) {
    const last = out[out.length - 1]
    if (last && last.id === b.groupId) last.blocks.push(b)
    else out.push({ id: b.groupId, blocks: [b] })
  }
  return out
}

// splitFormTitle — заголовок формы отдельно от остального документа (фаза 15).
// Блок form_title живёт первым в списке блоков (инвариант схемы), но РИСУЕТСЯ вне
// потока вопросов: `<h1 class="rf-title">` перед `.rf-form`, как он рисовался и до
// фазы. Иначе он попал бы внутрь `.rf-form` и получил её ритм (28px между
// вопросами) вместо своего (48px заголовок→форма) — то самое расхождение
// редактора с превью, которого этап 13.3 добился нулём.
//
// Один помощник на все три поверхности: разъедься они здесь, и заголовок поехал бы
// на одной из них — ровно тот класс расхождений, ради которого раскладчик общий.
export function splitFormTitle<T extends { type: BlockType }>(blocks: T[]): { title: T | null; rest: T[] } {
  const i = blocks.findIndex((b) => b.type === 'form_title')
  if (i < 0) return { title: null, rest: blocks }
  return { title: blocks[i]!, rest: [...blocks.slice(0, i), ...blocks.slice(i + 1)] }
}

// splitPages — страницы формы (фаза 19). Разрыв (`page_break`) — граница, а не элемент:
// в возвращённых страницах его нет, страницы идут в порядке документа, и на выходе их
// всегда хотя бы одна (форма без разрывов — это одна страница, то есть ровно поведение
// до фазы).
//
// ПУСТЫЕ СТРАНИЦЫ ВЫКИДЫВАЮТСЯ ЗДЕСЬ, а не запрещаются валидатором. Разрыв первым
// блоком, два подряд, разрыв последним — законные промежуточные состояния набора,
// драга и undo; кросс-блочное правило в схеме ловило бы на них 422, как ловило бы на
// инертном бите ряда (formSchema.ts, packCells). Инертный разрыв убирает стор, мусор на
// экране — этот раскладчик, и обе уборки идут ПОСЛЕ валидности, а не вместо неё.
//
// Один помощник на три поверхности, по тому же доводу, что splitFormTitle: разъедься
// разбиение — и автор увидел бы в превью не те страницы, что респондент.
export function splitPages<T extends { type: BlockType }>(blocks: T[]): T[][] {
  return splitPagesWithClosers(blocks).map((p) => p.blocks)
}

// Страница вместе с ЗАКРЫВАЮЩИМ её разрывом (null у последней). Нужна условной логике
// (фаза 21): переходы «куда уходим с этой страницы» живут на закрывающем разрыве, и
// достать его иначе можно было бы только вторым разбором документа — то есть второй
// копией правил о том, какой разрыв инертен.
//
// Разбиение остаётся ОДНИМ: splitPages выражен через эту функцию, а не рядом с ней.
export type PageRun<T> = { blocks: T[]; closer: T | null }

export function splitPagesWithClosers<T extends { type: BlockType }>(blocks: T[]): PageRun<T>[] {
  const pages: PageRun<T>[] = []
  let cur: T[] = []
  for (const b of blocks) {
    if (b.type !== 'page_break') {
      cur.push(b)
      continue
    }
    // Инертный разрыв (первым блоком, второй подряд): страницы не открывает и не
    // закрывает — правило то же, по которому пустые страницы не доезжают до экрана.
    if (cur.length === 0) continue
    pages.push({ blocks: cur, closer: b })
    cur = []
  }
  if (cur.length > 0) pages.push({ blocks: cur, closer: null })
  return pages.length > 0 ? pages : [{ blocks: [], closer: null }]
}

// pageNumbers — какую страницу открывает каждый разрыв. Нужен полотну редактора: метка
// «Страница 3» на разделителе обязана считаться ТЕМ ЖЕ разбиением, которым respondent'у
// режется форма, иначе автор увидит на полотне номера, которых у респондента нет.
//
// Разрыва нет в карте — он ИНЕРТЕН и страницы не открывает: два подряд, разрыв в самом
// конце (за ним пусто) и разрыв до первого блока (страницы перед ним нет вовсе). Инертный
// разрыв законен и НЕ удаляется: за ним автор ещё допишет блоки, и стирать набранное
// «в порядке уборки» редактор не вправе — в отличие от бита ряда, который не содержимое,
// а выводимая метаданная.
export function pageNumbers<T extends { id: string; type: BlockType }>(
  blocks: T[],
): Map<string, number> {
  const out = new Map<string, number>()
  let openedBy: string | null = null
  let filled = false
  let page = 0
  const closeSegment = () => {
    if (!filled) return
    page++
    // Первая страница ничьим разрывом не открыта: разрыв, за которым она оказалась,
    // стоит выше всего содержимого и не делит ничего.
    if (openedBy !== null && page > 1) out.set(openedBy, page)
  }
  for (const b of blocks) {
    if (b.type === 'page_break') {
      closeSegment()
      openedBy = b.id
      filled = false
      continue
    }
    filled = true
  }
  closeSegment()
  return out
}

// Ряд — это КОЛОНКИ, а колонка — стопка элементов. Полноширинный ряд = одна колонка с
// одним элементом; СЕКЦИЯ = две непустые колонки, в каждой сколько угодно элементов.
export type Row<T> = T[][]

// Ядро упаковки (спека §11.3) — автомат по потоку с одним состоянием: «открытая
// секция». Три состояния бита:
//
//   бита нет     → секция закрывается, элемент во всю ширину;
//   бит 'left'   → в левую колонку; секции нет — открываю;
//   бит 'right'  → в правую колонку; секции нет — открываю, ЗАБРАВ предыдущий
//                  полноширинный элемент в левую колонку.
//
// «Забрать предыдущего» — не костыль совместимости, а нужный жест: «поставь этот блок
// справа от того» не должно требовать сначала помечать левый. Так же читаются формы,
// собранные до этапа: у них левая колонка неявная. Забирать некого (элемент первый,
// пара недопустима) → бит инертен, но НЕ невалиден: кросс-блочное условие не
// валидируется ни в Zod, ни в Go, иначе undo и промежуточные состояния драга ловили бы
// 422. Инертный бит убирает стор (normalizeColumns), а не валидатор.
//
// СЕКЦИИ С ПУСТОЙ КОЛОНКОЙ НЕ БЫВАЕТ: одинокий 'left' даёт ряд из одной колонки, то
// есть ту же полную ширину, и его бит стор снимет как инертный. Инвариант «дыр нет»
// тот же, что был у бита первого элемента.
//
// Порядок документа неприкосновенен: конкатенация колонок равна исходному списку, а
// значит и порядок DOM, Tab и чтения скринридером. Колоночный порядок внутри секции
// (вся левая, затем вся правая) держит стор нормализацией — раскладчик принимает
// любой и в перестановку не вмешивается.
//
// Одно ядро на ТРИ слоя: блоки внутри группы (packGroupRows), группы (packRows) и
// варианты (packOptionRows). Допустимость пары спрашивается у canPair(левый, правый),
// а не у симметричного предиката: внутри вопроса пара направленная — слева подпись,
// справа поле. Левым для всей колонки остаётся тот, кто секцию открыл.
function packCells<T>(
  items: T[],
  bitOf: (i: T) => ColumnBit | undefined,
  canPair: (left: T, right: T) => boolean,
): Row<T>[] {
  const rows: Row<T>[] = []
  // Открытая секция — тот же массив, что лежит в rows: дописываем в него по месту.
  let section: Row<T> | null = null
  for (const item of items) {
    const bit = bitOf(item)
    if (bit === undefined) {
      section = null
      rows.push([[item]])
      continue
    }
    // 'left' ПОСЛЕ 'right' закрывает секцию и открывает новую. Канон внутри секции
    // колоночный (сперва вся левая колонка, потом вся правая), поэтому «левый после
    // правого» может значить только начало следующей секции. Без этого правила две
    // соседние секции в явной форме склеивались бы в одну — и у формы, собранной до
    // этапа, два ряда молча становились бы одной секцией 2+2 с другим выравниванием.
    if (section !== null && bit === COLUMN_LEFT && section[1] !== undefined) section = null
    if (section === null) {
      if (bit === COLUMN_LEFT) {
        section = [[item]]
        rows.push(section)
        continue
      }
      // 'right' без открытой секции: забрать предыдущий полноширинный элемент.
      const prev = rows[rows.length - 1]
      const prevSolo = prev?.length === 1 && prev[0]!.length === 1 ? prev[0]![0]! : undefined
      if (prevSolo === undefined || !canPair(prevSolo, item)) {
        rows.push([[item]]) // забирать некого → бит инертен
        continue
      }
      section = prev!
    }
    const opener = section[0]![0]!
    if (!canPair(opener, item)) {
      // Пара недопустима (внутри вопроса — не «подпись + поле»): секция закрывается,
      // элемент уходит своим рядом, бит инертен.
      section = null
      rows.push([[item]])
      continue
    }
    if (bit === COLUMN_LEFT) {
      section[0]!.push(item)
      continue
    }
    const right = section[1]
    if (right) right.push(item)
    else section.push([item])
  }
  return rows
}

// Носитель бита ряда задаётся МЕСТОМ блока в группе (v4, спека §6.2–6.3): на ПЕРВОМ
// блоке бит значит «моя группа встаёт справа от предыдущей», на любом другом —
// «встань справа от предыдущего блока в моей группе». Один ключ, один раскладчик,
// два уровня — не новая сущность, а снятие ограничения со старой.
type ColumnBit = typeof COLUMN_LEFT | typeof COLUMN_RIGHT
type RowCell = { type: BlockType; settings?: { column?: ColumnBit } }

const bitOfBlock = (b: RowCell | undefined): ColumnBit | undefined => b?.settings?.column

// Первый проход (§6.4): блоки ОДНОЙ группы в ряды. Пара тут узкая намеренно (§6.5):
// «подпись + поле ответа», и только в этом порядке. `text | image` бок о бок внутри
// вопроса — отдельное решение, вне скоупа фазы 15. Контент между подписью и полем
// ряд разрывает: он не подпись, парой быть не может, и поле за ним открывает свой ряд.
//
// Whitelist коротких контролов здесь не проверяется — его отменил владелец 2026-07-29
// (ADR §10): что читается в половину колонки, решает автор формы, а не раскладчик.
//
// Бит первого блока здесь безвреден по построению: первому элементу не к чему
// присоединяться (rows пуст), поэтому кросс-групповой носитель не может случайно
// собрать ряд внутри своей же группы.
export function packGroupRows<T extends RowCell>(blocks: T[]): Row<T>[] {
  return packCells(
    blocks,
    (b) => bitOfBlock(b),
    (left, right) => isCaptionType(left.type) && isAnswerableType(right.type),
  )
}

// Есть ли у группы внутренний ряд. Спрашивается раскладчиком, а не «по наличию бита
// у не первого блока»: инертный бит ряда не собирает и шириной группы не двигает.
export const groupHasInnerRow = (blocks: RowCell[]): boolean =>
  packGroupRows(blocks).some((row) => row.length > 1)

// Экспортируется: полотно редактора спрашивает тем же предикатом, кому светить зону
// жеста, — чтобы «кому можно в ряд» жило в одном месте с упаковкой.
//
// Условие ровно ОДНО (решение владельца 2026-07-29, ADR §10): группа с внутренним
// рядом занимает всю ширину и в кросс-групповой ряд не встаёт (§6.5) — иначе в одной
// строке оказались бы четыре ячейки и матрица правил, которую нельзя объяснить без
// туториала. Прежних двух условий больше нет: и whitelist коротких контролов, и
// требование «в группе есть отвечаемый блок» отменены. Второе ронял случай, о котором
// довод whitelist'а вообще не говорил: одинокий text/heading/image не мог встать в
// ряд ни с чем, хотя ширина ему не вредит.
//
// Заголовок формы сюда не попадает: он не в потоке вопросов и группой не бывает.
export const groupCanShareRow = (blocks: RowCell[]): boolean => !groupHasInnerRow(blocks)

// Второй проход (§6.4): группы в ряды. Обёртка .rf-row достаётся только ряду из
// двоих, ряд из одного рендерится как раньше (лишний div не меняет вид, но шумит в
// DOM). Единый раскладчик всех трёх поверхностей — поверх groupBlocks.
export function packRows<T extends { blocks: RowCell[] }>(groups: T[]): Row<T>[] {
  return packCells(
    groups,
    (g) => bitOfBlock(g.blocks[0]),
    (l, r) => groupCanPair(l.blocks) && groupCanPair(r.blocks),
  )
}

// groupCanPair — МОЖЕТ ЛИ ГРУППА СТОЯТЬ В ЯЧЕЙКЕ РЯДА. Два условия: разрешает ли делить
// ряд её ТИП (contract.ts, зеркало canShareRow в Go) и нет ли у неё внутреннего ряда
// (§6.5).
//
// Экспортируется, и это важнее, чем кажется: тем же предикатом обязаны спрашивать ВСЕ
// три стороны — раскладчик (здесь), команда (`placeInRow`) и приглашение жеста
// (`inviteRowId`, `rowPosition`, `rowCandidate` полотна). До фазы 19 типовое условие
// проверяла только команда, а приглашение обходилось `groupCanShareRow`: разойтись они
// не могли, потому что единственный тип с `canShareRow: false` — заголовок формы — в
// раскладку вообще не попадает (стор вырезает его `rowGroups`). Разрыв страницы стал
// вторым таким типом, и вырезать его нельзя: он ГРАНИЦА и обязан закрывать секцию, иначе
// секция склеится через него и разъедется на две страницы. От этого приглашение начало
// обещать ряд, которого команда не сделает, — жест, молча не делающий ничего (найдено
// ревью фазы 19).
//
// Типовое условие нужно и самому раскладчику: правило «'right' забирает предыдущий
// полноширинный элемент» (packCells) иначе утащило бы разрыв в левую колонку — а такого
// документа схема не принимает, и автор получил бы 422 на автосейве формы, которую даже
// не правил.
export const groupCanPair = (blocks: RowCell[]): boolean =>
  canShareRow(blocks[0]!.type) && groupCanShareRow(blocks)

// Упаковка вариантов в ряды (спека §5.1) — тот же бит, тот же раскладчик. Whitelist
// здесь не нужен: карточка варианта делит ряд всегда (потолок ширины у неё тот же,
// что у короткого поля), поэтому пара допустима всегда. У опций dropdown флаг инертен
// по другой причине: список живёт в нативном select и рядов не имеет вовсе.
export function packOptionRows<T extends { column?: ColumnBit }>(options: T[]): Row<T>[] {
  return packCells(
    options,
    (o) => o.column,
    () => true,
  )
}

export function groupMeta(blocks: Block[]): Map<string, GroupMeta> {
  const meta = new Map<string, GroupMeta>()
  const hasTitle = new Set<string>()
  const get = (g: string): GroupMeta => {
    let m = meta.get(g)
    if (!m) {
      m = { caption: '', required: false }
      meta.set(g, m)
    }
    return m
  }
  for (const b of blocks) {
    const m = get(b.groupId)
    // Подпись группы уходит в aria-label контрола и в тизеры — то есть в текст, а не в
    // разметку (фаза 14). Богатый заголовок вопроса РИСУЕТ ContentBlock из спанов; здесь
    // нужна плоская строка.
    const flat = plainText(b.text)
    const text = flat.trim()
    if (b.type === 'title') {
      if (text && !hasTitle.has(b.groupId)) {
        m.caption = flat
        hasTitle.add(b.groupId)
      }
    } else if (b.type === 'label') {
      if (text && !hasTitle.has(b.groupId) && !m.caption) {
        m.caption = flat
      }
    } else if (isAnswerableType(b.type)) {
      if (b.required) m.required = true
    }
  }
  return meta
}
