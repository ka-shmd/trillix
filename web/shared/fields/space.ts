import { type BlockType } from '@entities/blocks/contract'

// ВОЗДУХ ПЕРЕД ВОПРОСОМ — СВОЙСТВО ТИПА ЕГО ПЕРВОГО БЛОКА (решение владельца 2026-08-22).
//
// Базовый вертикальный шаг полотна один и тот же везде — 12px (.rf-form/.rf-group в
// fields.css). Типы, которые НАЧИНАЮТ смысловой кусок, берут вместо него своё число:
// заголовок раздела отбивается сильнее вопроса, вопрос — сильнее блоков внутри себя.
//
// Числа приведены в fields.css (классы .rf-space-*) и в утилитах полотна редактора
// (SPACE_MT в GroupRow) — здесь только КОМУ какая ступень положена, потому что этот
// вопрос у трёх поверхностей обязан иметь один ответ. Считать его от ПЕРВОГО блока
// вопроса, а не от каждого блока, — следствие устройства: интервал несёт обёртка
// вопроса (.rf-group), заголовок всегда стоит в своей группе один, подпись — всегда
// первая в своей.
//
// Record<BlockType, …> без Partial и без дефолта — по тому же доводу, что у реестров
// типов (entities/blocks/index.ts): новый тип обязан назвать свою ступень, а не
// унаследовать соседнюю молча.
export type SpaceStep = 'base' | 'q' | 'h1' | 'h2' | 'h3' | 'pb'

const SPACE: Record<BlockType, SpaceStep> = {
  short_text: 'base',
  long_text: 'base',
  email: 'base',
  phone: 'base',
  number: 'base',
  scale: 'base',
  rating: 'base',
  single_choice: 'base',
  dropdown: 'base',
  multi_choice: 'base',
  multi_select: 'base',
  date: 'base',
  file: 'base',
  slot: 'base',
  // Подписи открывают вопрос — воздух перед ними и есть воздух между вопросами.
  // Голое поле без подписи остаётся на базовом шаге: отбивать нечего, вопрос
  // начинается там же, где кончился предыдущий.
  title: 'q',
  label: 'q',
  heading: 'h1',
  heading_2: 'h2',
  heading_3: 'h3',
  text: 'base',
  image: 'base',
  // Разрыв страницы у респондента не рисуется вовсе (его потребляет splitPages), но на
  // полотне он разделитель, и воздух ему нужен с ОБЕИХ сторон — по 48px (решение
  // владельца 2026-08-22). Обе стороны — СВОИ: нижнюю даёт единственный на полотне
  // отступ снизу (rowSpaceBelow в builder/space.ts), а сосед под разрывом свой верхний
  // интервал сохраняет и добавляет сверху.
  page_break: 'pb',
  // Условие респонденту не показывается вовсе, свой воздух ему не нужен; заголовок формы
  // стоит ВНЕ .rf-form и живёт по своему интервалу (48px).
  logic: 'base',
  form_title: 'base',
}

// Ступень вопроса — по его первому блоку. Пустая группа невозможна (её заводит
// раскладчик из непустого списка), но сигнатура принимает список, а не тип: у
// вызывающих на руках именно группа.
export function groupSpace(blocks: { type: BlockType }[]): SpaceStep {
  const first = blocks[0]
  return first ? SPACE[first.type] : 'base'
}

// Класс для поверхностей, носящих rf-* (превью и рендерер). У базовой ступени класса
// нет: её интервал даёт общее правило ритма, и лишний класс в разметке значил бы, что
// правил два. Полотно редактора класс не носит (оно не внутри .rf-form) — там та же
// ступень разворачивается в утилиту Tailwind.
export function spaceClass(step: SpaceStep): string {
  // 'pb' класса не получает: разрыв страницы у респондента не рисуется ни на одной
  // поверхности (splitPages режет по нему форму), и правило .rf-space-pb в fields.css
  // было бы мёртвым. Его воздух — целиком дело полотна.
  return step === 'base' || step === 'pb' ? '' : ` rf-space-${step}`
}

// Готовый className обёртки вопроса — чтобы три поверхности собирали его одинаково.
export function groupClass(blocks: { type: BlockType }[]): string {
  return `rf-group${spaceClass(groupSpace(blocks))}`
}
