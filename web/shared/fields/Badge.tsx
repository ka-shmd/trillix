// БЕЙДЖ «Сделано в Trillix» — белая кнопка со знаком площадки и синим текстом,
// стоящая в одной строке с кнопкой отправки (решение владельца 2026-08-28).
//
// ЖИВЁТ В @fields, а не в рендерере, потому что поверхностей у него ДВЕ: публичная
// форма и превью билдера. Первая редакция стояла только в рендерере — и превью, чья
// единственная задача показать форму глазами респондента, молча врало: автор не видел
// бейджа, который на опубликованной форме есть.
//
// Показывать или нет, решает НЕ компонент: у респондента — сервер (поле showBadge в
// ответе), у автора — то же правило по его тарифу (showFormBadge в design.ts).
// Компонент об этом не знает — иначе решение оказалось бы в трёх местах.
//
// Стоит и на форме, и на экранах «Спасибо»/«приём закрыт»: иначе бейдж снимается
// разглядыванием второго экрана. На форме он лежит внутри .rf-nav, на этих двух
// экранах — сам по себе; вид один, место разное (см. .rf-badge в fields.css).
//
// Белый и синий — ФИКСИРОВАННЫЕ, мимо палитры автора: бейдж про площадку, а не про
// форму, и на форме с зелёным акцентом обязан остаться синим.
//
// ЗНАК — общий favicon площадки: свой знак бейджа ещё рисуется, до него стоит
// дефолтный. Файл обязан лежать в public/ у ОБЕИХ поверхностей (web/renderer и
// web/app) — путь корневой, и оба приложения отдают его сами.
//
// target="_blank" — респондент посреди заполнения не должен терять форму; rel к нему
// обязателен: без noopener открытая вкладка получает ссылку на нашу через
// window.opener.
export function Badge() {
  return (
    <p className="rf-badge">
      <a href="https://trillix.ru" target="_blank" rel="noopener noreferrer">
        <img className="rf-badge-mark" src="/favicon.svg" alt="" width={16} height={16} />
        Сделано в Trillix
      </a>
    </p>
  )
}
