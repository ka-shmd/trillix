import { ApiError } from '../../shared/api/errors'

// Текст отказа приглашения. Отдельным модулем, а не рядом с диалогом: его зовут
// оба входа — диалог приглашения и «Отправить снова» в строке приглашённого, — и
// два разных текста на один отказ были бы двумя разными обещаниями.
//
// Ветвимся по code, а не по тексту (web/CLAUDE.md): у каждого отказа свой совет
// человеку, и общее «что-то пошло не так» здесь бесполезно.
export function inviteErrorText(error: unknown): string {
  if (!(error instanceof ApiError)) return 'Не удалось отправить приглашение.'
  switch (error.code) {
    case 'conflict':
      return 'Этот человек уже в пространстве.'
    case 'plan_required':
      return 'На текущем тарифе больше участников пригласить нельзя.'
    case 'validation_failed':
      return 'Проверьте адрес почты.'
    case 'forbidden':
      return 'Приглашать может только владелец пространства.'
    case 'rate_limited':
      return 'Слишком много приглашений подряд. Попробуйте через пару минут.'
    default:
      return 'Не удалось отправить приглашение.'
  }
}
