// Знаки сервисов интеграций. Внешний источник в проде режет CSP
// (`default-src 'self'`), поэтому оба знака едут из сборки.
//
// Фирменный логотип рисуем инлайн-SVG: каталог узнаётся по нему, серый глиф
// lucide этого не даёт, а рисовать чужой логотип больше нечем — правило
// «интерфейс кабинета только из shadcn» на знак не распространяется. Там же, где
// у знака есть ОБЩЕПРИНЯТЫЙ вид и своего бренда нет (вебхук), берём готовый глиф:
// рисовать общее место заново незачем.

import { Webhook } from 'lucide-react'

import { cn } from '@/lib/utils'

// Google Таблицы: зелёный лист с загнутым углом и белой таблицей внутри.
export function GoogleSheetsIcon({ className }: { className?: string }) {
  return (
    <svg viewBox="0 0 24 24" className={className} role="img" aria-label="Google Таблицы">
      <path d="M14 2H7a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h10a2 2 0 0 0 2-2V7l-5-5Z" fill="#0F9D58" />
      {/* Загнутый угол — та же фигура, но темнее: без него лист читается просто
          зелёным прямоугольником. */}
      <path d="M14 2v5h5l-5-5Z" fill="#0B8043" />
      <rect x="8" y="10.5" width="8" height="7" rx="0.4" fill="#fff" />
      <path d="M12 10.5v7M8 12.9h8M8 15.2h8" stroke="#0F9D58" strokeWidth="0.9" />
    </svg>
  )
}

// Вебхук — не сервис, своего бренда у него нет, но есть общепринятый знак: три
// дуги, сходящиеся в петлю (он же у webhooks.fyi и в наборах иконок). Берём его
// из lucide, а не рисуем свой: предметная картинка «запрос уходит из формы»
// узнавалась бы хуже общего места.
//
// Цвет — токеном действия (`--primary`), а не литералом: у знака нет своего
// бренда, и в тёмной теме он обязан жить.
export function WebhookIcon({ className }: { className?: string }) {
  return <Webhook className={cn('text-primary', className)} role="img" aria-label="Вебхук" />
}
