import { type Block, isAnswerableType, plainText } from '@entities/formSchema'
import { groupMeta } from '@fields/groups'

// Колонки таблицы ответов: по одной на отвечаемый блок ТЕКУЩЕЙ схемы формы.
// Неотвечаемые блоки (подписи, контент, разрывы) ответов не собирают и колонок не
// получают — то же правило, по которому они исключены из CSV на бэкенде.
//
// Один список на таблицу и на панель одного ответа: разъедься они, владелец увидел
// бы у колонки одну подпись, а у той же строки в открытом ответе — другую.
export type AnswerColumn = { block: Block; label: string }

export function answerColumns(blocks: Block[]): AnswerColumn[] {
  // Подпись берётся из ГРУППЫ блока (заголовок вопроса), поэтому meta считается по
  // всем блокам, а колонки — только по отвечаемым.
  const groups = groupMeta(blocks)
  return blocks
    .filter((b) => isAnswerableType(b.type))
    .map((b) => ({ block: b, label: blockTitle(b, groups.get(b.groupId)?.caption) }))
}

// Как вопрос подписан в кабинете. Имя вопроса (фаза 16, ADR §10) стоит первым — той
// же ступенью, что в domain.questionLabel: колонка выгрузки и колонка этой таблицы
// обязаны называть вопрос ОДИНАКОВО. Разошедшись, два экрана одного кабинета
// показывали бы владельцу разные формы — ровно то, о чём предупреждает ANALYTICS.md.
//
// Последней ступени («Тип N») здесь нет: она требует нумерации вопросов по всем
// версиям формы, которой у экрана нет, — вместо неё честное «(без названия)».
function blockTitle(b: Block, caption?: string): string {
  return (
    (b.name ?? '').trim() ||
    (caption ?? '').trim() ||
    plainText(b.text).trim() ||
    (b.settings?.placeholder ?? '').trim() ||
    '(без названия)'
  )
}

// Колонка «Версия» показывается, только когда версии загруженных строк РАЗНЫЕ.
// Тем же правилом, что бейдж статуса формы (docs/DESIGN-SYSTEM.md §7): подпись
// вешается на отклонение, а не на норму. У формы, которую ни разу не переиздавали,
// столбец одинаковых чисел отнимает место у вопросов и не сообщает ничего.
//
// Считается по УЖЕ ЗАГРУЖЕННЫМ строкам, поэтому колонка может появиться после
// «Показать ещё»: это честно — до подгрузки различия действительно не было видно.
export function versionsDiffer(rows: readonly { formVersion: number }[]): boolean {
  return rows.length > 1 && rows.some((r) => r.formVersion !== rows[0]!.formVersion)
}
