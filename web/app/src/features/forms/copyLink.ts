import { toast } from 'sonner'

import { publicFormUrl } from './publicUrl'

// Копирование публичной ссылки на форму. Одна точка на два входа — значок в
// верхнем баре и пункт меню действий: разъедься они, человек получил бы разный
// адрес в зависимости от того, откуда копировал.
//
// У ЧЕРНОВИКА ССЫЛКИ НЕТ — публичной страницы у него не существует, и оба входа
// обязаны быть выключены. Проверку делает вызывающий: здесь нет статуса формы, а
// молча копировать адрес, ведущий на 404, хуже, чем не дать нажать.
export function copyFormLink(slug: string): void {
  navigator.clipboard
    .writeText(publicFormUrl(slug))
    .then(() => toast.success('Ссылка на форму скопирована'))
    .catch(() => toast.error('Не удалось скопировать — откройте «Поделиться»'))
}
