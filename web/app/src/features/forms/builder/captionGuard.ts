import { useCallback } from 'react'
import { toast } from 'sonner'

import { captionLoss } from './store'
import { useBuilderStoreApi } from './storeContext'
import type { FocusEngine } from './focusEngine'

// Цена свободы строки ответа, названная вслух (§4.3 спеки фазы 15). Полотно больше
// не мешает автору увести поле из вопроса, уронить чужое между подписью и полем или
// удалить подпись — но каждая такая правка молча переименовывала колонку CSV и шаг
// воронки (заголовок достаётся ближайшему снизу полю, прежнее остаётся голым).
// Ответы при этом целы всегда: они ключуются id отвечаемого блока.
//
// Кто что делает: считает потерю чистая функция стора (captionLoss), показывает —
// полотно. Стор о тостах не знает, поэтому обёртка живёт здесь, а не в командах.

// Длинный заголовок в тост не влезает и вытесняет саму мысль — режем с многоточием.
const MAX_CAPTION = 40

const short = (s: string): string => (s.length > MAX_CAPTION ? `${s.slice(0, MAX_CAPTION)}…` : s)

// useCaptionGuard — обёртка структурной команды: выполняет её и, если после неё у
// живого поля не осталось заголовка, называет вопрос-жертву тостом с отменой.
// Возвращаемая функция синхронна: команды стора применяются немедленно (set внутри
// commit), поэтому «до» и «после» читаются вокруг вызова без всякого ожидания.
//
// Отмена делает ровно то же, что Mod+Z: один шаг истории (правка — один commit) и
// каретка на первый затронутый откатом блок — иначе кнопка тоста и клавиша расходятся
// в поведении на одном и том же действии.
export function useCaptionGuard(engine: FocusEngine): (run: () => void) => void {
  const store = useBuilderStoreApi()
  return useCallback(
    (run: () => void) => {
      const before = store.getState().blocks
      run()
      const after = store.getState()
      const lost = captionLoss(before, after.blocks)
      if (lost.length === 0) return
      // Глубина истории сразу после операции. undo снимает ВЕРШИНУ стека, а не «свой»
      // шаг: тост живёт несколько секунд, и за это время автор успевает набрать текст
      // в уехавшей строке — тогда кнопка откатила бы набор, а заголовок так и не
      // вернула. Поэтому кнопка работает, только пока её шаг остаётся вершиной;
      // дальше она честно говорит, что уже не поможет, вместо тихой чужой отмены.
      const depth = after.past.length
      toast(
        lost.length === 1
          ? `Вопрос «${short(lost[0]!.caption)}» остался без заголовка`
          : 'Несколько вопросов остались без заголовка',
        {
          description: 'Ответы на них целы, но в выгрузке и воронке имени у них больше нет',
          action: {
            label: 'Отменить',
            onClick: () => {
              if (store.getState().past.length !== depth) {
                toast('После этой правки были другие — отменяйте их по очереди (Ctrl+Z)')
                return
              }
              const id = store.getState().undo()
              if (id) engine.focusBlock(id)
            },
          },
        },
      )
    },
    [store, engine],
  )
}
