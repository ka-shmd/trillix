import { describe, expect, it } from 'vitest'

import { COVER_Y_MAX, COVER_Y_MIN } from '@entities/formSchema'

import { coverOverflowPx, nextCoverY } from './coverDrag'

// Математика жеста «изменить положение». Проверяется отдельно от компонента, потому
// что ошибиться здесь можно ровно в трёх местах — знак, масштаб и края, — и все три
// на глаз выглядят как «перетаскивание работает как-то не так». Масштаб уже ошибался
// один раз (найдено владельцем 2026-08-02): ход брался от высоты полосы, и картинка
// уезжала кратно быстрее курсора — тем сильнее, чем выше снимок.

describe('coverOverflowPx', () => {
  // Полоса 900×220, снимок 2000×3000 → в ширину полосы он ляжет как 900×1350,
  // значит поверх полосы остаётся 1130 px хода.
  it('высокий снимок перерастает полосу на разницу высот', () => {
    expect(coverOverflowPx(2000, 3000, 900, 220)).toBe(1130)
  })

  it('обычное фото 3:2 даёт ход поменьше', () => {
    expect(coverOverflowPx(2000, 1333, 900, 220)).toBeCloseTo(379.85, 1)
  })

  // Панорама ниже полосы: cover растянет её по ВЫСОТЕ, и вертикального хода нет.
  it('широкая панорама хода не даёт', () => {
    expect(coverOverflowPx(4000, 500, 900, 220)).toBe(0)
  })

  it('несмеренная полоса и незагруженная картинка дают нулевой ход', () => {
    expect(coverOverflowPx(0, 0, 900, 220)).toBe(0)
    expect(coverOverflowPx(2000, 3000, 0, 220)).toBe(0)
  })
})

describe('nextCoverY', () => {
  // Ход 200 px: процент стоит два пикселя курсора.
  const overflow = 200

  it('увод указателя вверх показывает нижнюю часть картинки (y растёт)', () => {
    expect(nextCoverY(50, 300, 200, overflow)).toBe(100)
  })

  it('увод вниз показывает верхнюю часть (y падает)', () => {
    expect(nextCoverY(50, 300, 400, overflow)).toBe(0)
  })

  // Главное свойство: пиксель курсора двигает картинку ровно на пиксель. Ход 1000 px,
  // курсор прошёл 100 — картинка обязана сдвинуться на те же 100, то есть на 10%.
  it('картинка едет ровно за курсором, а не быстрее', () => {
    expect(nextCoverY(0, 500, 400, 1000)).toBe(10)
    expect(nextCoverY(50, 500, 300, 1000)).toBe(70)
  })

  it('протяжка на весь ход проходит весь диапазон', () => {
    expect(nextCoverY(0, 300, 300 - overflow, overflow)).toBe(COVER_Y_MAX)
    expect(nextCoverY(COVER_Y_MAX, 300, 300 + overflow, overflow)).toBe(COVER_Y_MIN)
  })

  it('за края не выходит', () => {
    expect(nextCoverY(50, 300, -10_000, overflow)).toBe(COVER_Y_MAX)
    expect(nextCoverY(50, 300, 10_000, overflow)).toBe(COVER_Y_MIN)
  })

  it('без движения значение не меняется', () => {
    expect(nextCoverY(37, 300, 300, overflow)).toBe(37)
  })

  // Во время жеста значение ДРОБНОЕ — иначе на высоком снимке, где процент стоит
  // десяток пикселей, картинка дёргалась бы ступеньками. Целое берётся на отпускании
  // (Math.round в CoverEditor), потому что схема принимает только его.
  it('во время жеста значение не округляется', () => {
    expect(nextCoverY(0, 300, 293, 1000)).toBeCloseTo(0.7, 5)
  })

  // Нулевой ход (панорама или незагруженная картинка) — двигать нечего: делить на
  // это нельзя, а Math.round(Infinity) дал бы NaN и 422 из схемы.
  it('нулевой ход не ломает значение', () => {
    expect(nextCoverY(42, 300, 100, 0)).toBe(42)
  })
})
