// Вид контролов блока условия — ОДНА строка классов на оба яруса (решение владельца
// 2026-09-09): «Когда» и «Тогда» читаются как один блок, и разъехавшаяся на пиксель
// плотность видна сразу. Файл заведён потому, что константа жила в двух копиях —
// в ConditionEditor и в LogicBlockEditor, — а копия правится в одной из двух.
//
// Что здесь есть и почему именно так:
//
//   • `bg-muted` — серая подложка вместо прозрачной у shadcn; рамка контролам остаётся
//     (дизайн-система: плоскость у групп, рамка у полей ввода);
//   • `px-2` — падинг ОДИН у всех: у селектов, у поля значения и у его шеврона. Три
//     разных отступа в одной строке видны как небрежность, даже когда каждый по
//     отдельности хорош;
//   • `data-[size=sm]:h-7` — ВЫСОТА, и это МИНА. `SelectTrigger` задаёт свою высоту
//     вариантом (`data-[size=sm]:h-8`), а плоский `h-7` рядом её не перебивает: разные
//     ключи, tailwind-merge их не сливает, а в собранном CSS у селектора с атрибутом
//     специфичность выше. Селекты из-за этого стояли 32px против 28px у поля значения —
//     ровно то, что видно глазом как «строка выше соседней». Правило общее для всех
//     вендоренных компонентов (`web/CLAUDE.md`, `docs/DESIGN-SYSTEM.md`): размер
//     правится ТЕМ ЖЕ вариантом, каким задан. Здесь же — `data-[size=sm]:py-0`;
//   • `py-0` — вертикального падинга нет НИ У КОГО. Высоту держит `h-7`, а `py-2`,
//     который shadcn ставит триггеру, при этой высоте оставляет тексту 10px рабочей
//     области: строка в него не влезает и живёт переполнением. У поля значения своего
//     `py` не было изначально — оно и есть образец, по которому выровнены остальные;
//   • `font-medium` — текст контролов толще обычного: он состоит из имён вопросов и
//     названий действий, то есть из ссылок, а не из прозы.
//
// ⚠ Заливка объявлена ТЕМ ЖЕ вариантом, что перебиваемое (`dark:bg-muted` против
// `dark:bg-input/30` у SelectTrigger): иначе tailwind-merge их не сольёт и победит
// порядок в собранном CSS, а не строка className (web/CLAUDE.md). У кнопки падинг
// задан вариантом `has-[>svg]:px-*` — там его тем же вариантом и перебивают.
export const FILL =
  'bg-muted px-2 py-0 font-medium data-[size=sm]:h-7 data-[size=sm]:py-0 dark:bg-muted'

// Многоточие в конце значения — тремя классами разом, и все три объявлены вариантом
// `*:data-[slot=select-value]:`, каким объявлено перебиваемое: `block` перебивает флекс
// слота (на флекс-контейнере `text-overflow` не действует вовсе, и текст режется посреди
// буквы), `min-w-0` разрешает флекс-элементу сжаться, `truncate` ставит саму обрезку.
export const TRUNCATE =
  '*:data-[slot=select-value]:block *:data-[slot=select-value]:min-w-0 *:data-[slot=select-value]:truncate'

// Контрол, чьё значение НЕ голый текст, а «значок + имя» (GlyphName у источника,
// ActionName у действия): флекс слота не перебивается — на нём держится просвет
// значок→имя, — многоточие ставит сам компонент, а слоту достаётся один `min-w-0`.
export const GLYPH_VALUE = '*:data-[slot=select-value]:min-w-0'
