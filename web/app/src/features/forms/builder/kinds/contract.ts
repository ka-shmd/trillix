import { type ReactNode } from 'react'

import { type Block } from '@entities/formSchema'

// Контракт файла типа в РЕДАКТОРЕ (фаза 16, этап 16.1в). Третий и последний слой среза:
// контракт живёт в @entities/blocks, вид у респондента — в @fields/kinds, а здесь то, что
// знает только полотно.
//
// Граница та же, что и в остальных слоях: здесь СВОЙСТВА типа. Отношения блоков
// (regroup, ряды, планирование дропа, контракт фокуса, карта клавиш) остаются в общем
// коде — правило про двух участников, уехавшее в файл одного из них, расходится
// половинами и молча.

// Поверхность строки — чем автор правит блок на полотне:
//   • 'text'        — редактируемая строка текста (подписи, контент, согласие);
//   • 'placeholder' — инпут плейсхолдера (текстовые поля);
//   • 'choice'      — список инпутов вариантов;
//   • 'object'      — объектная остановка: фокусируемая строка с кольцом (картинка,
//                     дата, шкала — у них нет своего текста).
// От поверхности зависит клавиатурный поток строки, поэтому это свойство типа, а не вид.
export type RowSurface = 'text' | 'placeholder' | 'choice' | 'object'

// Высота absolute-кластера значков = line-height ПЕРВОЙ строки блока: вопрос и заголовок
// раздела — 28px (h-7), остальное — 24px (h-6). Жёсткое значение здесь баг: кластер
// повиснет ниже строки. Меняется вместе с line-height в fields.css.
type LineHeight = 'h-6' | 'h-7'

// Контрол объектной остановки — что стоит внутри фокусируемой строки-объекта (картинка,
// шкала, превью даты). Компонент, а не строковый признак: строковый признак пришлось бы
// разворачивать в JSX через ветвление в BlockRow, то есть оставить там ту же карту
// «тип → контрол», которую этап и уносит в файлы типов.
export type ObjectControl = (props: { block: Block; formId: string }) => ReactNode

// Факты о строке типа на полотне. РАЗДЕЛЁННОЕ объединение, а не общий мешок: имя строки и
// классы текста есть только у текстовой поверхности, и требовать их от шкалы значило бы
// заставить выдумать данные, которых у типа нет, — а выдуманное поле однажды кто-нибудь
// прочитает.
export type RowFacts =
  | {
      surface: 'text'
      // Как строка называется — для скринридера и для e2e. null означает «имя берётся из
      // ПОЗИЦИОННОЙ подсказки»: у абзаца оно зависит от места (первая строка формы,
      // строка внутри вопроса), то есть это отношение, а не свойство типа.
      name: string | null
      // Классы редактируемой строки — только rf-* из fields.css. Начертание ПОДСКАЗКИ
      // сюда не пишется: утилита `placeholder:*` разворачивается в `::placeholder`,
      // которого у contenteditable нет, — вид подсказки живёт в richLine.css.
      className: string
      lineH: LineHeight
      // Текст типа набирается ЖИРНЫМ: первый символ в пустой строке рождается с маркой
      // `b` (RichLine, applyDefaultMarks). Не вид — вид держит fields.css; это про то,
      // каким текст ПОЯВЛЯЕТСЯ в документе, потому что с 2026-08-15 жирность заголовков
      // и подписей лежит в документе, а не в весе поверхности. Поле обязательное, хотя
      // «нет» — самый частый ответ: забытый новый тип заголовка молча набирался бы
      // обычным, и заметил бы это автор, а не компилятор.
      bold: boolean
      // Подсказка-плейсхолдер видна только под фокусом (абзац): пустая строка у него —
      // законное состояние документа, мигающее ИМЯ строки скринридеру не нужно, а
      // видимая подсказка нужна, но лишь когда каретка здесь.
      placeholderOnFocusOnly?: boolean
      // Глиф слева от текста: у согласия строка вопроса и есть текст согласия, поэтому
      // галочка стоит вплотную к нему — отдельного превью-контрола у типа нет.
      mark?: 'check'
    }
  | {
      surface: 'placeholder'
      lineH: LineHeight
      // Плейсхолдер правится многострочно (длинный ответ): и поверхность textarea, и
      // положение глифа типа — следствия одного факта.
      multiline?: boolean
    }
  | {
      surface: 'choice'
      lineH: LineHeight
      // Варианты умеют вставать в ряд (спека §5.1). У dropdown рядов нет: список живёт в
      // нативном select, и жест Mod+Alt+→ на варианте уходит ВОПРОСУ, а не варианту.
      optionRows: boolean
    }
  | {
      surface: 'object'
      lineH: LineHeight
      Control: ObjectControl
      // Контекст карты клавиш (§7): у картинки Mod+Enter открывает файловый диалог, у
      // даты и шкалы открывать нечего. Это разные контексты подсказок, а не один
      // «объект», — иначе шпаргалка обещала бы клавишу, которой нет.
      hint: 'image' | 'object'
    }

// Типовой раздел попапа настроек — то, чего на полотне показать нельзя (§4.7 спеки):
// диапазон шкалы сегодня, min/max числа и alt картинки — когда попросят. Полотно остаётся
// WYSIWYG: на нём видно ровно то, что увидит респондент.
//
// Компонент, а не описание полей для генератора (§3.5 спеки). Генератор пришлось бы
// расширять под каждый новый тип, и он всегда был бы на шаг позади: диапазон шкалы — не два
// независимых select, а пара со связью min < max; картинке нужен асинхронный аплоад. JSX сам
// по себе декларация — только типизированная и без интерпретатора, а экономию даёт набор
// готовых строк-настроек (settings.tsx).
export type SettingsSection = (props: { block: Block }) => ReactNode

export interface EditorKind {
  // В каких разделах меню вставки стоит тип. Разделы: «Вопросы» (бандл подпись+поле),
  // «Отдельные поля» (голое поле), «Лэйаут» (подписи и контент).
  menu: { question: boolean; field: boolean; layout: boolean }
  label: string
  description: string
  icon: ReactNode
  // Дефолты нового блока поверх скелета (id/groupId/пустой текст/пустые настройки).
  // Отсутствуют — тип создаётся скелетом как есть.
  defaults?: Partial<Block>
  // Факты о строке на полотне. null — у типа СВОЯ строка, и BlockRow его не рисует
  // (заголовок формы: он вне потока вопросов, у него FormTitleRow).
  row: RowFacts | null
  // Типовой раздел попапа настроек. Отсутствует — разделу неоткуда взяться, и попап
  // показывает одни общие пункты (разделителя тоже нет). Это не забытое поле: у
  // большинства типов правится только то, что видно на полотне.
  Settings?: SettingsSection
}
