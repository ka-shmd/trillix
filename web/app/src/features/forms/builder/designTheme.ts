import type { FormDesign } from '@entities/formSchema'

import { patchTop } from './designEdit'

// Выбор темы в шторке «Оформление» — отдельным модулем, а не внутри компонента,
// ровно чтобы это можно было проверить тестом: Radix Select в happy-dom не
// открывается вовсе (известная граница, STATUS.md), поэтому через разметку эта
// логика непокрываема, а тонкостей в ней хватает.

// ТРИ ТЕМЫ В ПАНЕЛИ, НО ДВЕ В СХЕМЕ (решение владельца 2026-08-09).
//
// «Пользовательская» — не третье значение поля `theme`, а ВЫВОД: она означает «у
// формы есть мои собственные настройки», и узнаётся по их наличию. Хранить её
// отдельным значением нельзя, не заведя рядом второе поле под базу: форма с тёмным
// холстом и своим акцентом — это тёмная база плюс правки, и `theme: 'custom'`
// потерял бы, от чего именно эти правки считаются. Тогда один подобранный акцент
// перекидывал бы форму со тёмного фона на светлый.
//
// Из вывода следует и то, чего просил владелец, без единой строки на «автоматически
// поставить пользовательскую»: любая правка цвета, шрифта или лэйаута сама делает
// её текущей, потому что настройка появилась в документе.
export type ThemeChoice = 'light' | 'dark' | 'custom'

// Ключи, наличие которых и делает оформление пользовательским. `theme` не в счёт —
// он и есть база, поверх которой всё остальное.
//
// `css` сюда НЕ входит, и по той же причине, по которой переживает сброс: это не про
// вид темы. Форма с парой правил CSS остаётся «Светлой» — иначе дропдаун показывал бы
// «Пользовательскую» автору, который цветов не касался вовсе.
const CUSTOM_KEYS = ['palette', 'font', 'layout', 'controls', 'button'] as const

export function hasCustomFields(design: FormDesign | undefined): boolean {
  if (!design) return false
  return CUSTOM_KEYS.some((k) => design[k] !== undefined)
}

// Ключи раздела «Дополнительно» — лэйаут, поля, кнопки. Отдельно от CUSTOM_KEYS:
// тот отвечает на «оформление стало пользовательским?» и считает заодно цвета со
// шрифтом, а этот — на «в платном разделе что-то задано?», и палитра со шрифтом,
// живущие выше разделителя, в него не входят.
const ADVANCED_KEYS = ['layout', 'controls', 'button'] as const

// hasAdvancedFields — есть ли в разделе «Дополнительно» хоть одно значение автора.
// По документу, а не по событию правки: предупреждение обязано стоять и у формы,
// которую открыли завтра, — иначе оно исчезало бы ровно у той формы, где уже
// накоплено то, что не опубликовать.
export function hasAdvancedFields(design: FormDesign | undefined): boolean {
  if (!design) return false
  return ADVANCED_KEYS.some((k) => design[k] !== undefined)
}

// currentTheme — что показывает дропдаун.
//
// Отсутствие темы и светлая тема — ОДНО состояние вида, и показывать их по-разному
// нельзя: форма, которой оформления не касались, выглядела бы «ничем не выбранной».
export function currentTheme(design: FormDesign | undefined): ThemeChoice {
  if (hasCustomFields(design)) return 'custom'
  return baseTheme(design)
}

// baseTheme — готовая тема, ПОВЕРХ которой лежат правки автора. От currentTheme
// отличается тем, что «пользовательской» здесь не бывает: своё оформление — это
// всегда светлая или тёмная база плюс правки (см. шапку файла), и цвет, которого
// автор не задавал, форма берёт у базы. Этим и пользуется панель, показывая в строке
// цвета не «по теме», а то, что нарисовано.
export function baseTheme(design: FormDesign | undefined): 'light' | 'dark' {
  return design?.theme === 'dark' ? 'dark' : 'light'
}

// resetToTheme — переход на одну из готовых тем. СБРАСЫВАЕТ все свои значения:
// именно поэтому панель спрашивает подтверждение, а не делает это молча.
//
// Светлая — это ОТСУТСТВИЕ ключа, а не theme: 'light'. Довод тот же, что у всей
// фазы: форма, у которой тему включили и выключили, обязана стать байт в байт
// прежней; сохранённое 'light' дало бы документ, отличающийся от исходного при
// одинаковом виде, и это расхождение живёт вечно.
//
// СВОЙ CSS ПЕРЕЖИВАЕТ СБРОС, и это не исключение из правила, а само правило: сброс
// возвращает к готовой теме ОФОРМЛЕНИЕ — цвета, шрифт, лэйаут, контролы и кнопки, то
// есть ровно то, что диалог и перечисляет. `css` — не оформление, а код автора, и
// терять его от смены темы значит стереть работу, которой в диалоге даже не обещано.
// Бейджа этот вопрос больше не касается: он не в документе (ADR §10).
//
// история — JOURNAL, «Бейдж переезжает в живую колонку»
export function resetToTheme(
  theme: 'light' | 'dark',
  design?: FormDesign | undefined,
): FormDesign | undefined {
  const kept: FormDesign = {}
  if (design?.css) kept.css = design.css
  if (theme === 'dark') kept.theme = 'dark'
  return Object.keys(kept).length === 0 ? undefined : kept
}

// dropPaid — снять из оформления РОВНО ТО, что не пускает форму в публикацию: платные
// группы, на которые у пространства нет права. Зовётся из диалога отказа, где автору
// предложены два выхода — оплатить или снять.
//
// СНИМАЕТСЯ ТОЛЬКО ЗАКРЫТОЕ, а не всё своё: у пространства может не быть права на CSS
// при живом праве на цвета, и «заодно» стёртая палитра была бы потерей работы, которой
// автору никто не обещал. Тема переживает всегда — обе бесплатны (BILLING §10).
//
// Схлопывание пустого — то же, что у patch: оформление, из которого сняли последнее
// значение, обязано исчезнуть целиком, а не остаться пустым объектом.
export function dropPaid(
  design: FormDesign | undefined,
  allowCustom: boolean,
  allowCSS: boolean,
): FormDesign | undefined {
  if (!design) return undefined
  const next: Record<string, unknown> = { ...design }
  if (!allowCustom) for (const key of CUSTOM_KEYS) delete next[key]
  if (!allowCSS) delete next.css
  return Object.keys(next).length === 0 ? undefined : (next as FormDesign)
}

// withTheme — смена базы БЕЗ сброса своих значений. Нужна там, где сбрасывать
// нечего (пользовательских настроек нет), и в этом случае совпадает с resetToTheme.
export function withTheme(
  design: FormDesign | undefined,
  theme: 'light' | 'dark',
): FormDesign | undefined {
  return patchTop(design, 'theme', theme === 'dark' ? 'dark' : undefined)
}
