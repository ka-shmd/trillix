// ПРОБА ЭТАПА 14.0. Один переключатель поверхности текстовой строки полотна.
//
// Константа, а не env-переменная: проба живёт на своей ветке и в поставку не идёт —
// её исход либо переезжает в контракт (этап 14.1), либо удаляется вместе с каталогом
// `spike/`. Переключатель нужен ровно для того, чтобы сравнить две поверхности на
// одном и том же полотне, не пересобирая ветку.
//
// **Чтобы посмотреть пробу в браузере — поставь `true`** и подними `make dev`.
//
// По умолчанию `false`, потому что восемь проверок `focusContract.test.tsx` ищут
// поверхность строки как `document.querySelector('textarea')` и на contenteditable
// падают на самом хелпере, не дойдя до поведения (переписываются этапом 14.3). Красный
// прогон на ветке нёс бы ровно ноль сведений сверх уже измеренного, поэтому набор
// остаётся зелёным, а новую поверхность включает себе сама проба
// (`richLine.test.tsx` подменяет этот модуль через `vi.mock`).
export const RICH_TEXT_SPIKE = false
