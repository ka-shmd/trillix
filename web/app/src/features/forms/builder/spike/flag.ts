//
// Константа, а не env-переменная: проба живёт на своей ветке и в поставку не идёт —
// её исход либо переезжает в контракт (этап 14.1), либо удаляется вместе с каталогом
// `spike/`. Переключатель нужен ровно для того, чтобы сравнить две поверхности на
// одном и том же полотне, не пересобирая ветку.
//
// **Он влияет ТОЛЬКО на браузер.** `true` — строка полотна на contenteditable,
// `false` — прежняя textarea; переключается на живую, `make dev` перезапускать не надо.
//
// На тесты не влияет вовсе, и это сделано нарочно: оба набора прибивают себе поверхность
// сами через `vi.mock` этого модуля — проба берёт `true` (`spike/richLine.test.tsx`),
// набор контракта фокуса `false` (`focusContract.test.tsx`, он написан под textarea и
// переписывается этапом 14.3). Иначе прогон краснел бы от того, в каком состоянии
// кто-то оставил эту строчку, — то есть от чужого рабочего дерева, а не от кода.
