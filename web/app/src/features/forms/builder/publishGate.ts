import { type Block } from '@entities/formSchema'

// Почему форму нельзя опубликовать прямо сейчас — списком человеческих фраз.
//
// ЗЕРКАЛО СЕРВЕРА, А НЕ ЗАМЕНА ЕМУ: те же два условия проверяет `forms.Publish`
// (`domain.SlotNeedsEmail` и пустой `scheduleId`), и решают они именно там —
// инвариант 3. Здесь они нужны затем, чтобы автор увидел причину ДО нажатия, а не
// получил 422 в тот момент, когда уже считает форму готовой.
//
// Разъехаться этим двум спискам нельзя: погашенная кнопка при живом сервере означает
// форму, которую нельзя опубликовать вообще ничем, а активная при отказе сервера
// возвращает нас к 422 на нажатии.

export type PublishBlocker = { id: 'schedule' | 'email'; text: string }

export function publishBlockers(blocks: Block[], scheduleId: string | null): PublishBlocker[] {
  if (!blocks.some((b) => b.type === 'slot')) return []
  const out: PublishBlocker[] = []
  if (!scheduleId) {
    out.push({ id: 'schedule', text: 'В блоке «Онлайн-запись» не выбрано расписание' })
  }
  // Вопрос о почте обязан быть ОБЯЗАТЕЛЬНЫМ: письмо о записи — единственный носитель
  // ссылки отмены, а необязательный вопрос респондент пропускает, и место остаётся
  // занятым до самого приёма.
  if (!blocks.some((b) => b.type === 'email' && b.required === true)) {
    out.push({
      id: 'email',
      text: 'Нужен обязательный вопрос «Email»: на него уйдёт подтверждение записи со ссылкой отмены',
    })
  }
  return out
}
