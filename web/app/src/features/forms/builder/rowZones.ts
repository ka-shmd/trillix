import { type Block } from '@entities/formSchema'
import { groupCanShareRow } from '@fields/groups'

// Правила приглашения «встань в ряд» — то, что решает, ГДЕ горит зона и КАК будет
// выглядеть результат. Вынесено из SlashEditor чистыми функциями: жест проверяется
// перетаскиванием мыши, а перетаскивание в vitest не воспроизводится, и оба правила
// молча ломались бы правкой соседнего кода.
//
// Устройство самого жеста — EDITOR.md §5.

// Группа полотна в терминах раскладчика: ряд — колонки, колонка — стопка групп.
type Group = { id: string; blocks: Block[] }
type Row = Group[][]

// inviteRowId — ряд, у которого горит приглашение, и его АДРЕС. Ряд РОВНО ОДИН:
// ближайший к перетаскиваемому элементу (решение владельца 2026-08-02). Прежде зоны
// зажигались у каждого ряда, способного принять элемент, то есть почти по всему
// полотну: приглашений было вдвое больше, чем вопросов, и ни одно не называло место,
// куда автор целится.
//
// Адрес — id первой группы ряда, КРОМЕ САМОГО ПЕРЕТАСКИВАЕМОГО. Тонкость не
// косметическая: адрес уезжает целью в `placeInRow`, а та первой же строкой выходит на
// `active === target`. Перенос между колонками своей же секции — обычный жест (элемент
// стоит слева, автор тянет его вправо), и с адресом «первая группа ряда» он молча
// становился бы no-op'ом: дублёр рисует результат, дроп не делает ничего.
//
// Два отказа, и оба про честность приглашения, а не про вкус:
//   • ряд из одного вопроса с внутренним рядом колонку не делит (§6.5) — placeInRow
//     такой дроп отвергнет, и зона обещала бы несбыточное;
//   • ряд, в котором стоит только сам перетаскиваемый вопрос, паре не с кем (адреса,
//     отличного от активного, в таком ряду просто нет).
export function inviteRowId(
  rows: Row[],
  nearGroupId: string | null,
  candidateGroupId: string | null,
): string | null {
  if (candidateGroupId === null || nearGroupId === null) return null
  const row = rows.find((r) => r.some((cell) => cell.some((g) => g.id === nearGroupId)))
  if (!row) return null
  if (row.length === 1 && !groupCanShareRow(row[0]![0]!.blocks)) return null
  return row.flat().find((g) => g.id !== candidateGroupId)?.id ?? null
}

// previewCells — раскладка ряда с ДУБЛЁРОМ: как ряд будет выглядеть, если элемент
// уронить в зону со стороны side. Повторяет placeInRow один в один, и это не
// дублирование правил, а их единственный видимый смысл: дублёр обязан показывать
// результат КОМАНДЫ, иначе он врёт убедительнее всякой линии.
//
//   • ряд из одной колонки → секция создаётся, и сторона зоны выбирает, в какую
//     колонку встанет активный, а какая достанется прежнему содержимому;
//   • ряд из двух колонок → активный дописывается в КОНЕЦ колонки-получателя
//     (placeInRow якорится за её последним элементом).
//
// Место дублёра помечено null: подставить туда узел — дело рендера.
export function previewCells(row: Row, side: 'left' | 'right'): (Group | null)[][] {
  if (row.length > 1) {
    const at = side === 'left' ? 0 : 1
    return row.map((cell, i) => (i === at ? [...cell, null] : cell))
  }
  return side === 'left' ? [[null], row[0]!] : [row[0]!, [null]]
}
