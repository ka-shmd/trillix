import { type Block } from '@entities/formSchema'
import { splitPagesWithClosers, splitThankYou } from '@fields/groups'

// КНОПКИ ШАГА НА ПОЛОТНЕ. Многостраничная форма даёт респонденту на каждой странице свою
// кнопку — «Далее» или отправку, — а полотно показывало ровно одну кнопку отправки под
// всем документом: автор не видел, что страница кончается «Далее», и узнавал это из
// превью или от людей.
//
// Кнопка у страницы ровно одна, и тип это отражает: ход назад в форме снят целиком
// (решение владельца 2026-08-22), «Назад» не существует ни на одной поверхности.
//
// Считается здесь, а не в разметке: правило простое на словах и раскидывалось по трём
// условиям в JSX, где его нельзя проверить тестом.
export type PageNav = {
  // Единственная кнопка страницы: 'next' — «Далее», 'submit' — отправка (последняя
  // страница ФОРМЫ; экран после отправки страницей формы не считается).
  kind: 'next' | 'submit'
}

export type PageNavPlan = {
  // Что стоит ПЕРЕД разрывом: разрыв закрывает страницу, и кнопки этой страницы — над ним.
  byBreakId: Map<string, PageNav>
  // Что стоит под всем полотном. null — последняя страница формы кончается не там: за ней
  // идёт страница «Спасибо», и кнопки отправки нарисованы перед её разрывом.
  tail: PageNav | null
}

// pageNavPlan — где на полотне какие кнопки. Разбиение берётся ТЕМИ ЖЕ функциями, что
// режут форму респонденту (splitThankYou + splitPagesWithClosers): собственный счёт
// разрывов разошёлся бы с показом на первом же инертном разрыве.
//
// Инертные разрывы (два подряд, разрыв в конце, разрыв до содержимого) кнопок не получают
// вовсе: они не закрывают страницу, и рисовать «Далее» там значило бы обещать шаг, которого
// у респондента нет.
export function pageNavPlan(blocks: Block[]): PageNavPlan {
  const { blocks: formBlocks, thankYou } = splitThankYou(blocks)
  const runs = splitPagesWithClosers(formBlocks)
  const byBreakId = new Map<string, PageNav>()

  // Все страницы, кроме последней, кончаются «Далее» — и закрывает их свой разрыв.
  runs.slice(0, -1).forEach((run) => {
    if (run.closer) byBreakId.set(run.closer.id, { kind: 'next' })
  })

  // Последняя страница формы кончается ОТПРАВКОЙ. Место зависит от того, есть ли за ней
  // экран после отправки: если есть, кнопки уходят перед его разрывом, а не под полотно.
  const last: PageNav = { kind: 'submit' }
  if (thankYou === null) return { byBreakId, tail: last }

  // Разрыв страницы «Спасибо» — тот, что закрывает последнюю страницу формы. В formBlocks
  // его уже нет (splitThankYou вырезал), поэтому берём из исходного документа: это
  // последний разрыв перед первым блоком экрана.
  const cut = blocks.indexOf(thankYou[0]!)
  for (let i = cut - 1; i >= 0; i--) {
    const b = blocks[i]!
    if (b.type !== 'page_break') continue
    byBreakId.set(b.id, last)
    break
  }
  return { byBreakId, tail: null }
}
