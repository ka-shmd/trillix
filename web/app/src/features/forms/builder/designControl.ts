// 2026-08-29). Панель собрана из DesignDrawer и DesignChrome (строки логотипа и
// обложки), контролы у них стоят в одних и тех же рядах, и разъехавшийся рост читался
// бы как две панели, сложенные в одну.
//
// НИЖЕ И МЕЛЬЧЕ КАБИНЕТНЫХ. Контролов в панели больше двух десятков, они идут сплошными
// рядами, и кабинетный рост (h-8 при кегле 14) превращает секцию в лестницу. 28px и
// 12/400 — обе ступени в замороженной шкале есть (DESIGN-SYSTEM §3, §4: 12/400 заведён
// под подсказки хрома), нового кегля тут не появляется.
//
// КРАЙ — ТЕНЬЮ, А НЕ РАМКОЙ: рамка это линия в потоке, она добавляет контролу ширины и
// на плотной сетке читается решёткой. Кольцо тенью рисуется ПОВЕРХ и геометрию не
// трогает — тот же приём, которым нарисовано поле формы (--rf-field-shadow в
// fields.css), только здесь он нужен ради плотности.

/**
 * Рост и кегль контрола.
 *
 * `md:text-xs` РЯДОМ С `text-xs` — НЕ ДУБЛЬ. У вендоренного `Input` кегль объявлен
 * парой `text-base md:text-sm`, и плоская утилита перебивает только первую половину:
 * на десктопе, то есть везде, где собирают форму, поле оставалось 14px, пока дропдаун
 * рядом (у него кегль плоский) уже стал 12. Правило записано в ui-kit: размер
 * вендоренного компонента правится ТЕМ ЖЕ вариантом, каким задан.
 */
export const CONTROL = 'h-7 text-xs md:text-xs'

/**
 * Край тенью вместо рамки — тот же рецепт, которым нарисовано поле формы
 * (`--rf-field-shadow` в fields.css): блик под верхней кромкой, тонкое кольцо и мягкое
 * рассеивание вниз. Одно кольцо в 1px рамку не заменяет, а повторяет — разницы на глаз
 * нет; слои дают контролу объём, и он читается приподнятым, а не обведённым.
 *
 * `border-transparent` обязателен: у shadcn `border-input` та же специфичность, и без
 * явной перебивки через cn победит порядок в собранном CSS, а не порядок в строке
 * (web/CLAUDE.md, «конфликтующие утилиты — молчаливый баг»).
 */
export const CONTROL_SHELL =
  'border-transparent shadow-[0_1px_1px_0_rgb(0_0_0/0.10),0_0_0_1px_rgb(61_59_53/0.14),0_2px_5px_0_rgb(61_59_53/0.07)]'

/** Оба сразу — то, что надевается на поле ввода. */
export const CONTROL_BOX = `${CONTROL} ${CONTROL_SHELL}`

/**
 * ДОБАВКИ ДЛЯ КОНТРОЛОВ, У КОТОРЫХ РОСТ ЗАДАН ВАРИАНТОМ, а не плоской утилитой.
 * Правило то же, что у кегля выше, и попадаются на него по очереди: `Select` объявляет
 * высоту как `data-[size=sm]:h-8`, `TabsList` — как
 * `group-data-[orientation=horizontal]/tabs:h-9`, и плоский `h-7` не перебивает ни ту,
 * ни другую — дропдаун и вкладки молча остаются кабинетного роста среди ужатых полей.
 */
export const CONTROL_SELECT = `${CONTROL_BOX} data-[size=sm]:h-7 data-[size=default]:h-7`
export const CONTROL_TABS = `${CONTROL} group-data-[orientation=horizontal]/tabs:h-7`

/**
 * Подписи шторки — 12/400 приглушённым, вровень с текстом контролов (решение владельца
 * 2026-08-29; до этого 14/600, потом 14/400).
 *
 * Довод — плотность и порядок чтения. Подписей в панели больше двух десятков, они идут
 * сплошной колонкой, и подпись КРУПНЕЕ и ЧЕРНЕЕ своего значения перетягивает взгляд на
 * себя: автор просматривает список названий, а не значений, хотя пришёл смотреть, что у
 * формы сейчас. Уравняв кегль и приглушив цвет, подпись возвращается на роль ярлыка.
 *
 * Кегль правится плоской утилитой намеренно: у вендоренного `Label` он объявлен плоским
 * `text-sm` (в отличие от `Input`, где пара `text-base md:text-sm`), и вариант тут не
 * нужен. Вес и цвет снимаются здесь, а не в самом `Label`: тот держит подписи всего
 * кабинета, где подпись одна на экран и выделять её как раз надо.
 */
export const LABEL = 'text-xs font-normal text-muted-foreground'
