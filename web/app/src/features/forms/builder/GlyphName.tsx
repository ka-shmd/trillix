import { type ReactNode } from 'react'

import { type BlockType } from '@entities/formSchema'

import { typeIcon } from './blockTypeIcons'

// «Глиф типа + имя» — общий вид пункта, который называет вопрос там, где самого вопроса
// не видно: список источников в условной логике, пункты меню, будущие пикеры целей. Имя
// вопроса выводится из его текста и у половины форм звучит одинаково («Вопрос 3»,
// «Короткий ответ»), поэтому глиф здесь не украшение — он единственное, что отличает
// строку от соседней.
//
// Глиф берётся из реестра типов (`typeIcon`) — того же словаря, что в slash-меню, диалоге
// добавления и в углу поля на полотне: тип выглядит одинаково везде, где о нём говорят.
//
// ГРУППА ПОКАЗЫВАЕТ ГЛИФ СВОЕГО ИНПУТА, а не подписи: `type` сюда передаёт вызывающий, и
// для вопроса это тип его отвечаемого блока. У подписи собственного глифа в этой роли не
// бывает — вопрос узнают по тому, чем на него отвечают.
//
// РАЗМЕТКА РАССЧИТАНА НА ХОЗЯИНА-ФЛЕКС и на его правила для svg — так устроены и
// SelectItem, и слот значения у SelectTrigger, и CommandItem (`flex items-center gap-2`,
// `[&_svg]:shrink-0`, размер и цвет глифа). Отсюда две вещи, без которых длинное имя
// ломает контрол:
//
//   • `min-w-0` на самой коробке — флекс-элемент по умолчанию не сжимается уже своего
//     содержимого, и обрезать было бы нечего;
//   • `truncate` на ИМЕНИ, а не на коробке — многоточие нужно тексту, глиф обрезать
//     нельзя. У флекс-элемента с `overflow: hidden` минимальный размер и так ноль,
//     поэтому второго `min-w-0` тут не нужно.
//
// Хозяину остаётся дать себе `min-w-0` (у триггера Select это
// `*:data-[slot=select-value]:min-w-0`) — без него сжиматься нечему уже ему самому.
export function GlyphName({ type, children }: { type: BlockType; children: ReactNode }) {
  return (
    <span className="flex min-w-0 items-center gap-2">
      {typeIcon(type)}
      <span className="truncate">{children}</span>
    </span>
  )
}
