import { useCallback, useState } from 'react'

import { type FormSchema } from '@entities/formSchema'

import { DEFAULT_FORM_TITLE, type FormDetail } from '../../entities/form'

// Ленивое создание формы: кнопка «Новая форма» НИЧЕГО не создаёт на сервере, а
// открывает редактор несуществующего черновика. POST /forms уходит с первой правкой
// (useAutosave.ensureForm), и форма, которую открыли и закрыли не тронув, на сервере
// не появляется вовсе.
//
// Адрес такого черновика — /forms/new/edit, тот же маршрут, что и у настоящей формы:
// создание заменяет `new` на реальный slug, НЕ размонтировав полотно (маршрут тот же,
// ключ стора заморожен) — иначе первая же правка выбивала бы каретку из-под автора.
// Столкнуться с настоящим slug сентинел не может: сервер выдаёт ровно
// domain.SlugLen = 10 символов, здесь их три.
export const NEW_FORM_SLUG = 'new'

// Черновик пустой формы, каким его отдаёт СЕРВЕР: строка заголовка на полотне — это
// блок документа, и у формы, которая о заголовке ещё не говорила, его дописывает
// чтение (`domain.EnsureFormTitle`, `CanonicalDraftV4`), а не хранит база. Пустой
// `blocks: []` дал бы полотно без первой строки — заголовок формы просто исчез бы.
// Id зеркалит серверный (`ft_<id формы>`), но id формы здесь ещё нет: сентинел стоит
// на его месте и таким в документе и остаётся — уникальность нужна только внутри
// документа, а второй раз заголовок никто не синтезирует.
const NEW_FORM_SCHEMA: FormSchema = {
  blocks: [{ id: 'ft_new', groupId: 'g_ft_new', type: 'form_title', text: [] }],
}

// Деталь несозданной формы: редактору она нужна вся (гидрирует стор, рисует шапку и
// страницу настроек) за минуту до того, как форма появится. Поля повторяют то, чем
// новую форму заводит сервер, — пустой черновик, дефолтный заголовок, письма о новых
// ответах включены (forms.Create + дефолты колонок `forms`). Врать этому зеркалу
// недолго: с первой правкой деталь заменяется настоящей карточкой из ответа POST.
export function newFormDetail(): FormDetail {
  return {
    id: '',
    // Пространство и расписание у несозданной формы неизвестны: первое приедет с
    // ответом POST, второго нет по устройству — записи у новой формы не бывает.
    workspaceId: '',
    workspaceSlug: '',
    scheduleId: null,
    name: null,
    title: DEFAULT_FORM_TITLE,
    slug: NEW_FORM_SLUG,
    status: 'draft',
    createdAt: '',
    updatedAt: '',
    publishedVersion: null,
    publishedVersionId: null,
    hasUnpublishedChanges: false,
    submissionCount: 0,
    lastSubmissionAt: null,
    visitCount: 0,
    visitSubmittedCount: 0,
    draftSchema: NEW_FORM_SCHEMA,
    closeAt: null,
    responseLimit: null,
    closedMessage: null,
    closedTitle: null,
    // Письма о новых ответах у новой формы ВЫКЛЮЧЕНЫ — дефолт колонки (0042):
    // продукт не начинает слать почту, ни о чём не спросив.
    notifyOnSubmission: false,
    // Сбор незавершённых у новой формы выключен: собирать то, что человек не
    // отправлял, по умолчанию нельзя.
    collectPartial: false,
    // Бейдж у новой формы стоит — дефолт колонки `forms.branding`.
    branding: true,
    // Шкала прогресса у новой формы выключена — дефолт колонки `forms.progress`.
    progress: false,
    // Поведение у новой формы — дефолты колонок (0044): страницы листает человек,
    // ответы живут до закрытия вкладки.
    autoJump: false,
    saveLocally: false,
    allowBack: false,
    // Письмо о новом ответе не настраивали — уйдёт дефолтным шаблоном.
    notifyEmail: null,
    // Карточку ссылки не настраивали — публичная страница возьмёт дефолты.
    linkPreview: null,
    // Письма у несозданной формы ещё нет: сервер не считал ни адресов, ни темы, —
    // бланк настроек отступит к описанию вместо пустых строк.
    notifyMail: { from: '', to: '', fromName: '', subject: '' },
    // Письмо респонденту у новой формы выключено и не настроено — те же дефолты
    // колонок (0046) и тот же довод, что у письма владельцу.
    notifyRespondent: false,
    password: null,
    respondentEmail: null,
    respondentMail: { from: '', to: '', fromName: '', subject: '' },
  }
}

// Мишень экрана редактора: какую форму просит адрес и не пора ли начать заново.
//
// Маршрут у настоящей формы и у несозданного черновика ОДИН (/forms/$slug/edit), так
// что React переиспользует компонент между ними, а сентинел в адресе живёт только до
// первой правки. Отсюда два требования, которые тянут друг друга в разные стороны:
//
//   • создание МЕНЯЕТ slug в адресе, и экран обязан этого не заметить — иначе полотно
//     ремаунтится под кареткой автора, дописывающего первое слово;
//   • «+» у пространства в сайдбаре меняет slug на сентинел, и экран обязан заметить —
//     иначе, придя из редактора готовой формы, он останется в ветке обычной и спросит
//     у сервера форму `new`: 404 и «Форма не найдена» вместо чистого полотна.
//
// Поэтому хук помнит АДРЕС, который обслуживает, и сверяется с ним на каждом рендере;
// созданную форму он берёт себе (adoptCreated) и на время, пока адрес её догоняет,
// обслуживает оба написания.
//
// Пространство входит в мишень черновика: «+» у другого пространства — просьба о
// ДРУГОЙ новой форме, хотя slug в адресе не меняется.
export function useFormEditorTarget(slug: string, workspaceSlug: string) {
  const target = slug === NEW_FORM_SLUG ? `${NEW_FORM_SLUG}?${workspaceSlug}` : slug

  const [state, setState] = useState(() => ({
    target,
    // Slug формы, которую этот экран сам и завёл. Пока не null, адрес может стоять
    // как на сентинеле, так и на нём: `replace` в пути.
    created: null as string | null,
    // Номер черновика в жизни экрана. Нужен ключу полотна: у двух черновиков подряд
    // адрес один и тот же, а полотно разное.
    epoch: 0,
    draft: slug === NEW_FORM_SLUG ? newFormDetail() : null,
  }))

  // Правка состояния прямо в рендере (React, «adjusting state when props change»):
  // экран обязан спрашивать не ту форму, которой в адресе больше нет, уже В ЭТОМ
  // рендере — отложенный до эффекта сброс успел бы отправить лишний запрос.
  let s = state
  const serving = s.created === null ? [s.target] : [s.target, s.created]
  if (!serving.includes(target)) {
    // Адрес зовёт туда, где экран ещё не был: другая форма или новый черновик.
    s = {
      target,
      created: null,
      epoch: s.epoch + 1,
      draft: slug === NEW_FORM_SLUG ? newFormDetail() : null,
    }
    setState(s)
  } else if (target === s.created) {
    // Адрес догнал созданную форму. Сентинел с этого момента забыт — иначе следующее
    // «+» в том же пространстве экран принял бы за свой же адрес и черновик не завёл.
    s = { ...s, target, created: null }
    setState(s)
  }

  const adoptCreated = useCallback((detail: FormDetail) => {
    setState((prev) => ({ ...prev, created: detail.slug, draft: detail }))
  }, [])

  return {
    // Синтетическая деталь черновика, а после создания — настоящая карточка формы.
    // null у обычной формы: её деталь приезжает запросом.
    draftDetail: s.draft,
    isDraft: s.draft !== null,
    // Ключ стора билдера. У черновика он ЗАМОРОЖЕН на сентинеле с номером: создание
    // меняет slug, и ключ по нему ремаунтил бы полотно (см. выше).
    canvasKey: s.draft !== null ? `${NEW_FORM_SLUG}:${s.epoch}` : slug,
    adoptCreated,
  }
}
