// Фабрика query-ключей forms: строковые литералы ключей в компонентах запрещены
// (web/CLAUDE.md), только отсюда.
export const formKeys = {
  // list() — префикс всех списков: им инвалидируют разом любые поиск/сортировку
  // (мутация меняет выдачу при любых параметрах).
  list: () => ['forms', 'list'] as const,
  // listWith() — конкретный список: свой кэш на каждую четвёрку (пространство,
  // поиск, сортировка, размер страницы). Пространство входит в ключ обязательно —
  // иначе переключение показало бы формы прежнего из кэша, и это выглядело бы как
  // «мои формы уехали в чужую папку». Размер страницы — тоже: дашборд листает по
  // 50, обзор пространств по 10, и общий ключ склеил бы два разных списка в один.
  // Фильтр по статусу — там же: сервер отдаёт под него другую выдачу.
  listWith: (params: {
    workspaceId: string
    q: string
    sort: string
    status: string
    limit?: number
  }) => ['forms', 'list', params] as const,
  // search() — выдача поиска по ВСЕМ пространствам; ключуется самим запросом.
  // Отдельно от list(): у поиска нет ни пространства, ни сортировки, ни страниц, и
  // общий префикс заставлял бы мутацию формы инвалидировать заодно все набранные
  // запросы — а они всё равно перечитаются при следующем открытии окна.
  search: (q: string) => ['forms', 'search', q] as const,
  // detail ключуется slug'ом формы (идентификатор URL кабинета), не UUID:
  // роут даёт slug, мутации патчат кэш по возвращённому form.slug.
  detail: (slug: string) => ['forms', 'detail', slug] as const,
  // detailAll() — префикс всех деталей: нужен там, где на руках только UUID формы,
  // а её slug ещё неизвестен (оптимистичный патч rename — см. queries.ts).
  detailAll: () => ['forms', 'detail'] as const,
  // consent — раздел «Персональные данные» формы. Ключуется UUID: страница настроек
  // получает его из детали, а ручка раздела адресуется им же.
  consent: (id: string) => ['forms', 'consent', id] as const,
}
