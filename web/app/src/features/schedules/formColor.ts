// Цвет формы в списке ближайших записей.
//
// ОДНО РАСПИСАНИЕ ОБСЛУЖИВАЕТ НЕСКОЛЬКО ФОРМ, и в списке они идут вперемешку: название
// формы под временем отвечает на вопрос «чья запись», но читать его приходится
// строку за строкой. Цвет отвечает на тот же вопрос без чтения.
//
// Набор — КАТЕГОРИАЛЬНЫЙ `--chart-1..8` дизайн-системы, а не свой: он собран ровно под
// эту задачу (восемь тонов, а не светлот одного, соседи по порядку разнесены, светлота
// гуляет вместе с тоном — различимы и в тёмной теме). Второй набор рядом с ним
// разъехался бы с темами при первой же правке токенов.
//
// Тон закреплён ЗА ID ФОРМЫ, а не за местом в списке: место меняется от каждой новой
// записи, и цвет, привязанный к нему, менял бы значение на глазах. Форм больше восьми —
// тона повторяются; цвет здесь подсказка, а название формы в строке стоит всегда.
const TONES = 8

export function formTone(formId: string): number {
  // djb2: одинаковый ответ на одном id в любой сессии и на любом экране.
  let hash = 5381
  for (let i = 0; i < formId.length; i++) hash = (hash * 33 + formId.charCodeAt(i)) % 0xffffffff
  return (hash % TONES) + 1
}

// formInk — сам тон: им красится метка-полоска слева от строки.
export function formInk(formId: string): string {
  return `var(--chart-${formTone(formId)})`
}

// formTint — тот же тон подложкой. Через `color-mix` с прозрачностью, а не второй
// светлотой в токенах: подложка обязана лежать на своём фоне и в светлой теме, и в
// тёмной, а разводить восемь тонов ещё и по светлотам — это шестнадцать токенов ради
// заливки строки.
export function formTint(formId: string): string {
  return `color-mix(in oklab, var(--chart-${formTone(formId)}) 12%, transparent)`
}
