import { ApiError } from '../../shared/api/errors'

// ОТКАЗ ПО ТАРИФУ — НЕ СБОЙ, и говорить о нём надо иначе.
//
// Общий текст «не удалось, попробуйте ещё раз» здесь врёт дважды: повторять
// бессмысленно (тариф от повтора не изменится), а причина известна серверу и
// перечислена им поимённо — что именно в форме платное. Заставлять автора гадать,
// какую из десяти настроек снять, значит превращать отказ в тупик.
//
// Живёт отдельным модулем, потому что точек публикации ДВЕ (шапка редактора и
// экран «Поделиться»), и разъехавшись, они начали бы объяснять один и тот же 402
// по-разному.

// planRequiredMessage — человеческая часть сообщения сервера, если это отказ по
// тарифу; иначе null (вызывающий покажет свой общий текст).
//
// Ветвление по code, а не по тексту (web/CLAUDE.md): текст меняется, код — контракт.
// Служебный префикс сентинела («plan required: …») срезается — его писал Go для
// себя, а читает человек.
export function planRequiredMessage(error: unknown): string | null {
  if (!(error instanceof ApiError) || error.code !== 'plan_required') return null
  const i = error.message.indexOf(': ')
  return i >= 0 ? error.message.slice(i + 2) : error.message
}
