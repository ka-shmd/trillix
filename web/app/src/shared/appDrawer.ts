import { useEffect } from 'react'

// СДВИГ ОБОЛОЧКИ ПОД ВЫЕЗЖАЮЩУЮ ШТОРКУ — общий на все шторки редактора.
//
// Открытая шторка не накрывает страницу, а отодвигает её: маршрутная коробка
// (`SidebarInset` в routes/_app.tsx) держит правый отступ `pr-(--app-drawer)`,
// поэтому шапка и полотно съезжают, а колонка формы перецентрируется. Переменная
// живёт на корне документа, а не проп через три слоя: шторку открывают глубоко в
// фиче, а съезжает оболочка маршрута.
//
// ХУК, А НЕ ПОВТОРЁННЫЙ ЭФФЕКТ В КАЖДОЙ ШТОРКЕ: ширина обязана совпадать с классом
// панели, и второй экземпляр этого числа означал бы щель или нахлёст в тот день,
// когда поправят одно из двух мест.
//
// ШТОРКИ ВЗАИМОИСКЛЮЧАЮЩИ (открытие одной закрывает другую — BuilderScreen): они
// занимают одно и то же место у правого края, и открытые вместе легли бы друг на
// друга, а закрытие первой сняло бы отступ из-под второй.

// APP_DRAWER_WIDTH — ширина открытой шторки одним числом на два места: класс
// `w-104`/`sm:max-w-104` у панели и отступ оболочки. 26rem = w-104.
export const APP_DRAWER_WIDTH = '26rem'

export function useAppDrawerOffset(open: boolean): void {
  useEffect(() => {
    if (!open) return
    const root = document.documentElement
    root.style.setProperty('--app-drawer', APP_DRAWER_WIDTH)
    // Снимается в cleanup — иначе закрытая панель оставила бы страницу с вечным
    // отступом справа.
    return () => {
      root.style.removeProperty('--app-drawer')
    }
  }, [open])
}
