// Текущее пространство живёт в АДРЕСНОЙ СТРОКЕ — в ПУТИ `/w/{slug}/…`, а не в
// параметре запроса и не в сторе. Ссылка на раздел пространства сохраняется в
// закладки, F5 не сбрасывает, «Назад» работает, и две вкладки в разных
// пространствах не мешают друг другу.
//
// ⚠ ПАРАМЕТРА `?w=` БОЛЬШЕ НЕТ, И ЗАВОДИТЬ ЕГО ЗАНОВО НЕЛЬЗЯ. Пока пространство
// ехало параметром, существовала ссылка, которая его потеряла, — а потерянный
// параметр читался как «личное пространство» МОЛЧА: расписание команды уходило в
// личное (отчёт владельца 2026-09-03), тариф команды был недостижим, форма из
// шаблона ложилась не туда. Путь умолчать пространство не может.
// Спека — `docs/design/cabinet-navigation.md` §3.2.
//
// АДРЕС НАЗЫВАЕТ ПРОСТРАНСТВО SLUG'ОМ, А API — ID. То же разделение, что у формы:
// в URL кабинета стоит `form.slug`, а мутации уходят с `form.id`. Перевод одного в
// другой делает `features/workspaces/current.ts` по уже загруженному списку.

// Пространство в пути раздела: `/w/{slug}`, `/w/{slug}/schedules/{id}` и так далее.
// `null` — «путь пространства не называет» (форма, настройки аккаунта, вход).
export function workspaceSlugFromPath(pathname: string): string | null {
  const slug = /^\/w\/([^/]+)(?:\/|$)/.exec(pathname)?.[1]
  return slug === undefined ? null : decodeURIComponent(slug)
}

const MEMORY_KEY = 'trillix:workspace'

// ПАМЯТЬ БРАУЗЕРА — ТОЛЬКО ДЛЯ ВЫВЕСКИ, и ничего по ней не создаётся. Нужна она
// одному экрану: настройки аккаунта пространству не принадлежат, и без памяти
// переключатель на них показывал бы личное, а возврат из настроек терял бы место.
// Всё, что заводит сущность в пространстве (форма, черновик, расписание), берёт
// slug ИЗ ПУТИ — иначе вернулся бы ровно тот дефект, ради которого убран `?w=`.
export function recallWorkspaceSlug(): string | null {
  try {
    return window.localStorage.getItem(MEMORY_KEY)
  } catch {
    // Приватное окно, запрет на хранилище сайта — не повод ронять оболочку.
    return null
  }
}

export function rememberWorkspaceSlug(slug: string): void {
  try {
    window.localStorage.setItem(MEMORY_KEY, slug)
  } catch {
    // См. выше: память необязательна, без неё переключатель просто покажет личное.
  }
}
