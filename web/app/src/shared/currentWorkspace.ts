import { useRouterState } from '@tanstack/react-router'

// Текущее пространство живёт в АДРЕСНОЙ СТРОКЕ (?w=<slug>), а не в сторе и не на
// сервере в сессии. Причины те же, по которым там же живут поиск и сортировка
// дашборда: ссылка на список пространства сохраняется в закладки, F5 не
// сбрасывает, «Назад» работает — и, в отличие от серверного «текущего», две
// вкладки в разных пространствах не мешают друг другу.
//
// Пусто (параметра нет) = ЛИЧНОЕ пространство. Так адрес «/forms» остаётся
// «/forms», а десяток существующих ссылок на дашборд не обязан ничего знать
// про пространства.
//
// АДРЕС НАЗЫВАЕТ ПРОСТРАНСТВО SLUG'ОМ, А API — ID. То же разделение, что у формы:
// в URL кабинета стоит `form.slug`, а мутации уходят с `form.id`. Перевод одного в
// другой делает `features/workspaces/current.ts` по уже загруженному списку —
// отдельной ручки-резолвера (как /forms/lookup у формы) пространству не нужно,
// потому что `GET /workspaces` и так отдаёт все.
//
// useCurrentWorkspaceSlug читает адрес вне зависимости от того, какой это маршрут:
// оболочка кабинета (сайдбар, кнопка «Новая форма») живёт над деревом маршрутов и
// типизированного доступа к их search не имеет. Возвращает '' — «в адресе не
// сказано», то есть личное.
//
// ДВА МЕСТА, ГДЕ ПРОСТРАНСТВО МОЖЕТ БЫТЬ НАПИСАНО: `?w=` у форм и путь
// `/workspaces/{slug}` у страницы пространства. Без второго «Новая форма» из
// сайдбара, стоя внутри командного пространства, молча заводила бы форму в личном,
// а гейты тарифа спрашивали бы не тот план. Путь важнее параметра: он и есть
// текущий экран.
export function useCurrentWorkspaceSlug(): string {
  return useRouterState({
    select: (s) => workspaceSlugFromLocation(s.location.pathname, s.location.search),
  })
}

// Разбор адреса вынесен из хука отдельной функцией: правило «путь важнее ?w=»
// проверяется тестом, а не запуском роутера.
export function workspaceSlugFromLocation(pathname: string, search: unknown): string {
  const fromPath = /^\/workspaces\/([^/]+)\/?$/.exec(pathname)?.[1]
  if (fromPath !== undefined) return decodeURIComponent(fromPath)
  const w = (search as { w?: unknown }).w
  return typeof w === 'string' ? w : ''
}
