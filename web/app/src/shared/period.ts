import { z } from 'zod'

// Окно наблюдения экранов аналитики (спека design/analytics-tally.md §4).
//
// Живёт в shared, а не в фиче: период читают и запросы визитов, и запросы ответов
// — это разные фичи, а импорт одной фичи из другой запрещён (web/CLAUDE.md).

// Значение периода — токен, а не пара дат: в query-ключе TanStack дата менялась бы
// на каждый рендер (Date.now()), и кеш обнулялся бы сам собой. Даты считаются в
// момент запроса.
const periodEnum = z.enum(['all', '24h', '7d', '30d'])
export type Period = z.infer<typeof periodEnum>

// DEFAULT_PERIOD — окно, с которым аналитика открывается, когда его не назвали:
// адрес без ?period, старая закладка на /summary, вход по вкладке «Аналитика».
// Одна константа на все эти входы: разъехавшись, они открывали бы разные экраны с
// одной кнопки.
//
// Она же — ответ на битое значение в адресе (.catch ниже). Ветку «неизвестный
// период» отдельно писать не надо: непонятное окно и неназванное — один случай.
export const DEFAULT_PERIOD: Period = '24h'

export const periodSchema = periodEnum.catch(DEFAULT_PERIOD)

// Свежесть запросов аналитики (TD-79). Каждый из них — полный проход по визитам или
// ответам формы за окно, поэтому фокус окна их не перезапускает, а повторный заход на
// вкладку в пределах минуты берёт кеш. Смена окна — другой ключ и новый запрос.
export const analyticsFreshness = { staleTime: 60 * 1000, refetchOnWindowFocus: false } as const

// Порядок окон на экране: от узкого к широкому. У объекта подписей он другой (ключи
// схемы), и ряд переключателя открывался бы «Всем временем».
export const PERIODS: readonly Period[] = ['24h', '7d', '30d', 'all']

export const periodLabels: Record<Period, string> = {
  all: 'Всё время',
  '24h': '24 часа',
  '7d': '7 дней',
  '30d': '30 дней',
}

// С чем сравнивается окно на карточках: с прошлым окном той же длины. У «всего
// времени» сравнения нет.
export const previousPeriodLabels: Record<Exclude<Period, 'all'>, string> = {
  '24h': 'к прошлым суткам',
  '7d': 'к прошлым 7 дням',
  '30d': 'к прошлым 30 дням',
}

const periodHours: Record<Exclude<Period, 'all'>, number> = {
  '24h': 24,
  '7d': 24 * 7,
  '30d': 24 * 30,
}

// periodRange — параметры запроса для выбранного периода. «Всё время» не шлёт
// границ вовсе: сервер понимает их отсутствие как ±бесконечность, и одно окно
// наблюдения не должно иметь двух представлений на клиенте.
//
// Верхняя граница не ставится сознательно: она была бы «сейчас» на момент сборки
// запроса, то есть визит, пришедший во время загрузки страницы, выпадал бы из
// периода без всякой причины.
export function periodRange(period: Period): Record<string, string> {
  if (period === 'all') return {}
  return { from: new Date(Date.now() - periodHours[period] * 3600_000).toISOString() }
}
