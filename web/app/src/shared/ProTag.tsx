import { Link } from '@tanstack/react-router'

import { Badge } from '@/components/ui/badge'

// Метка платной возможности. Ссылка, а не подпись: автор, увидевший её, должен
// иметь возможность узнать цену тем же жестом, каким заметил ограничение.
//
// СЛОВО, А НЕ ЗНАЧОК (решение владельца 2026-08-10): замок сообщает «нельзя», но не
// сообщает ЧТО с этим делать, и на секции, где половина настроек бесплатна, читался
// как поломка. «ПРО» называет тариф, на котором это работает, — и называет его
// по-русски, как весь остальной кабинет (решение владельца 2026-08-26).
//
// ЗНАЧКА В МЕТКЕ НЕТ ВОВСЕ (решение владельца 2026-08-27): ни замка, ни точки. Замок
// повторял смысл, уже сказанный словом, и добавлял к нему запрет, которого в метке
// нет — настройку под ней обычно можно и потрогать, и сохранить; точка же только
// занимала место в надписи из трёх букв.
//
// ВТОРОЙ АКЦЕНТ, а не синий (решение владельца 2026-08-26) — единственное нажимаемое
// в кабинете, покрашенное `--highlight`. Довод записан в index.css и в
// DESIGN-SYSTEM §6: метка стоит рядом с главной кнопкой экрана, и синяя пилюля
// спорила бы с ней за внимание, обещая действие там, где названо условие доступа.
//
// Собрана из `Badge` (вариант `highlight`), а не своей вёрсткой: рамка и своя
// геометрия там, где система требует плоскости, — лишний вид на ровном месте.
//
// КЕГЛЬ 10px — ЕДИНСТВЕННОЕ МЕСТО КАБИНЕТА ВНЕ ЗАМОРОЖЕННОЙ ШКАЛЫ (решение владельца
// 2026-08-27, DESIGN-SYSTEM §3): метка приклеена к чужой строке и обязана читаться
// подписью к ней, а не её частью. Ни с одной строкой шкалы 10px не рифмуется — и не
// должен; исключение записано в документе, чтобы следующий кегль вне таблицы
// заводили тем же порядком, а не ссылкой на этот.
//
// РАЗРЯДКА ОБЯЗАТЕЛЬНА, и она же чинит наследование. Метка стоит ВНУТРИ заголовка
// раздела, у которого `tracking-tight` (−0.025em), а letter-spacing наследуется —
// без своего значения три заглавные буквы слипались бы. Плюс капсу разрядка нужна
// сама по себе: у прописных нет выносных элементов, которые разводят буквы в
// строчном наборе. `tracking-wide` (+0.025em) переопределяет унаследованное
// значение целиком, а не складывается с ним.
//
// Вес 600 против 500 у прочих бейджей (решение владельца 2026-08-26): три буквы на
// мягкой подложке — самая мелкая надпись экрана, и на 500 она читается бледнее, чем
// заголовок, к которому приклеена. Типографика метки живёт ЗДЕСЬ, а не в варианте
// `highlight`: вариант отвечает за цвет, и вешать на него начертание значило бы
// раздать его каждому будущему бейджу второго акцента.
export function ProTag() {
  return (
    <Badge asChild variant="highlight" className="text-[10px] font-semibold tracking-wide">
      <Link to="/settings/plan">ПРО</Link>
    </Badge>
  )
}
