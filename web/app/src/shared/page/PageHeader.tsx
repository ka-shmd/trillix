import { cn } from '@/lib/utils'

// Шапка содержимого страницы: заголовок, пояснение, ряд состояния и действия
// справа. Крошки и путь назад сюда НЕ входят — они живут в верхнем баре кабинета
// (routes/_app.tsx), один на всё приложение.
//
// Верхняя ступень шкалы кеглей кабинета (вся шкала — docs/DESIGN-SYSTEM.md):
// заголовок страницы 30/800 → заголовок раздела 20/700 → название элемента 16/600.
// Вторичный текст всегда на ступень мельче того, к чему относится, — это и есть
// правило, по которому размер не приходится подбирать на каждом экране.
export function PageHeader({
  title,
  titleAction,
  description,
  meta,
  actions,
  wrapTitle,
  className,
}: {
  title: React.ReactNode
  // titleAction — кнопка ВПЛОТНУЮ к имени (меню действий над названной сущностью).
  // Отдельно от `actions`: те стоят у правого края шапки и относятся к разделу
  // целиком — прежде всего «завести новое» (DESIGN-SYSTEM §1).
  titleAction?: React.ReactNode
  description?: React.ReactNode
  // meta — ряд под заголовком: бейдж статуса, версия, счётчик. Отдельно от
  // description, потому что это состояние сущности, а не текст про неё.
  meta?: React.ReactNode
  // actions — действия РАЗДЕЛА, у правого края шапки. Сюда, а не в `PageActions`,
  // ставится «завести новое» (решение владельца 2026-09-07): верхний бар держит
  // действия над ОТКРЫТОЙ сущностью, и акцентная кнопка создания спорила бы там с
  // крошками за внимание.
  actions?: React.ReactNode
  // wrapTitle — заголовок переносится на вторую строку вместо многоточия. Для страниц, где
  // заголовок — НАЗВАНИЕ ДОКУМЕНТА, а не имя сущности из списка: «Согласие на получение
  // рекламных и информационных рассылок» в одну строку не влезает ни на одной ширине, и
  // обрезанное название документа прочитать нельзя.
  wrapTitle?: boolean
  className?: string
}) {
  return (
    // ⚠ НЕ `flex-wrap`, И ЭТО МИНА. Обёртка ставит действия на СЛЕДУЮЩУЮ строку
    // flex-контейнера, а там они прижимаются к левому краю — то есть место кнопки
    // начинает зависеть от длины заголовка и описания рядом. Так «Новое расписание»
    // оказывалось под двухстрочным описанием слева, а «Новая форма» — справа от
    // заголовка: одна и та же кнопка в двух разных местах кабинета, и заметить это
    // можно только глазами (найдено владельцем 2026-09-07).
    //
    // Вместо обёртки — колонка на узком экране и ряд от `sm`: текст жмётся в своей
    // колонке (`min-w-0`), а действия стоят у правого края всегда.
    <header
      className={cn('flex flex-col gap-4 sm:flex-row sm:items-start sm:justify-between', className)}
    >
      <div className="min-w-0">
        <div className="flex min-w-0 items-center gap-1.5">
          <h1
            className={cn(
              'text-3xl font-extrabold tracking-tight',
              // Умолчание — одна строка с многоточием: имя формы или пространства бывает
              // любой длины, и перенос ломал бы высоту шапки на каждом длинном названии.
              wrapTitle ? 'text-balance' : 'truncate',
            )}
          >
            {title}
          </h1>
          {titleAction}
        </div>
        {description && <p className="mt-1 text-base text-muted-foreground">{description}</p>}
        {meta && <div className="mt-2 flex flex-wrap items-center gap-2">{meta}</div>}
      </div>
      {actions && <div className="flex shrink-0 items-center gap-2">{actions}</div>}
    </header>
  )
}
