/**
 * Подсветка кода на экране вставки — своя, без библиотеки (решение владельца
 * 2026-08-28).
 *
 * ПОДСВЕТЧИКИ ДОРОГИ ТЕМ, ЧТО РАЗБИРАЮТ ПРОИЗВОЛЬНЫЙ КОД: чужие языки, битый
 * синтаксис, вложенные строки. Здесь этой задачи нет. На экране ровно три формы, и
 * все три печатает `embedSnippet.ts` — набор строк закрыт и меняется только вместе с
 * генератором, у которого свои юниты. Отсюда и право на регулярку вместо разбора.
 *
 * ГРАНИЦА, ЗА КОТОРОЙ ЭТОТ ФАЙЛ ПЕРЕСТАЁТ ГОДИТЬСЯ: появится на экране код, который
 * пишем не мы (пример из документации, сниппет от пользователя, другой язык), —
 * правильной подсветки от этих правил ждать нельзя, и разговор возвращается к
 * библиотеке (`prism-react-renderer` — единственный популярный, кто отдаёт React-узлы,
 * а не HTML-строку, то есть не спорит с инвариантом 4).
 *
 * Разметка НЕ СОБИРАЕТСЯ СТРОКОЙ: наружу уходят токены, из которых компонент делает
 * `<span>`. `dangerouslySetInnerHTML` запрещён во всём репозитории (инвариант 4), и
 * подсветка — ровно то место, где к нему тянутся по привычке.
 */

/** Что раскрашивается. `plain` — всё остальное: скобки, знаки, пробелы. */
export type TokenKind = 'tag' | 'attr' | 'string' | 'comment' | 'plain'

export interface Token {
  text: string
  kind: TokenKind
}

/**
 * Разметка сниппета: тег, имя атрибута, значение в кавычках.
 *
 * ЗНАЧЕНИЕ ЧИТАЕТСЯ ПРОСТЫМ `"[^"]*"` — и это верно ровно потому, что кавычку внутрь
 * значения не пропускает `escapeAttr` генератора (она уезжает как `&quot;`, а `<`
 * и `>` — как `&lt;`/`&gt;`). Уберут экранирование — сломается и сниппет на чужой
 * странице, и эта регулярка; порядок поломки правильный, потому что первое заметят
 * раньше.
 *
 * Имя атрибута ловится по «слово перед `=`, пробелом или `>`»: так в подсветку
 * попадает и `async`, у которого значения нет вовсе. Текста вне тегов в наших
 * сниппетах не бывает, поэтому спутать слово атрибута с содержимым узла не с чем.
 */
const HTML = /(<\/?[a-z][\w-]*)|("[^"]*")|([\w-]+)(?=[=\s>])/gi
const HTML_KINDS: TokenKind[] = ['tag', 'string', 'attr']

/**
 * Вызов из кода приложения: комментарий, строка, имя объекта и ключ.
 *
 * Комментарий стоит ПЕРВЫМ: в нём живёт подпись вопроса — авторский текст, где
 * возможна и кавычка, и скобка. Съев строку до конца, правило не даёт этим знакам
 * открыть строковый литерал, которого там нет.
 *
 * Ключ в кавычках (`'blk_1':`) достаётся строковому правилу, а не ключевому, и это
 * не промах: id блока и есть строка, а различать «строку-ключ» и «строку-значение»
 * цветом — различие без разницы.
 */
const JS = /(\/\/[^\n]*)|('[^']*')|(\bTrillix\b)|([\w$]+)(?=\s*:)/g
const JS_KINDS: TokenKind[] = ['comment', 'string', 'tag', 'attr']

/**
 * CSS автора формы — правила из шторки «Оформление» (решение владельца 2026-08-28).
 *
 * ЭТО ТОТ САМЫЙ СЛУЧАЙ, О КОТОРОМ ПРЕДУПРЕЖДАЕТ ШАПКА: код здесь пишем не мы, набор
 * строк не закрыт, и регулярка правильной подсветки не гарантирует. Разница с
 * остальными грамматиками — в цене промаха: сниппет с неверно раскрашенным куском
 * ввёл бы в заблуждение, а тут ошибка подсветки видна автору сразу и ничего не ломает.
 * Значение по-прежнему проверяет схема, а не эти правила.
 *
 * СЕЛЕКТОР ОТ СВОЙСТВА ОТЛИЧАЕТСЯ ЛУКАХЕДОМ ДО `{`: слово, за которым до открывающей
 * скобки не встретилось ни `;`, ни `{`, ни `}`, — селектор; слово перед `:` — свойство.
 * Внутри блока лукахед всегда упирается в `;` или `}`, поэтому `border-radius: 0` не
 * притворяется селектором. Известный промах — `@media (max-width: 600px)`: `max-width`
 * стоит перед `{` без разделителей и красится как селектор. Цветом, а не смыслом.
 *
 * ЗНАЧЕНИЯ ОСТАЮТСЯ ЧЕРНИЛАМИ — три цвета на язык, как и у двух грамматик выше:
 * различать `0`, `red` и `1px solid` цветом значит раскрасить строку целиком.
 *
 * ЛУКАХЕД ОГРАНИЧЕН 200 СИМВОЛАМИ, и это не про длину селектора, а про стоимость:
 * без предела каждое слово текста БЕЗ фигурных скобок заставляет движок дочитывать
 * остаток до конца, то есть даёт квадрат на потолке в 10 000 рун. Подсветка считается
 * на каждое нажатие клавиши.
 */
const CSS =
  /(\/\*[\s\S]*?\*\/)|("[^"]*"|'[^']*')|([.#]?[-\w]+(?=[^{};]{0,200}\{))|([-\w]+)(?=\s*:)/g
const CSS_KINDS: TokenKind[] = ['comment', 'string', 'tag', 'attr']

/** Язык. `auto` — выбор по самой строке (экран вставки, где строк три и все наши). */
export type Lang = 'auto' | 'css'

/**
 * highlight — код в токены. При `auto` грамматика выбирается по самой строке: сниппет
 * начинается с тега, адрес — со схемы, остальное — вызов из кода.
 *
 * CSS НАЗЫВАЕТСЯ ЯВНО, а не угадывается: авторское правило может начаться с чего
 * угодно — с комментария, с `@media`, с пустой строки, — и любое чутьё на нём
 * ошибётся. Место вызова язык знает точно, поэтому гадать незачем.
 *
 * АДРЕС НЕ РАЗМЕЧАЕТСЯ ВОВСЕ: он одна строка целиком, и раскраска его кусков
 * (схема, путь, параметры) — шум там, где читают одним взглядом и копируют кнопкой.
 */
export function highlight(code: string, lang: Lang = 'auto'): Token[] {
  if (lang === 'css') return scan(code, CSS, CSS_KINDS)
  if (code.startsWith('<')) return scan(code, HTML, HTML_KINDS)
  if (/^https?:\/\//.test(code)) return [{ text: code, kind: 'plain' }]
  return scan(code, JS, JS_KINDS)
}

/**
 * scan — один проход: что попало в группу, красится по её виду, что между
 * совпадениями — остаётся как есть.
 *
 * Ни один символ не теряется и не задваивается: куски между совпадениями режутся по
 * их же границам. Это свойство и проверяется юнитом («склеенные токены дают исходную
 * строку») — на нём же ловится любая будущая правка регулярок.
 */
function scan(code: string, re: RegExp, kinds: TokenKind[]): Token[] {
  const out: Token[] = []
  let last = 0
  for (const match of code.matchAll(re)) {
    const at = match.index
    if (at > last) out.push({ text: code.slice(last, at), kind: 'plain' })
    const group = match.slice(1).findIndex((value) => value !== undefined)
    out.push({ text: match[0], kind: kinds[group] ?? 'plain' })
    last = at + match[0].length
  }
  if (last < code.length) out.push({ text: code.slice(last), kind: 'plain' })
  return out
}
