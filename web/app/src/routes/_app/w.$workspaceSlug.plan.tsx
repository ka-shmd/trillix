import { createFileRoute, redirect } from '@tanstack/react-router'

// Адрес тарифа У ПРОСТРАНСТВА: закладки и ссылки, оставшиеся с тех суток, что
// страница тарифа прожила разделом пространства.
//
// Ведёт на аккаунтную страницу без вопросов: подписка одна на человека, и «тариф
// этого пространства» — вопрос, ответа на который нет (ADR §10, 2026-09-06).
// Пространство из адреса при этом не теряется: его расход виден в списке на самой
// странице, строкой с именем.
export const Route = createFileRoute('/_app/w/$workspaceSlug/plan')({
  beforeLoad: () => {
    throw redirect({ to: '/settings/plan' })
  },
})
