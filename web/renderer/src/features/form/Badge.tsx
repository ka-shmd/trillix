// БЕЙДЖ «Сделано в Trillix» — одна строка мелким приглушённым текстом внизу формы.
//
// Показывать или нет, решает СЕРВЕР (поле showBadge в ответе): в схеме лежит только
// намерение автора, а разрешает его тариф. Компонент об этом не знает и знать не
// должен — иначе решение оказалось бы в двух местах.
//
// Стоит и на форме, и на экранах «Спасибо»/«приём закрыт»: иначе бейдж снимается
// разглядыванием второго экрана.
//
// target="_blank" — респондент посреди заполнения не должен терять форму; rel к нему
// обязателен: без noopener открытая вкладка получает ссылку на нашу через
// window.opener.
export function Badge() {
  return (
    <p className="form-badge">
      <a href="https://trillix.ru" target="_blank" rel="noopener noreferrer">
        Сделано в Trillix
      </a>
    </p>
  )
}
