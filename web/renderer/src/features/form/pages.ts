import { type Block, isAnswerableType } from '@entities/formSchema'

import { type Errors } from './validation'

// Решения многостраничной формы (фаза 19) одной чистой функцией на каждое — по образцу
// planThankYou: у рендерера нет testing-library (список зависимостей заморожен, бюджет
// 45 КиБ не резиновый), поэтому всё, что можно проверить без DOM, живёт вне компонента.

// pageOfBlock — на какой странице лежит блок; -1, если его нет ни на одной (форму
// переопубликовали, пока вкладка стояла открытой, и блок из неё исчез).
export function pageOfBlock(pages: readonly Block[][], blockId: string): number {
  return pages.findIndex((page) => page.some((b) => b.id === blockId))
}

// firstQuestionIndex — позиция первого ОТВЕЧАЕМОГО блока страницы в полном потоке
// документа; -1, если вопросов на странице нет (страница-вступление из одного текста).
//
// Позиция, а не id: воронке нужен id, но «дальше или ближе» сравнивается только по
// порядку документа — тому же, которым считается самая дальняя точка визита по фокусу.
// Две меры одной величины в разных единицах разошлись бы на первом же прыжке назад —
// теперь это переброс к странице с ошибкой при отправке (ход назад у человека снят).
export function firstQuestionIndex(blocks: readonly Block[], page: readonly Block[]): number {
  const first = page.find((b) => isAnswerableType(b.type))
  return first === undefined ? -1 : blocks.indexOf(first)
}

// firstErrorPage — САМАЯ РАННЯЯ страница с ошибкой, или null, если вести некуда.
//
// Нужна одному сценарию, и он не редкий: «Отправить» проверяет форму целиком, а ошибка
// может оказаться не на той странице, где стоит человек (вернулся назад и стёр ответ,
// открыл форму с восстановленным черновиком, схема сменилась под открытой вкладкой). Без
// перехода экран сказал бы «проверьте выделенные поля», не показав ни одного, — тупик,
// из которого выход только F5 с потерей набранного.
//
// Самая ранняя, а не любая: карта ошибок неупорядочена, и прыжок на последнюю оставил бы
// человека идти назад через уже пройденные шаги. Ошибки на страницах, которых больше нет,
// в расчёт не идут — вести на них некуда.
export function firstErrorPage(pages: readonly Block[][], errors: Errors): number | null {
  let best: number | null = null
  for (const id of Object.keys(errors)) {
    const p = pageOfBlock(pages, id)
    if (p < 0) continue
    if (best === null || p < best) best = p
  }
  return best
}
