import { defineConfig } from 'vite'

// Сборка загрузчика встроенной формы (/embed/v1.js, фаза 20) — ОТДЕЛЬНАЯ от сборки
// рендерера, и это не удобство, а требование:
//
//   - формат IIFE, а не ES-модуль: файл подключается обычным <script src> с чужого
//     домена (модулю понадобился бы CORS), а однотеговый сниппет стоит на
//     document.currentScript, который в модулях не работает вовсе;
//   - имя без хеша: сниппет на чужом сайте не переписать, адрес обязан быть вечным.
//     Отсюда же и кэш на минуты, а не immutable (deploy/caddy/Caddyfile);
//   - свой бюджет: загрузчик грузится на ЧУЖОЙ странице, где мы гости, и его вес
//     считается отдельно от формы (scripts/check-bundle.mjs).
//
// emptyOutDir: false — конфиг запускается ПОСЛЕ основной сборки и не должен вынести
// её результат из dist/.
export default defineConfig({
  build: {
    outDir: 'dist/embed',
    emptyOutDir: false,
    // Чужая страница может быть какой угодно старости, а выигрыш от современного
    // синтаксиса на 3 КиБ кода нулевой.
    target: 'es2018',
    rollupOptions: {
      input: 'embed/v1.ts',
      output: { format: 'iife', entryFileNames: 'v1.js' },
    },
  },
})
