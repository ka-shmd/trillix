#!/usr/bin/env bash
# Регистр комментариев (CLAUDE.md «Комментарии в коде»): комментарий излагает
# факт, а не пересказывает историю и не убеждает читателя.
#
# Зачем: комментарии тянут около половины токенов боевого кода, и это налог на
# каждую сессию по файлу — агент перечитывает их целиком при каждом открытии.
# Мёртвый жанр здесь один и он машинно опознаваем: рассказ о том, что было
# раньше. Ему место в JOURNAL.md, который читается грепом и только по нужде.
#
# На ДЛИНУ проверка не смотрит сознательно: объяснение механизма стоит своих
# строк, и потолок в N строк заставлял бы резать как раз то, ради чего
# комментарии пишут. Ограничен жанр, а не объём.
#
# Убеждение («это не деталь, а суть правила») машиной не ловится — остаётся на
# ревью. Здесь только то, что умеет краснеть однозначно.
set -uo pipefail
cd "$(dirname "$0")/.."

fail=0
errs=0
err() {
	echo "::error::$1"
	echo "   $2"
	fail=1
	errs=$((errs + 1))
}
ok() { echo "  ✓ $1"; }
begin() { errs=0; }

# Генераты: sqlc и router-plugin пишут их сами, править бессмысленно.
is_generated() {
	case "$1" in
	internal/postgres/queries.sql.go | web/app/src/routeTree.gen.ts) return 0 ;;
	esac
	return 1
}

files=()
while IFS= read -r f; do
	is_generated "$f" || files+=("$f")
done < <(git ls-files '*.go' '*.ts' '*.tsx')

echo "Проверка регистра комментариев"
echo

# --- 1. История в коде без ссылки на журнал ----------------------------------
# Блок комментариев, который рассказывает «как было раньше», обязан ссылаться на
# запись JOURNAL.md — тогда история читается там, где её ищут, а в коде остаётся
# строка. Ссылка в ЛЮБОЙ строке блока снимает претензию ко всему блоку.
#
# Мутация: дописать «// Прежде здесь стоял closestVertical.» в любой .ts →
# краснеет; дописать в тот же блок «// история — JOURNAL, «Прицеливание»» → гаснет.
begin
# Маркеры узкие намеренно. «снят», «удалён», «отменён» сюда НЕ входят: ими
# описывают отсутствующую сегодня функциональность («рейл снят, возвращать
# нельзя»), и это живое предупреждение, а не история.
#
# «Прежде/Раньше/Ранее» ловятся только с ЗАГЛАВНОЙ и в начале предложения.
# Разделитель проверен на всём репозитории: заглавная форма открывает рассказ о
# прошлом (20 из 20 попаданий), строчная значит порядок и вся живая — «строится
# раньше authSvc», «строго раньше головы», «ошибку раньше, чем распухнет
# документ». Ловить обе значило бы 50% ложных, а сторож с ложными выключают.
#
# Классов символов ([а-яё]) в маркерах нет и быть не должно: grep трактует их
# по локали, и в CI с LC_ALL=C кириллический диапазон разъезжается по байтам.
# Литеральные слова байт-безопасны при любой локали.
markers='(//|\*|\.|:|\))[[:space:]]+(Прежде|Раньше|Ранее)[[:space:],]|до 20[0-9][0-9]-[0-9]|то этим заменено|перв(ая|ой) редакци|дв(е|ух) редакци|прошлой редакции'
found=0
for f in "${files[@]}"; do
	# Комментарии сворачиваются в блоки (строка начала + склеенный текст), чтобы
	# ссылка на журнал засчитывалась всему блоку, а не той строке, где написана.
	while IFS= read -r hit; do
		err "история в коде без ссылки на журнал: ${hit%%$'\t'*}" \
			"перенеси рассказ в JOURNAL.md, здесь оставь «// история — JOURNAL, «<заголовок>»»"
		found=$((found + 1))
	done < <(
		awk '
			function flush() {
				if (start > 0 && buf != "") print FILENAME ":" start "\t" buf
				start = 0; buf = ""
			}
			{
				line = $0
				sub(/^[ \t]+/, "", line)
				if (line ~ /^(\/\/|\*|\/\*|\{\/\*)/) {
					if (start == 0) start = FNR
					buf = buf " " line
				} else flush()
			}
			END { flush() }
		' "$f" | grep -E "$markers" | grep -v 'JOURNAL'
	)
done
[ $found -eq 0 ] && ok "истории в комментариях нет (или она со ссылкой на журнал)"

# --- 2. Отчёт: доля токенов на комментарии -----------------------------------
# Не проверка, а зеркало: правило в CLAUDE.md ссылается на это число, и оно
# должно быть под рукой, а не добываться разовым скриптом. Порога здесь нет
# намеренно — доля падает по мере переписывания файлов, и гейт по ней заставлял
# бы резать смысл ради цифры.
echo
echo "  Доля комментариев (оценка токенов: русский ~2.2 симв/токен, код ~3.6):"
# LC_ALL=C делает awk байт-ориентированным одинаково в mawk и gawk, после чего
# длина в СИМВОЛАХ получается снятием continuation-байтов UTF-8 (10xxxxxx).
# Без этого кириллица считается вдвое, и доля комментариев завышается: mawk
# длину в символах не умеет вовсе, а gawk умеет только в UTF-8-локали.
printf '%s\n' "${files[@]}" | LC_ALL=C awk '
	function zone(f) {
		if (f ~ /_test\.go$/ || f ~ /\.test\.tsx?$/ || f ~ /^e2e\//) return "тесты"
		return "боевой код"
	}
	function chars(s,   t) { t = s; gsub(/[\200-\277]/, "", t); return length(t) }
	{
		f = $0; z = zone(f); inblock = 0
		while ((getline line < f) > 0) {
			s = line; sub(/^[ \t]+/, "", s); sub(/[ \t]+$/, "", s)
			isc = 0
			if (inblock) { isc = 1; if (s ~ /\*\//) inblock = 0 }
			else if (s ~ /^(\/\/|\*|\{\/\*)/) { isc = 1; if (s ~ /^\{\/\*/ && s !~ /\*\//) inblock = 1 }
			else if (s ~ /^\/\*/) { isc = 1; if (s !~ /\*\//) inblock = 1 }
			if (isc) c[z] += chars(line) + 1; else k[z] += chars(line) + 1
		}
		close(f)
	}
	END {
		for (z in c) {
			tc = c[z] / 2.2; tk = k[z] / 3.6
			printf "    %-12s комментарии ~%7d ток, код ~%7d ток — %4.1f%% токенов\n", \
				z, tc, tk, 100 * tc / (tc + tk)
		}
	}
' | sort

echo
if [ $fail -ne 0 ]; then
	echo "Регистр комментариев: есть замечания"
else
	echo "Регистр комментариев: чисто"
fi
exit $fail
