else
	ok "нет сравнений с ролью вне internal/workspaces"
fi

# --- 8. Шкала кеглей и токены полотна (fields.css) ---------------------------
# Вид формы держат токены --rf-* в web/shared/fields/fields.css, и ни одна другая
# проверка их не видит: eslint про CSS не знает, tsc тем более, юниты меряют
# логику, а e2e — тексты и DOM. Сломанный токен не роняет ничего — он молча
# меняет вид, и заметить это может только глаз на нужном экране.
#
# Оба дефекта ниже реальные, оба из фазы 22 (слайс 1):
#   1. глобальная замена попала в определение базы, и --rf-font-size стал ссылаться
#      на шкалу, считаемую от него же. Цикл делает невалидной ВСЮ шкалу разом:
#      браузер откатывает font-size к наследуемому, шесть кеглей схлопываются в 16px;
#   2. шкала, объявленная готовыми размерами на :root, за базой не едет вовсе —
#      кастомное свойство подставляется там, где объявлено. Отсюда безразмерные
#      отношения --rf-ratio-* и умножение в ТОЧКЕ ИСПОЛЬЗОВАНИЯ.
# Мутации: вписать `--rf-font-size: var(--rf-ratio-title)`, `font-size: 1rem`,
# `--rf-ratio-title: 2.5rem` или вернуть `--rf-surface` → краснеет каждая.
begin
css=web/shared/fields/fields.css
# Комментарии вырезаются: в шапке и в :root лежат примеры-антипаттерны («просится
# --rf-size-title: …»), и без вычистки проверка краснела бы на собственном
# объяснении, почему так делать нельзя.
code=$(perl -0777 -pe 's{/\*.*?\*/}{}gs' "$css")

base=$(printf '%s\n' "$code" | grep -oP '^\s*--rf-font-size\s*:\s*\K[^;]+' || true)
if [ -z "$base" ]; then
	err "fields.css: база шкалы --rf-font-size не объявлена" "$css"
elif printf '%s' "$base" | grep -q 'var('; then
	err "fields.css: база шкалы ссылается на переменную — цикл погасит все кегли" "--rf-font-size: $base"
fi

# Значение ИЗВЛЕКАЕТСЯ и проверяется положительно, а не отвергается негативным
# lookahead: `\s*` перед (?!…) схлопывается в ноль, лукахед смотрит на пробел, не
# находит там числа — и пропускает ЛЮБУЮ строку. Первая редакция этой проверки
# ровно так и краснела на здоровом файле.
hits=$(printf '%s\n' "$code" | grep -oP '^\s*--rf-ratio-[a-z-]+\s*:\s*\K[^;]+' |
	sed 's/[[:space:]]*$//' | grep -vP '^[0-9.]+$' || true)
if [ -n "$hits" ]; then
	err "fields.css: отношение шкалы обязано быть безразмерным числом" "$hits"
fi

# --rf-submit-size — ЕДИНСТВЕННЫЙ разрешённый переход через второй токен: кегль
# кнопки автор задаёт числом, а пока не задал, токен выведен от базы. Что он выведен
# именно от неё, проверяется отдельно ниже — иначе разрешение здесь открыло бы дорогу
# любому литералу, спрятанному за собственным токеном.
hits=$(printf '%s\n' "$code" | grep -oP '^\s*font-size:\s*\K[^;]+' |
	grep -vF 'var(--rf-font-size)' | grep -vF 'var(--rf-submit-size)' || true)
if [ -n "$hits" ]; then
	err "fields.css: кегль литералом — размер берётся от базы через --rf-ratio-*" "$hits"
fi

submit=$(printf '%s\n' "$code" | grep -oP '^\s*--rf-submit-size\s*:\s*\K[^;]+' || true)
if [ -z "$submit" ]; then
	err "fields.css: --rf-submit-size не объявлен — кегль кнопки ссылается в пустоту" "$css"
elif ! printf '%s' "$submit" | grep -qF 'var(--rf-font-size)'; then
	err "fields.css: --rf-submit-size оторван от базы шкалы" "--rf-submit-size: $submit"
fi

hits=$(printf '%s\n' "$code" | grep -nP '^\s*line-height:.*var\(--rf-(font-size|ratio-)' || true)
if [ -n "$hits" ]; then
	err "fields.css: line-height поехал за базой — числа обязаны совпадать с h-7/h-6 редактора" "$hits"
fi

# Осиротевшее обращение: var(--rf-foo) без объявления даёт пустое значение и
# молча снимает заливку или контур.
declared=$(printf '%s\n' "$code" | grep -oP '^\s*\K--rf-[a-z0-9-]+(?=\s*:)' | sort -u)
usedv=$(printf '%s\n' "$code" | grep -oP 'var\(\s*\K--rf-[a-z0-9-]+' | sort -u)
hits=$(comm -13 <(printf '%s\n' "$declared") <(printf '%s\n' "$usedv"))
if [ -n "$hits" ]; then
	err "fields.css: обращение к необъявленному токену" "$hits"
fi

# Холст страницы и заливка контрола — разные токены (фаза 22 §3.1): пока это был
# один --rf-surface, «цветная страница с белыми карточками» была невыразима.
if printf '%s' "$code" | grep -q -- '--rf-surface'; then
	err "fields.css: --rf-surface вернулся — холст и заливка обязаны быть разными токенами" "$css"
fi

# СОСТАВНОЙ ТОКЕН В ГОЛОМ :root — тот же дефект, что «шкала на :root», только на
# цветах. Кастомное свойство подставляется на том элементе, где объявлено: токен,
# ссылающийся на другой токен, посчитается на корне со значениями СВЕТЛОЙ темы и
# унаследуется вниз готовой строкой, а .rf-theme-dark на контейнере уже ничего не
# изменит. Так тёмная тема при первой сборке получила поля с кольцом светлой — то
# есть поля, исчезнувшие с фона. Лечение: такие токены живут в правиле
# `:root, .rf-theme`, которое матчит и корень, и контейнер темы.
# Мутация: перенести --rf-field-shadow обратно в :root → краснеет.
rootblock=$(printf '%s\n' "$code" | awk '/^:root \{/{f=1;next} f&&/^\}/{exit} f')
hits=$(printf '%s\n' "$rootblock" | grep -nP '^\s*--rf-[a-z0-9-]+\s*:.*var\(--rf-' || true)
if [ -n "$hits" ]; then
	err "fields.css: составной токен в голом :root — за темой он не поедет (правило :root, .rf-theme)" "$hits"
fi

# ФОЛБЭК В var(--rf-…, светлое-значение) У РЕНДЕРЕРА — готовая вспышка белым.
# Второй аргумент писался «на случай, если общий CSS не подгрузился», но такого
# случая не бывает: main.tsx импортирует index.css и fields.css, vite складывает их
# в ОДИН файл — доезжают оба или ни одного. Зато выписаны фолбэки светлыми числами,
# и на тёмной форме каждый из них — белый текст или белый фон в момент, когда токен
# почему-либо не разрешился (фаза 22 §11).
# Мутация: вернуть `color: var(--rf-muted, #6b7280)` в .status-detail → краснеет.
rcss=web/renderer/src/index.css
hits=$(perl -0777 -pe 's{/\*.*?\*/}{}gs' "$rcss" | grep -nP 'var\(\s*--rf-[a-z0-9-]+\s*,' || true)
if [ -n "$hits" ]; then
	err "renderer/index.css: фолбэк в var(--rf-…) — на тёмной теме он врёт светлым значением" "$hits"
fi
ok_if_clean "токены и шкала кеглей fields.css сходятся"


# --- 8.5. Цвета тем в панели «Оформление» ↔ fields.css -----------------------
# Строка палитры в шторке показывает не «по теме», а цвет, который форма рисует
# сейчас (решение владельца 2026-08-28), — значит кабинет знает три токена каждой
# темы наизусть (designDefaults.ts). Копия разъезжается молча и в худшую сторону:
# панель уверенно показывает цвет, которого на форме нет, и автор подбирает свой
# относительно вранья.
# Мутация: поменять цифру в CSS_TOKENS или в --rf-accent тёмной темы → краснеет.
begin
defaults=web/app/src/features/forms/builder/designDefaults.ts
for pair in "light|:root {" "dark|.rf-theme-dark {"; do
	theme=${pair%%|*}
	sel=${pair##*|}
	cssblock=$(printf '%s\n' "$code" | awk -v s="$sel" 'index($0,s)==1{f=1;next} f&&/^\}/{exit} f')
	tsblock=$(awk -v t="  $theme: {" 'index($0,t)==1{f=1;next} f&&/^  \},/{exit} f' "$defaults")
	for key in canvas field text placeholder border accent button buttonText; do
		var=$(grep -oP "^\s*$key: '\K--rf-[a-z-]+(?=')" "$defaults" || true)
		if [ -z "$var" ]; then
			err "designDefaults.ts: у цвета «$key» не назван токен в PALETTE_CSS_VAR" "$defaults"
			continue
		fi
		want=$(printf '%s\n' "$cssblock" | grep -oP "^\s*$var\s*:\s*\K[^;]+" || true)
		got=$(printf '%s\n' "$tsblock" | grep -oP "^\s*$key:\s*'\K[^']+" || true)
		if [ -z "$want" ]; then
			err "fields.css: у темы «$theme» нет токена $var — зеркалу панели нечего сверять" "$css"
		elif [ "$want" != "$got" ]; then
			err "designDefaults.ts: цвет «$key» темы «$theme» разошёлся с fields.css" \
				"fields.css: $want · панель: ${got:-—}"
		fi
	done
done
ok_if_clean "цвета тем в панели оформления сходятся с fields.css"


# --- 9. Брендовая картинка карточки ссылки: кабинет ↔ рендерер ---------------
# Файл лежит в двух местах намеренно: публичная страница берёт его с домена
# рендерера (OG_IMAGE_URL), а предпросмотр в кабинете — со своего, потому что
# прод-CSP кабинета режет чужие origin (img-src 'self'). Копии расходятся молча:
# заменил одну — предпросмотр начинает врать про то, что увидит получатель ссылки,
# и заметить это можно, только отправив себе ссылку.
# Мутация: `printf x >> web/app/public/og-preview.png` → краснеет.
begin
if ! cmp -s web/app/public/og-preview.png web/renderer/public/og-preview.png; then
	err "og-preview.png в кабинете и рендерере разошлись — предпросмотр карточки врёт" \
		"сверь web/app/public/og-preview.png и web/renderer/public/og-preview.png"
fi
ok_if_clean "картинка карточки ссылки по умолчанию одинакова в обоих фронтах"

# --- 10. Тона форм на полотне расписания: класс ↔ правило --------------------
# Цвет записи собирается ИМЕНЕМ КЛАССА (`sc-tone-N`, eventClass.ts), а рисуется
# правилом в canvas.css. Между ними нет ничего: класс без правила компилируется,
# проходит линт и молча даёт белую карточку — ровно так тона и пропали, а заметил
# это владелец глазами. Юнит-тест сторожит только половину пары: css-импорт vitest
# не обрабатывает, а `node:fs` валит `tsc -b` (типов Node в кабинете нет).
# Мутация: переименуй `.sc-tone-8` в canvas.css → краснеет.
begin
tones_css=web/app/src/features/schedules/canvas.css
tones_ts=web/app/src/features/schedules/formColor.ts
tones_want=$(grep -oP '^const TONES = \K\d+' "$tones_ts" || true)
tones_got=$(grep -c '^\.sc-canvas \.sc-tone-[0-9]* {' "$tones_css" || true)
if [ -z "$tones_want" ]; then
	err "formColor.ts: не найдено «const TONES = N» — сверять правила тонов не с чем" "$tones_ts"
elif [ "$tones_want" != "$tones_got" ]; then
	err "canvas.css: правил .sc-tone-* — $tones_got, а тонов формы $tones_want" \
		"класс без правила рисует белую карточку, правило без класса — мёртвые строки"
fi
if ! grep -q 'sc-tone-\${' web/app/src/features/schedules/eventClass.ts; then
	err "eventClass.ts: класс записи собирается без префикса sc-tone-" \
		"голый номер тона ни с одним правилом не совпадёт — карточка выйдет белой"
fi
ok_if_clean "тона форм на полотне: класс собирается и правило для него есть"

echo
if [ $fail -ne 0 ]; then
	echo "Проверка документов НЕ пройдена — почини расхождение и повтори."
	exit 1
fi
echo "Документы и структурные инварианты сходятся с кодом."
