-- 0039: своё оформление становится платным (решение владельца 2026-08-28).
--
-- Последний из трёх ключей оформления, заведённых 0018 открытыми. Про два решение
-- приняли тогда же (0019), про этот было записано «решения пока нет» — теперь есть:
-- раздел «Дополнительно» в шторке оформления (лэйаут, поля, кнопки) уходит за
-- пейгейт целиком, а вместе с ним и цвета со шрифтом — ключ у них общий.
--
-- ЧТО ОСТАЁТСЯ БЕСПЛАТНЫМ, и это не изменилось: обе готовые темы и системный шрифт.
-- Гейт ставится на созданную ценность, а не на настройку (DesignPaidFeatures в
-- internal/domain/design.go — там же полный перечень платного).
--
-- legacy_free ГЕЙТИТСЯ ВМЕСТЕ С free — по прямому решению владельца, в отличие от
-- 0019, где грандфазерить было нечего. Здесь есть: ключ был открыт с фазы 22, и
-- форма бесплатного автора, у которой уже задан цвет или ширина колонки, перестанет
-- публиковаться, пока настройку не снимут или не оплатят тариф. Черновик при этом
-- сохраняется на любом тарифе — стена стоит на публикации (инвариант 3).
--
-- Обратно — один UPDATE без выкатки, как и всё в plans.limits.
UPDATE plans
SET limits = limits || '{"form_design_custom": false}'::jsonb
WHERE code IN ('free', 'legacy_free');
