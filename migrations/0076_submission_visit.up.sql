-- ADR §10). Ответы получают разрез по источнику, устройству и месту визита.
--
-- БЕЗ FK — так же, как partial_submissions.visit_id: бикон визита мог не доехать
-- (CSP, лимитер), а визит может уйти по сроку хранения; ответ от этого не теряется и
-- не ломается, у него просто нет меток. Индекс не нужен: визит ищется по своему PK.
--
-- Только для ответов, принятых после миграции: старые с визитами не связать —
-- form_visits.submitted булево без ссылки на ответ, подбор по времени был бы
-- угадыванием.
ALTER TABLE submissions ADD COLUMN visit_id UUID;
