-- 0028: аватар пользователя — ключ картинки в объектном хранилище.
--
-- Хранится КЛЮЧ, а не URL (docs/S3.md §5, то же правило, что у settings.imageKey
-- в схеме формы): абсолютный адрес собирается из MEDIA_BASE_URL, и переезд между
-- провайдерами хранилища не требует переписывать таблицу.
--
-- NULL = аватара нет, кабинет рисует кружок с инициалами. Пустая строка тем же
-- смыслом не наделяется: два способа записать «нет» разъезжаются в первом же
-- запросе, который сравнивает с одним из них (та же причина, что у 0021).
--
-- Ключ контент-адресный (avatars/<sha256>.<ext>), поэтому UNIQUE здесь не нужен и
-- вреден: два человека с одинаковой картинкой делят один объект, и это штатно.
ALTER TABLE users ADD COLUMN avatar_key TEXT;
