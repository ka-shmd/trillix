-- 0058: позвать в пространство можно только ССЫЛКОЙ (решение владельца
-- 2026-09-08, ADR §10). Приглашение по адресу почты вырезано целиком —
-- отменяет 0017 в части таблицы.
--
-- Ссылка отличается от приглашения тремя вещами сразу, и потому это отдельная
-- таблица, а не `email = NULL` в прежней:
--
--   * она МНОГОРАЗОВАЯ — по ней входит сколько угодно людей, поэтому нет ни
--     used_at, ни атомарного потребления токена;
--   * она НЕ НАЗЫВАЕТ человека — сверять на принятии нечего, факт владения
--     строкой и есть право;
--   * её ОТЗЫВАЮТ явно, а не вытесняют повторной отправкой.
--
-- ⚠ ТОКЕН ХРАНИТСЯ СЫРЫМ, И ЭТО ЕДИНСТВЕННОЕ ТАКОЕ МЕСТО В ПРОДУКТЕ. Сессии
-- (0002), сброс пароля (0011), подтверждение почты (0012) и прежние
-- приглашения (0017) лежат SHA-256: утечка дампа не даёт рабочих ссылок. Здесь
-- иначе, потому что ценность ссылки в повторном копировании — кинул в чат, люди
-- заходят, — а из хеша сырой токен не достать. Калибр секрета мерян и назван в
-- ADR §10: роль editor в ОДНОМ пространстве, 24 часа жизни, отзыв кнопкой.
CREATE TABLE workspace_join_links (
    -- token — сырой 256-битный токен в base64url; он же PRIMARY KEY, потому что
    -- вход по ссылке ищет строку ровно по нему.
    token        TEXT PRIMARY KEY,
    workspace_id UUID NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    -- Роль, которую даёт ссылка. Тот же CHECK, что был у приглашений, и по той
    -- же причине: владелец ровно один (0016), а передача владения — отдельное
    -- действие (0058 её не касается). CHECK выражает правило, а не перечисляет
    -- допустимые роли: список ролей ещё вырастет.
    role         TEXT NOT NULL CHECK (role <> 'owner'),
    created_by   UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at   TIMESTAMPTZ NOT NULL,
    revoked_at   TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ОДНА живая ссылка на пространство. «Создать новую» = отозвать прежнюю и
-- выписать следующую в одной транзакции, поэтому двух годных не бывает никогда
-- — а значит, вопрос «какая из них настоящая» не возникает ни у владельца, ни у
-- кода. Индекс частичный: отозванных за жизнь пространства накопится сколько
-- угодно.
--
-- Истёкшая, но не отозванная ссылка место занимает — и это правильно: следующая
-- выписывается тем же путём, через отзыв.
CREATE UNIQUE INDEX idx_join_links_active
    ON workspace_join_links (workspace_id) WHERE revoked_at IS NULL;

-- Для фоновой чистки истёкших (тот же приём, что у прежних приглашений).
CREATE INDEX idx_join_links_expires ON workspace_join_links (expires_at);

-- Приглашений по почте в продукте больше нет. Непринятые теряются: они жили
-- неделю, а обрабатывать ссылку из письма больше некому — ручка снята вместе с
-- таблицей.
DROP TABLE IF EXISTS invitations;
