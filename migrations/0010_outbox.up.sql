-- 0010: транзакционный outbox — надёжная доставка сообщений во внешний мир
-- (почтовая фаза, слайс A). Решения и отвергнутые альтернативы — docs/ARCHITECTURE.md §10 (ADR).

-- Одна таблица на все каналы доставки (email сейчас; вебхуки/телега — потом без
-- переделки схемы). Строка — НАМЕРЕНИЕ ДОСТАВКИ, а не сырое доменное событие:
-- продюсер (сервис) сам знает интент и кладёт «доставить payload по каналу channel».
-- Диспетчер — тупой релей: выбирает готовые строки, отдаёт нужному транспорту,
-- ретраит при сбое. Внутренние реакции через outbox не ходят (это была бы доставка
-- из своей БД в свою же) — только наружу. Обоснование рамки — ADR §10.
CREATE TABLE outbox (
    id              UUID PRIMARY KEY,                    -- UUIDv7 (domain.NewID)
    channel         TEXT NOT NULL,                       -- email | (webhook | telegram — потом)
    payload         JSONB NOT NULL,                      -- намерение: получатель + шаблон + данные (форма зависит от канала)
    attempts        INT NOT NULL DEFAULT 0,              -- сколько раз пытались доставить (растёт при неудаче)
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),  -- не пытаться раньше этого момента (экспоненциальный бэкофф)
    last_error      TEXT,                                -- диагностика последней неудачи (не секрет); NULL пока не падало
    sent_at         TIMESTAMPTZ,                         -- NULL = ещё не доставлено; проставляется при успехе (терминально)
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Горячий запрос диспетчера — «что готово к отправке»: недоставленные строки,
-- чей next_attempt_at уже наступил. Частичный индекс по sent_at IS NULL: доставленные
-- строки (растущий архив) в индекс не попадают, выборка не деградирует с их числом.
CREATE INDEX idx_outbox_pending ON outbox (next_attempt_at) WHERE sent_at IS NULL;
