--
-- Значение ОТКРЫТОЕ (null — без ограничения) на всех планах: сама запись тарифом
-- не гейтится, это не объём, а способ работы (design/booking.md §14). Включение
-- лимита потом — один UPDATE без выкатки, как у всех лимитов.
