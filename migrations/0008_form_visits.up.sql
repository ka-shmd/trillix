-- 0008: визиты публичной формы (фаза 8.5, шаг 6). Строка на визит, а не лог
-- событий и не серверный счётчик открытий (ADR §10): воронке нужно одно число на
-- визит — докуда дошёл человек, — а серверный счёт занижен кэшем GET формы
-- (max-age=60/ETag/304) и считает краулеров вместо людей.
--
-- Приватность: IP не пишется ни в открытом виде, ни в хеше; cookie/localStorage
-- рендерер не заводит — id визита живёт в памяти страницы и умирает с ней, поэтому
-- человек между визитами не узнаётся (сознательно).

CREATE TABLE form_visits (
    id              UUID PRIMARY KEY,            -- UUIDv7, генерируется клиентом → повторный бикон упирается в PK (апсерт)
    form_id         UUID NOT NULL REFERENCES forms(id) ON DELETE CASCADE,
    form_version_id UUID NOT NULL REFERENCES form_versions(id),
    -- Самая дальняя точка визита: id блока, которого человек коснулся последним.
    -- NULL = открыл и ушёл, не тронув ни одного вопроса. Именно block_id, а не
    -- индекс: подписи и порядок всё равно берутся из схемы версии на чтении, а
    -- block_id переживёт приход многостраничных форм без миграции.
    last_block_id   TEXT,
    -- Порядковый номер бикона в рамках визита (0 — «открыли», дальше растёт).
    -- Бикон уходит через navigator.sendBeacon, доставка не упорядочена, а
    -- visibilitychange срабатывает на каждое переключение вкладки — без seq поздний
    -- бикон отбрасывал бы визит назад по воронке. Апсерт двигает last_block_id
    -- ТОЛЬКО при seq строго больше сохранённого.
    seq             SMALLINT NOT NULL DEFAULT 0 CHECK (seq >= 0),
    -- Ставит ТОЛЬКО сервер при приёме ответа (тело бикона это поле не содержит):
    -- иначе конверсия подделывается с клиента, а второй бикон затирал бы её обратно.
    submitted       BOOLEAN NOT NULL DEFAULT false,
    meta            JSONB NOT NULL DEFAULT '{}', -- user_agent, referer, utm (без IP)
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Счётчики «N просмотров → M ответов» по форме: обе величины берутся одним
-- сканом по этому индексу (count(*) и count(*) FILTER (WHERE submitted)).
CREATE INDEX idx_form_visits_form ON form_visits (form_id);
