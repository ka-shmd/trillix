-- 0044: раздел «Поведение» — как форма ведёт себя у респондента (решение владельца
-- 2026-08-29).
--
-- Живые колонки, как progress (0040) и branding (0038): это не документ, который
-- снапшотится публикацией, а поведение выдачи — правка обязана действовать со
-- следующего же открытия формы, без перепубликации.
--
-- auto_jump — переходить на следующую страницу сразу после ответа. Работает только
-- там, где на странице ОДИН отвечаемый вопрос выбором (один из списка, выпадающий
-- список, шкала): у поля с текстом «ответ дан» нет момента, а у страницы с двумя
-- вопросами прыжок унёс бы человека от второго.
--
-- save_locally — хранить незавершённые ответы так, чтобы они пережили закрытие
-- вкладки. ⚠ ЭТО НЕ ТО ЖЕ, что collect_partial (0033): там черновик уезжает НА
-- СЕРВЕР и его видит автор формы, здесь ответы остаются в браузере респондента и
-- никуда не отправляются. Рендерер и так хранит их в sessionStorage (переживают
-- перезагрузку вкладки); колонка переключает хранилище на localStorage — то есть
-- «вернуться завтра», а не «пережить F5».
--
-- Обе выключены по умолчанию: ни прыжки по страницам, ни хранение ответов дольше
-- сессии не должны включаться за автора.
ALTER TABLE forms
    ADD COLUMN auto_jump    BOOLEAN NOT NULL DEFAULT false,
    ADD COLUMN save_locally BOOLEAN NOT NULL DEFAULT false;
