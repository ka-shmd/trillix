-- 0007: закрытие формы (фаза 8.5, шаг 4). Три ЖИВЫЕ настройки формы-уровня,
-- сознательно НЕ в JSONB-схеме (ADR §10, ARCHITECTURE §3.4): схема снапшотится при
-- публикации и внутри версии неизменна, а эти настройки обязаны меняться без
-- перепубликации — владелец правит лимит/дату, проверка идёт против текущего значения.
--   close_at        — форма закрывается ПОСЛЕ этого момента (NULL = без ограничения по дате);
--   response_limit  — максимум принятых ответов (NULL = без лимита; жёсткий кап, ADR §10);
--   closed_message  — текст на экране «приём закрыт» (NULL/пусто → дефолт рендерера).
-- «Фактически закрыта» ВЫЧИСЛЯЕТСЯ на чтении (status=closed ИЛИ дата прошла/лимит
-- достигнут), status по дате не флипается — крон не нужен, продление даты
-- переоткрывает мгновенно. Все три NULL по умолчанию — обратная совместимость.
ALTER TABLE forms ADD COLUMN close_at       TIMESTAMPTZ;
ALTER TABLE forms ADD COLUMN response_limit INT CHECK (response_limit > 0);
ALTER TABLE forms ADD COLUMN closed_message TEXT;
