-- 0036: своя карточка ссылки на форму (задача вне плана, 2026-08-27).
--
-- forms.link_preview — ЖИВАЯ КОЛОНКА, а не поле схемы, и это то же решение, что у
-- close_at/response_limit (0007) и collect_partial (0033): карточка ссылки описывает
-- не документ, который увидит респондент, а то, как ссылка выглядит при пересылке.
-- Правка обязана доезжать до мессенджера без перепубликации — иначе автор правит
-- заголовок карточки, шлёт ссылку и видит прежний текст. Схема при этом не растёт
-- на пять полей и schemaVersion не двигается.
--
-- JSONB, а не пять колонок: поля меняются вместе (окно сохраняет карточку целиком),
-- по отдельности не ищутся и в WHERE не участвуют. Структуру валидирует приложение
-- (domain.ValidateLinkPreview) — БД-констрейнтов на форму JSONB не вешаем
-- (migrations/CLAUDE.md). NULL = карточку не настраивали, публичная страница берёт
-- прежние дефолты (заголовок формы, тизер из подписей, брендовая og-картинка).
ALTER TABLE forms ADD COLUMN link_preview JSONB;

-- form_link_preview — ключ гейта в лимитах ВСЕХ планов, включая legacy_free:
-- молчание плана про известный каталогу ключ считается ошибкой конфигурации и
-- краснеет TestPlansCoverCatalog.
--
-- ОТКРЫТ ВСЕМ (true), то есть гейт приезжает на прод выключенным — так же, как
-- приехали ключи оформления в 0018. Закрыть на Free — один UPDATE без выкатки:
--
--   UPDATE plans SET limits = jsonb_set(limits, '{form_link_preview}', 'false')
--    WHERE code IN ('free', 'legacy_free');
UPDATE plans SET limits = limits || '{"form_link_preview": true}'::jsonb;
