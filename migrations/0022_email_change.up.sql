-- 0022: смена адреса аккаунта (фаза 23 DEV-PLAN, слайс D). Двухшаговая: новый
-- адрес встаёт в users только после перехода по ссылке, отправленной НА НЕГО.
-- Иначе опечатка в адресе = потерянный аккаунт, потому что email и есть
-- единственный ключ восстановления (сброс пароля ходит туда же).
--
-- Отдельная таблица, а не колонка new_email в email_verification_tokens (0012):
-- токены выглядят одинаково, но означают разное — тот подтверждает адрес,
-- КОТОРЫЙ УЖЕ СТОИТ в users, этот переносит users.email на другой. Слить их
-- значит поставить в потребляющий UPDATE ветку по наличию new_email, то есть
-- завести место, где однажды подтвердят не тот адрес.
--
-- Устройство — по образцу 0011/0012: в БД только SHA-256 сырого токена,
-- одноразовость и срок колонками, потребление атомарным UPDATE.
CREATE TABLE email_change_tokens (
    token_hash BYTEA PRIMARY KEY,       -- SHA-256 сырого токена (не логируется)
    user_id    UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    new_email  TEXT NOT NULL CHECK (new_email = lower(new_email)),
    expires_at TIMESTAMPTZ NOT NULL,    -- 24 часа: письмо могут открыть не сразу
    used_at    TIMESTAMPTZ,             -- NULL = не использован (одноразовость)
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Для фоновой чистки истёкших/использованных (аналог idx_password_reset_tokens_expires).
CREATE INDEX idx_email_change_tokens_expires ON email_change_tokens (expires_at);

-- UNIQUE на новый адрес здесь НЕ ставится сознательно: запрос смены — это
-- намерение, а не бронь. Занятость адреса проверяется дважды (при запросе и при
-- подтверждении), и единственный настоящий сторож — UNIQUE на users.email:
-- бронировать адрес строкой в этой таблице значило бы дать любому желающему
-- способ занять чужой адрес на сутки, ничего не подтверждая.
