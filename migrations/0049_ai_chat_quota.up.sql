-- 0049: числа квоты под ЧАТ (фаза 26, слайс E; решение владельца 2026-09-01).
--
-- В `0048` стояли 10 и 100 — квота «одна генерация = одна форма». С чатом единицей
-- расхода стало СООБЩЕНИЕ автора, и десять сообщений это один разговор, а не десять
-- форм. Прикидка расхода на сообщение: ~2900 входных токенов (инструкция, схема
-- ответа, форма планом, история, запрос) и ~500 выходных — порядка 0,7 ₽, то есть
-- 30 сообщений дают ~20 ₽ на аккаунт в месяц, 500 — ~350 ₽.
--
-- Ключ не переименовывается: `ai_generations` — «вызов модели», и сообщение чата это
-- он и есть; переименование стоило бы миграции ради красоты.
UPDATE plans SET limits = jsonb_set(limits, '{ai_generations}', '500'::jsonb);
UPDATE plans SET limits = jsonb_set(limits, '{ai_generations}', '30'::jsonb)
 WHERE code IN ('free', 'legacy_free');
