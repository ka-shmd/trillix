-- 0052: номер редакции события календаря (перенос записи автором, ADR §10).
--
-- Приглашение и его отмена связаны по UID, и клиент вправе ОТБРОСИТЬ документ, чей
-- SEQUENCE не больше уже принятого (RFC 5545). Пока переносов не было, номера
-- обходились константами: приглашение 0, отмена 1. Перенос ломает это молча — он
-- тоже REQUEST, его бывает несколько подряд, и вторая правка с прежним номером
-- просто не доехала бы до чужого календаря.
--
-- Поэтому номер живёт в строке брони и растёт при каждом изменении времени; оба
-- письма берут его отсюда, а отмена прибавляет единицу.
ALTER TABLE bookings ADD COLUMN revision INT NOT NULL DEFAULT 0;
