-- 0019: свой CSS и снятие бейджа становятся платными (решение владельца 2026-08-10).
--
-- Миграция 0018 завела три ключа оформления ОТКРЫТЫМИ всем планам — раскладка
-- упиралась в нерешённое «когда включать Free». Два из трёх решены: `form_custom_css`
-- и `form_branding` уходят за пейгейт, `form_design_custom` (цвета, шрифт, лэйаут)
-- остаётся открытым — про него решения пока нет.
--
-- Почему именно эти два. Свой CSS — не настройка, а доступ к вёрстке, и он единственная
-- возможность продукта, у которой цена риска ненулевая (спрятанный текст согласия —
-- риск площадки, спека design/theme.md §10.2). Снятие бейджа — классическая покупка
-- «уберите ваш логотип с моей страницы», и продавать её бессмысленно, пока бейдж
-- доступен бесплатно.
--
-- legacy_free ГЕЙТИТСЯ ВМЕСТЕ С free, хотя обычно грандфазеринг сохраняет прежнее:
-- сохранять нечего — обе возможности родились в этой же фазе и ни у кого никогда не
-- были включены. Оставить их legacy-плану значило бы раздать Pro всем, кто успел
-- зарегистрироваться до тарифов.
--
-- Обратно — один UPDATE без выкатки, как и всё в plans.limits.
UPDATE plans
SET limits = limits || '{"form_custom_css": false, "form_branding": false}'::jsonb
WHERE code IN ('free', 'legacy_free');
