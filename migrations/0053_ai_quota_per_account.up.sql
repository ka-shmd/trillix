-- 0053: расход ассистента переезжает с воркспейса на АККАУНТ (ADR §10,
-- решение владельца 2026-09-06).
--
-- Почему: подписка принадлежит аккаунту с 0016, а счётчик сообщений остался
-- воркспейсным — значит квота умножалась числом пространств, и множитель ничем
-- не ограничен (`workspaces` во всех планах стоит null). Для этого ключа это не
-- косметика: безлимита у него нет ни на одном плане намеренно — каждый вызов
-- оплачен нами у провайдера, — и открытый счёт открывался кнопкой «Новое
-- пространство».
--
-- Колонка снимается ТОЙ ЖЕ миграцией, а не через релиз, как требует общее правило
-- migrations/CLAUDE.md: правило страхует бинарник предыдущей версии на тех
-- секундах выкатки, пока он работает с новой схемой. Здесь цена страховки выше
-- цены риска — единственный путь старого кода к этой колонке — списание после
-- удачного вызова модели, то есть в худшем случае одна пятисотка на одно
-- сообщение в окне выкатки, — а живая колонка-двойник означала бы два ответа на
-- вопрос «сколько израсходовано».

-- 1. Расход аккаунта за период. Отдельная таблица, а не колонка в subscriptions:
--    расход накапливается ПО ПЕРИОДАМ и обнуляется первым числом, а подписка —
--    одна строка на человека без истории. Период тот же, что у workspace_usage
--    (первое число месяца по Москве, считает приложение), и обнуляются они
--    вместе — но считают разное, поэтому таблицы разные.
--
--    ON DELETE CASCADE: удалили человека — его расход больше ничей.
CREATE TABLE account_usage (
    user_id        UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    period         DATE NOT NULL,
    ai_generations BIGINT NOT NULL DEFAULT 0 CHECK (ai_generations >= 0),
    PRIMARY KEY (user_id, period)
);

-- 2. Перенос накопленного — СУММОЙ по пространствам владельца, а не максимумом и
--    не нулём. Сумма и есть правда: эти сообщения человек израсходовал, и обнулять
--    их переездом значит раздать всем по лишней квоте в месяц переезда.
--
--    Пространства без владельца (сироты от удаления пользователя, TD-53) не дают
--    строк и ничего не ломают: их расход не принадлежит никому.
INSERT INTO account_usage (user_id, period, ai_generations)
SELECT o.user_id, u.period, sum(u.ai_generations)
  FROM workspace_usage u
  JOIN workspace_members o ON o.workspace_id = u.workspace_id AND o.role = 'owner'
 WHERE u.ai_generations > 0
 GROUP BY o.user_id, u.period;

-- 3. Старый счётчик снимается: два источника одного числа разъезжаются, и
--    разъехались бы молча — расход показывается автору, а не сверяется.
ALTER TABLE workspace_usage DROP COLUMN ai_generations;
