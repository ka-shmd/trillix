-- 0035: у пространства появляется публичный короткий ключ — как у формы.
--
-- Тот же приём, что forms.slug (0003): PK остаётся UUIDv7 (на него ссылаются
-- семь таблиц, он обязан быть вечным), а наружу — в адрес кабинета — уезжает
-- nanoid(10). Причина у пространства мягче, чем у формы (её ссылку видит
-- респондент, адрес пространства — только его участники), но следствия те же:
-- адрес читаем человеком и не выдаёт временем создания порядок регистрации.
--
-- Генерирует slug приложение (domain.NewSlug) — здесь только колонка и разовый
-- бэкфилл уже существующих строк.

ALTER TABLE workspaces ADD COLUMN slug TEXT;

-- Бэкфилл: 60 бит честной энтропии без расширений. gen_random_uuid() —
-- встроенный CSPRNG (PG13+), его 16 байт перегоняются в base64 и обрезаются до
-- десяти символов; translate приводит алфавит к тому же, что у domain.NewSlug
-- («+/» → «-_»), поэтому старые и новые ключи неразличимы на вид.
--
-- pgcrypto (gen_random_bytes) намеренно не подключается: в проекте нет ни одного
-- CREATE EXTENSION, и заводить первое ради одной строки бэкфилла — плохая сделка.
UPDATE workspaces
SET slug = substr(
    translate(
        encode(decode(replace(gen_random_uuid()::text, '-', ''), 'hex'), 'base64'),
        '+/=', '-_0'
    ), 1, 10)
WHERE slug IS NULL;

ALTER TABLE workspaces ALTER COLUMN slug SET NOT NULL;

-- UNIQUE — страховка от коллизии: 60 бит делают её астрономически редкой, но
-- повтор обязан стать ошибкой вставки, а не тихим дублем (как у forms.slug).
ALTER TABLE workspaces ADD CONSTRAINT workspaces_slug_key UNIQUE (slug);
