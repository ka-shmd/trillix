-- 0038: намерение автора о бейдже «Сделано в Trillix» переезжает из схемы формы
-- в живую колонку (решение владельца 2026-08-28, ADR §10).
--
-- Бейдж — не часть документа, как вопрос или заголовок: он про площадку, и его
-- наличие обязано считаться при заходе человека на форму. В схеме намерение
-- доезжало до респондента только следующей публикацией: чтобы отдать форму без
-- бейджа, автор публиковал её дважды (экран вставки, где живёт тумблер,
-- открывается после первой публикации).
--
-- Точка гейта не меняется: право тарифа по-прежнему спрашивается при отдаче
-- публичной формы, поэтому даунгрейд возвращает бейдж сам. Колонка несёт только
-- намерение — ровно то, что раньше лежало в схеме.
--
-- true = показывать. «Не показывать» — единственное осмысленное намерение автора,
-- и в схеме оно выражалось наличием ключа; в колонке оба состояния равноправны, и
-- отдельного «не задано» у неё нет.
ALTER TABLE forms ADD COLUMN branding BOOLEAN NOT NULL DEFAULT true;

-- Перенос намерения из ЧЕРНОВИКА: он и есть последняя воля автора (тумблер писал
-- туда). Опубликованные снапшоты не спрашиваем — намерение из них могло быть
-- отменено правкой черновика, которую ещё не публиковали.
UPDATE forms SET branding = false
 WHERE draft_schema -> 'design' ->> 'branding' = 'false';

-- Ключ уходит из документов совсем: контракт схемы строгий с обеих сторон
-- (DisallowUnknownFields в Go, strictObject в Zod), поэтому оставленный ключ не
-- дал бы разобрать ни черновик, ни снапшот. Пустой design схлопывается в NULL —
-- тем же правилом, каким его схлопывает кабинет: объект без единого ключа и
-- отсутствие объекта обязаны быть одним состоянием, иначе канонизация снапшота
-- при публикации даст два разных документа на одну форму.
CREATE FUNCTION pg_temp_strip_branding(doc jsonb) RETURNS jsonb AS $$
  SELECT CASE
    WHEN coalesce(jsonb_typeof(doc -> 'design'), '') <> 'object' THEN doc
    -- Скобки обязательны: у вычитания приоритет ВЫШЕ, чем у `->`, и без них
    -- Postgres читает выражение как doc -> ('design' - 'branding').
    WHEN (doc -> 'design') - 'branding' = '{}'::jsonb THEN doc - 'design'
    ELSE jsonb_set(doc, '{design}', (doc -> 'design') - 'branding')
  END
$$ LANGUAGE sql IMMUTABLE;

UPDATE forms SET draft_schema = pg_temp_strip_branding(draft_schema)
 WHERE draft_schema -> 'design' ? 'branding';

-- ⚠ ТРОГАЕТ form_versions — таблицу, которую migrations/CLAUDE.md объявляет
-- иммутабельной. То же осознанное отступление и по тому же доводу, что в 0020,
-- 0025 и 0026: иначе публичная отдача обязана понимать оба формата вечно, а
-- строгий разбор снапшота отверг бы старый документ. Пользовательских форм нет,
-- schemaVersion заморожена до релиза. После релиза правило действует без
-- исключений.
UPDATE form_versions SET schema = pg_temp_strip_branding(schema)
 WHERE schema -> 'design' ? 'branding';

DROP FUNCTION pg_temp_strip_branding(jsonb);
