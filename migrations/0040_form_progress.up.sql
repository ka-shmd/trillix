-- 0040: шкала прогресса — намерение автора о том, показывать ли индикатор шагов
-- многостраничной формы (решение владельца 2026-08-29).
--
-- ЖИВАЯ КОЛОНКА, а не поле схемы (решение владельца, ADR §10 — та же природа, что
-- у бейджа): автор снимает шкалу и хочет увидеть форму без неё сразу, а не после
-- перепубликации. Документ формы от этого не меняется: индикатор рисует не блок
-- полотна, а хром страницы, и снапшот версии его не несёт.
--
-- true = показывать, и дефолт ВЫКЛЮЧЕН (решение владельца 2026-08-29). Прежнее
-- поведение он не повторяет: до 0040 индикатор стоял всегда при двух и более
-- страницах, а теперь его нет, пока автор не включит, — то есть миграция меняет вид
-- уже опубликованных многостраничных форм. Это осознанная цена: шкала — решение
-- автора, а не свойство формы по умолчанию.
ALTER TABLE forms ADD COLUMN progress BOOLEAN NOT NULL DEFAULT false;
