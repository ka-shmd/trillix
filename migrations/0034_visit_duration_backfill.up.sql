-- 0034: починка длительности визитов, собранных ДО миграции 0030.
--
-- ЧТО СЛОМАЛОСЬ. 0030 добавила колонку как `NOT NULL DEFAULT now()`, и Postgres
-- проставил существующим строкам время САМОЙ МИГРАЦИИ, а не их created_at (в
-- комментарии 0030 было написано обратное — неверно). В результате визит, случившийся
-- за две недели до выкатки, выглядит длившимся две недели: карточка «Длительность
-- визита» за «всё время» показывает дни вместо секунд.
--
-- ПОЧЕМУ ЛЕЧИМ ПРИРАВНИВАНИЕМ, А НЕ УДАЛЕНИЕМ. Запросы считают визит измеренным
-- только при updated_at > created_at (см. internal/visits/queries.sql). Приравняв
-- одно к другому, мы говорим правду: длительности этих визитов мы не знаем — их
-- второй бикон случился до того, как мы научились его запоминать.
--
-- ДВА УСЛОВИЯ, и каждое закрывает свою часть данных:
--   seq = 0   — структурное: updated_at двигается тем же UPDATE'ом, что и seq, поэтому
--               у визита с единственным биконом длительности не бывает по построению.
--               Дат тут не нужно вовсе.
--   created_at < момента выкатки v0.26.0 — всё остальное, что застала 0030. Дата
--               зашита намеренно: отличить «строку проштамповала миграция» от
--               «человек правда заполнял форму долго» другим способом нельзя, а
--               оставить мусор — значит навсегда испортить медиану за «всё время».
--               Контурам, где данных до выкатки не было, оператор ничего не стоит.
UPDATE form_visits
SET updated_at = created_at
WHERE updated_at > created_at
  AND (seq = 0 OR created_at < timestamptz '2026-08-25 08:35:00+00');
