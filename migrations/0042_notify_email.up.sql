-- 0042: письмо о новом ответе — выключено по умолчанию и настраивается автором
-- (решение владельца 2026-08-29).
--
-- ТРИ РАЗНЫЕ ПРАВКИ, и держатся они вместе, потому что описывают одну настройку.
--
-- 1. Дефолт тумблера меняется на false. До 0042 письма были включены у каждой
--    новой формы (0013), то есть продукт начинал слать почту, ни о чём не спросив.
UPDATE forms SET notify_on_submission = false;
ALTER TABLE forms ALTER COLUMN notify_on_submission SET DEFAULT false;

-- 2. Шаблон письма — своя колонка JSONB рядом с остальными живыми настройками
--    (имя отправителя, Reply-To, тема, текст). NULL = автор не настраивал, письмо
--    уходит дефолтным шаблоном `internal/mail`. JSONB, а не четыре колонки, по тому
--    же доводу, что у link_preview: поля меняются вместе, по отдельности не ищутся
--    и в WHERE не участвуют; структуру валидирует приложение.
--
--    Живая колонка: письмо — не документ формы, снапшот версии его не несёт, и
--    правка обязана действовать со следующего же ответа, без перепубликации.
ALTER TABLE forms ADD COLUMN notify_email JSONB;

-- 3. Ключ гейта в лимитах ВСЕХ планов: молчание плана про известный ключ считается
--    ошибкой конфигурации и краснеет TestPlansCoverCatalog. Заводится СРАЗУ
--    закрытым на бесплатных планах — в отличие от 0018, где ключи ставились
--    открытыми: решение владельца принято вместе с самой настройкой («менять может
--    только платный»), и открывать её на день, чтобы закрыть следующей миграцией,
--    незачем.
UPDATE plans SET limits = limits || '{"form_notify_email": true}'::jsonb;
UPDATE plans SET limits = limits || '{"form_notify_email": false}'::jsonb
 WHERE code IN ('free', 'legacy_free');
