-- 0032: суточный ключ посетителя (спека design/analytics-tally.md §6, ADR §10).
--
-- ЧТО ЭТО. Хеш sha256(соль дня ‖ form_id ‖ IP ‖ user-agent), обрезанный до 16 байт.
-- Нужен ровно для одного числа: «сколько людей», а не «сколько визитов». Три захода
-- одного человека за день дают один ключ и одного уникального.
--
-- ЧТО ЭТО НЕ. Не идентификатор человека и не псевдоним: соль выводится из секрета
-- контура и ДАТЫ, поэтому завтра тот же человек получит другой ключ. Связать
-- вчерашнего посетителя с сегодняшним нельзя даже нам — вчерашняя соль нигде не
-- хранится. Это и есть цена, которой мы платим за право вообще считать людей: за
-- период длиннее суток «уникальные» завышены, и оговорка стоит на экране.
--
-- Отменяет запись «человек между визитами не узнаётся сознательно» (0008) — узнаётся,
-- но только в пределах суток и только внутри одной формы: form_id входит в хеш,
-- поэтому один посетитель двух форм это два ключа, и сквозного профиля не собрать.
--
-- IP по-прежнему НЕ ХРАНИТСЯ. Он участвует в вычислении и исчезает; из ключа его не
-- восстановить (можно лишь проверить гипотезу «этот адрес заходил», зная секрет
-- контура и дату, — цена принята явно).
ALTER TABLE form_visits ADD COLUMN visitor_key BYTEA;

-- Индекс под count(distinct visitor_key) за период. Частичный: визиты без ключа
-- (нет IP, нет секрета) в счёт уникальных не идут и в индексе не нужны.
CREATE INDEX idx_form_visits_visitor ON form_visits (form_id, created_at, visitor_key)
    WHERE visitor_key IS NOT NULL;
