-- 0055: ход назад по страницам формы (просьба владельца 2026-09-07).
--
-- Третья колонка раздела «Поведение» (0044), к auto_jump и save_locally: это одна
-- экранная группа, и кабинет шлёт её набором. Живая колонка по тем же доводам —
-- поведение выдачи, а не документ: правка обязана действовать со следующего же
-- открытия формы, без перепубликации.
--
-- allow_back — пускать ли респондента на пройденные страницы. Выключенная (дефолт)
-- повторяет поведение, которое действовало с 2026-08-22 и до этой миграции: хода
-- назад нет ни одного. Включённая даёт ДВА пути и ровно два (решение владельца
-- 2026-09-07): кнопка «Назад» рядом с «Далее» и клик по линии пройденного шага
-- индикатора. Записи в истории браузера НЕТ ни при каком значении — системная
-- «Назад» уводит со страницы формы, как и раньше: во фрейме вставки записи ушли бы
-- в общую историю, и «Назад» чужой страницы начала бы листать наши шаги.
--
-- Выключена по умолчанию по тому же доводу, что обе соседки: поведение, которого
-- автор не просил, за него не включается — в том числе на уже опубликованных формах.
ALTER TABLE forms ADD COLUMN allow_back BOOLEAN NOT NULL DEFAULT false;
