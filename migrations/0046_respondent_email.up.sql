-- 0046: письмо респонденту после отправки формы (docs/design/respondent-email.md,
-- решение владельца 2026-08-30). До неё респондент не получал ничего, а строка
-- «Уведомления респонденту» на экране настроек стояла заглушкой.

-- 1. Тумблер. Зеркало notify_on_submission и с тем же дефолтом: продукт не начинает
--    слать почту, ни о чём не спросив.
ALTER TABLE forms ADD COLUMN notify_respondent BOOLEAN NOT NULL DEFAULT false;

-- 2. Бланк письма — своя колонка JSONB рядом с notify_email (0042), тем же составом
--    полей плюс sourceBlockId: id вопроса типа email, из ответа на который берётся
--    АДРЕС. NULL = автор не настраивал, письмо уходит дефолтным шаблоном.
--
--    Живая колонка: письмо не документ формы, снапшот версии его не несёт, и правка
--    обязана действовать со следующего ответа, без перепубликации (ADR §10).
--    Отдельная от notify_email, а не общая с ней: у двух писем разные адресаты,
--    разные гейты и разная судьба при даунгрейде — общий JSONB означал бы, что
--    правка одного письма переписывает другое.
ALTER TABLE forms ADD COLUMN respondent_email JSONB;

-- 3. Ключ гейта в лимитах ВСЕХ планов: молчание плана про известный ключ считается
--    ошибкой конфигурации и краснеет TestPlansCoverCatalog.
--
--    Свой ключ, а не общий с form_notify_email: там платной является ПЕРЕБИВКА
--    письма владельцу (само письмо бесплатно, владелец пишет сам себе), здесь —
--    сама ОТПРАВКА, потому что бесплатный тариф иначе открытый канал рассылки с
--    нашего домена. Заводится сразу закрытым на бесплатных планах, как 0042.
UPDATE plans SET limits = limits || '{"form_respondent_email": true}'::jsonb;
UPDATE plans SET limits = limits || '{"form_respondent_email": false}'::jsonb
 WHERE code IN ('free', 'legacy_free');
