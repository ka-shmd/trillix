-- 0031: страна и город визита (спека design/analytics-tally.md §7, ADR §10).
--
-- ГЛАВНОЕ ПРО ЭТУ МИГРАЦИЮ: колонки IP здесь нет и не будет. Страна и город
-- выводятся из IP в момент приёма бикона по локальному справочнику, после чего сам
-- адрес забывается — он не пишется ни сюда, ни в лог, ни в хеше. Запись «IP не
-- пишется» из 0008 остаётся верной; изменилось то, что он теперь ЧИТАЕТСЯ.
--
-- Имена, а не только код страны: справочник отдаёт русские названия готовыми, а
-- держать в коде таблицу «код → название» ради экономии пятнадцати байт на строке,
-- в которой уже лежит user_agent, незачем. Имя ЗАМОРАЖИВАЕТСЯ в момент визита:
-- переименование города в новой версии справочника не переписывает прошлое — то же
-- правило, по которому мета визита есть контекст первого касания.
--
-- Все три колонки nullable, и NULL здесь не «нет данных по недосмотру», а законное
-- «место не определили»: справочника на контуре нет, адрес приватный или это IPv6
-- (формат справочника его не понимает). Экран показывает такие визиты строкой
-- «Не определено» — дыра видима, а не спрятана.
ALTER TABLE form_visits
    ADD COLUMN country_code TEXT,  -- ISO 3166-1 alpha-2, верхним регистром
    ADD COLUMN country      TEXT,  -- русское название страны из справочника
    ADD COLUMN city         TEXT;  -- русское название города из справочника

-- Индекс под группировку стран и городов за период. Отдельный от покрывающего
-- idx_form_visits_form: тот ведёт форму и время ради воронки и карточек, и дописать
-- в него ещё три колонки значило бы раздуть ключ, который читают все запросы, ради
-- одного экрана.
--
-- Частичный (WHERE country_code IS NOT NULL): визиты без гео в списки стран не
-- попадают вовсе, и держать их в индексе незачем — на контуре без справочника он
-- останется пустым и бесплатным.
CREATE INDEX idx_form_visits_geo ON form_visits (form_id, created_at, country_code, city)
    WHERE country_code IS NOT NULL;
