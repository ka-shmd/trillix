-- 0066: уведомления кабинета — лента адресованных событий пространства
-- (спека docs/design/notifications.md, четыре строки ADR §10).
--
-- Строка = ПОВОД, адресованный человеку, а не попытка доставки: доставкой наружу
-- заняты outbox (письма) и очереди по целям (интеграции), а это чтение своей же
-- БД. Почему лента, а не производное от состояния (уведомлений в БД нет вовсе,
-- кабинет считает «что нового» по submissions и статусам целей), — ADR §10,
-- строка «Уведомления кабинета…»: производное дешевле, но не даёт ни истории, ни
-- фронта событию, от которого потом заводится push в мессенджер.
CREATE TABLE notifications (
    id           UUID PRIMARY KEY,                     -- UUIDv7 (domain.NewID): он же порядок ленты и курсор
    user_id      UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    workspace_id UUID NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    -- kind — повод. CHECK'а нет намеренно, как у outbox.channel: перечень поводов
    -- живёт реестром в internal/notify (текст, адресат, ссылка, отбой), и второй
    -- список в констрейнте означал бы миграцию на каждый новый повод при том, что
    -- чужих писателей у таблицы нет.
    kind         TEXT NOT NULL,
    -- Каскад, а не украшение: удалённая форма уносит свои уведомления сама, и лента
    -- не показывает ссылок в никуда. NULL у поводов пространства (квота).
    form_id      UUID REFERENCES forms(id) ON DELETE CASCADE,
    -- Субъект повода: форма, цель доставки или пространство. Внешнего ключа нет —
    -- субъект разного вида, одной ссылки на него не существует. Строки, которые
    -- каскад не унесёт, гасит отбой (починка и удаление цели) и уборщик.
    subject_id   UUID NOT NULL,
    -- Снимок того, из чего собираются текст и ссылка. Почему снимок, а не JOIN на
    -- живые таблицы: причина поломки живёт в last_error ЦЕЛИ и затирается починкой,
    -- а уведомление обязано помнить, что было; этот же снимок уедет в сообщение
    -- мессенджера, когда канал придёт.
    payload      JSONB NOT NULL,
    count        INT NOT NULL DEFAULT 1,               -- сколько событий склеилось в эту строку
    first_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    read_at      TIMESTAMPTZ                           -- NULL = непрочитано
);

-- Коалесинг только в НЕПРОЧИТАННОЕ: прочитал — следующее событие заводит новую
-- строку, и «3 новых ответа» не дописываются задним числом к уже увиденному. Тот
-- же приём, что стоит в outbox под coalesce_key (0013).
--
-- Этот же индекс обслуживает счётчик непрочитанных на колокольчике — отдельного
-- индекса под него не нужно.
CREATE UNIQUE INDEX idx_notifications_live
    ON notifications (user_id, kind, subject_id) WHERE read_at IS NULL;

-- Лента пользователя: свежие сверху. Порядок по last_at, а не по id: id — момент
-- ПЕРВОГО события склейки, и строка, получившая двенадцатый ответ минуту назад,
-- лежала бы ниже давно молчащей. Показываем мы тоже last_at, и расходиться порядку
-- с показанным временем нельзя. id вторым ключом — tie-break курсора: у двух строк
-- last_at совпадает чаще, чем кажется (одно событие адресуется всем участникам).
CREATE INDEX idx_notifications_feed ON notifications (user_id, last_at DESC, id DESC);

-- Уборка по возрасту (30 суток прочитанным, 90 непрочитанным): у ленты, в отличие
-- от производного состояния, нет способа забыть самой.
CREATE INDEX idx_notifications_age ON notifications (first_at);
