-- 0016: подписка переезжает с воркспейса на АККАУНТ (ADR §10, фаза 18).
--
-- Почему: фаза 18 даёт человеку несколько воркспейсов, и на воркспейс-подписке
-- получается нелепица — Pro куплен ради права завести командное пространство, а
-- созданное пространство рождается на Free. Решение владельца 2026-08-02: план
-- принадлежит аккаунту, воркспейс работает по плану своего ВЛАДЕЛЬЦА
-- (единственный участник с role='owner'). Отмена решения фазы 17 сделана сейчас,
-- пока перенос стоит нескольких UPDATE'ов: гейты на проде выключены, платежей не
-- было ни одного, все существующие воркспейсы — личные и с одним участником.
--
-- Миграция делает переезд ЦЕЛИКОМ, а не в два релиза, как требует общее правило
-- migrations/CLAUDE.md: правило страхует код предыдущей версии, работающий на
-- новой схеме те секунды, пока идёт выкатка, — а страховать сейчас некого,
-- пользователей у продукта ещё нет (решение владельца 2026-08-02). Как только
-- они появятся, правило снова действует без исключений.

-- 1. Пометка личного пространства. NULL у командных, у личного — его хозяин:
-- одна колонка отвечает и «личное ли», и «чьё», а UNIQUE даёт «ровно одно на
-- аккаунт» на уровне БД (в Postgres UNIQUE не мешает множеству NULL — командных
-- пространств у аккаунта может быть сколько угодно).
--
-- Личное пространство не удаляется, не покидается и не замораживается при
-- даунгрейде: иначе человек теряет доступ к собственным формам (ADR §10).
ALTER TABLE workspaces
    ADD COLUMN personal_user_id UUID REFERENCES users(id) ON DELETE CASCADE;

CREATE UNIQUE INDEX idx_workspaces_personal_user ON workspaces (personal_user_id);

-- Бэкфилл: на момент миграции КАЖДЫЙ воркспейс личный и ровно с одним
-- участником (единственный путь создания — транзакция регистрации), поэтому
-- «самое раннее членство» и «хозяин» — одно и то же. Тай-брейк по user_id, чтобы
-- результат не зависел от совпадения created_at.
--
-- Воркспейс БЕЗ участников остаётся с NULL, и это осознанно: такие сироты
-- возникают от удаления пользователя (членство каскадится, пространство нет —
-- TD-53) и недостижимы ни одним запросом, потому что доступ везде идёт через
-- членство. Ронять миграцию из-за недостижимого мусора нельзя — это остановило
-- бы выкатку; пометить его наугад тоже нельзя — речь про то, чей это план.
UPDATE workspaces w
   SET personal_user_id = (SELECT m.user_id
                             FROM workspace_members m
                            WHERE m.workspace_id = w.id
                            ORDER BY m.created_at, m.user_id
                            LIMIT 1);

-- 2. Владелец у пространства РОВНО один (решение владельца 2026-08-02).
-- «Не больше одного» держит этот индекс; «не меньше одного» индексом невыразимо
-- и остаётся правилом сервиса (нельзя разжаловать и удалить последнего owner'а).
-- Если у какого-то воркспейса окажется два owner'а, миграция упадёт здесь — это
-- и требуется: молча выбирать «главного» из двух нельзя, речь про деньги.
CREATE UNIQUE INDEX idx_workspace_members_owner
    ON workspace_members (workspace_id) WHERE role = 'owner';

-- 3. Подписка переезжает на аккаунт: колонка, бэкфилл, первичный ключ.
ALTER TABLE subscriptions
    ADD COLUMN user_id UUID REFERENCES users(id) ON DELETE CASCADE;

UPDATE subscriptions s
   SET user_id = w.personal_user_id
  FROM workspaces w
 WHERE w.id = s.workspace_id;

-- Подписка без владельца — след того же сиротства (TD-53): воркспейс есть,
-- участников нет, значит и аккаунта-плательщика нет. Такая строка не описывает
-- ничьи деньги и уезжает вместе со своим воркспейсом, а не блокирует NOT NULL.
DELETE FROM subscriptions WHERE user_id IS NULL;

ALTER TABLE subscriptions ALTER COLUMN user_id SET NOT NULL;

-- Первичный ключ переезжает на аккаунт, workspace_id уходит совсем: пока он тут,
-- у вопроса «чей это тариф» два ответа, и однажды они разойдутся. Подписка у
-- аккаунта ровно одна — история операций будет журналом платежей, а не набором
-- строк здесь (ADR §10).
ALTER TABLE subscriptions DROP CONSTRAINT subscriptions_pkey;
ALTER TABLE subscriptions DROP COLUMN workspace_id;
ALTER TABLE subscriptions ADD PRIMARY KEY (user_id);

-- 4. Личное пространство называется по-русски: интерфейс русскоязычный, а имя
-- воркспейса видно человеку в сайдбаре и крошках. Имя новых пространств задаёт
-- код (internal/auth), здесь переименовываются уже созданные.
UPDATE workspaces SET name = 'Личное пространство' WHERE name = 'Personal';
