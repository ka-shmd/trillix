-- 0047: пароль на форму (docs/design/form-password.md, решения владельца 2026-09-01).
-- До неё строка «Пароль на форму» в блоке «Доступность» стояла заглушкой с красной
-- меткой: тумблер выключен, за ним ничего.

-- Пароль лежит ОБРАТИМО — шифротекстом AES-GCM, а не хешем (решение владельца, спека
-- §2.1): автор видит и копирует свой пароль, потому что это не учётная запись, а общий
-- секрет, который он рассылает участникам. Ключ выводится HKDF из FORM_TOKEN_SECRET с
-- отдельной меткой назначения — тот же приём, что у секрета TOTP и refresh-токенов
-- интеграций; дамп базы без секрета пароли не отдаёт.
--
-- Инвариант безопасности 2 («пароли — только argon2id») говорит о паролях АККАУНТОВ:
-- за паролем формы нет ни личности, ни сессии, ни права в кабинете. Строка здесь
-- потому, что при чтении инварианта по диагонали это выглядит нарушением.
--
-- Живая колонка, как настройки закрытия: включение и снятие действуют немедленно, без
-- перепубликации. NULL = пароля нет.
ALTER TABLE forms ADD COLUMN password BYTEA;
