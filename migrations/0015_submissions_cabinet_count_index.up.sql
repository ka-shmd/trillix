-- 0015: индекс под счётчики кабинета, разделяющие видимые и скрытые ответы.
--
-- Найдено ревью фазы 17 и подтверждено замером на сидированной базе (форма с
-- 10 000 ответов, `make seed`):
--
--   count(*) WHERE form_id = $1                     → Index Only Scan, 10 буферов, Heap Fetches: 0
--   count(*) FILTER (WHERE NOT over_quota) ...      → Seq Scan, 223 буфера
--   то же с этим индексом                           → Index Only Scan, 11 буферов, Heap Fetches: 0
--
-- Колонки over_quota нет ни в одном существующем индексе, поэтому фильтрующий
-- счёт вынужден идти в кучу за каждой строкой формы. На десяти тысячах разница
-- ещё в миллисекундах (1,4 мс против 0,7), но растёт линейно и бьёт по двум
-- горячим экранам сразу: карточка каждой формы в списке (LATERAL-подсчёт) и
-- таблица ответов.
--
-- Отдельной миграцией, а не правкой 0014: та уже применена на dev-контурах, и
-- отредактированная миграция не переприменится сама — расхождение схемы было бы
-- молчаливым (migrations/CLAUDE.md).
--
-- Частичный индекс (WHERE NOT over_quota) дал бы index-only только «видимым»;
-- обе величины нужны одной поездкой (visible и hidden считаются вместе), поэтому
-- over_quota входит в ключ.
CREATE INDEX idx_submissions_form_over_quota ON submissions (form_id, over_quota);
