-- Откат возвращает намерение в документы: колонка исчезает, и без этого шага
-- прежний код увидел бы формы, с которых бейдж сняли, снова с бейджем.
--
-- Правится ЧЕРНОВИК и только он: снапшоты up-миграция чистила необратимо (какая
-- версия несла ключ, а какая нет, не сохранялось), а гадать за иммутабельную
-- таблицу — хуже, чем оставить её в сегодняшнем виде. Прежний код на снапшоте без
-- ключа рисует бейдж — то же, что видел автор до перепубликации.
UPDATE forms
   SET draft_schema = jsonb_set(
         draft_schema,
         '{design}',
         coalesce(draft_schema -> 'design', '{}'::jsonb) || '{"branding": false}'::jsonb
       )
 WHERE NOT branding;

ALTER TABLE forms DROP COLUMN branding;
