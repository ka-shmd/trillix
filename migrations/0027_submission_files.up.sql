-- 0027: файлы в ответах (фаза 24 DEV-PLAN = 17 POST-MVP,
-- docs/design/answer-files.md).
--
-- Учёт загрузок ведёт таблица, а не листинг бакета. Причина не в удобстве: без неё
-- нечем считать квоту воркспейса, нечем собирать сирот (обход всего бакета — не
-- сборка мусора) и нечем удалять файлы вместе с ответом.
--
-- Жизненный цикл строки: «ожидает» (слот выдан, байты, возможно, ещё летят) →
-- «заявлена» (ответ пришёл, файл сверен с хранилищем). Незаявленная строка старше
-- суток — сирота: её объект и её саму сносит периодическая чистка. Сутки взяты не с
-- потолка: это потолок возраста токена формы, дольше незаявленной загрузке жить
-- незачем.
CREATE TABLE submission_files (
    -- UUIDv7, выдаёт СЕРВЕР, и он же — право на файл: знает его только тот, кому
    -- выдали слот. Поэтому заявление не требует ни сессии, ни привязки к заранее
    -- объявленному ответу (рендерер генерирует submission_id лениво, на отправке).
    id            UUID PRIMARY KEY,
    -- Денормализовано ради двух чтений, которым иначе понадобился бы join к forms
    -- на каждой загрузке: квота воркспейса и чистка сирот.
    workspace_id  UUID NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    form_id       UUID NOT NULL REFERENCES forms(id) ON DELETE CASCADE,
    -- Блок, для которого выдан слот: его настройки (число файлов, размер, семейства)
    -- проверяются при выдаче, а при заявлении — что файл пришёл в ТОТ вопрос.
    block_id      TEXT NOT NULL,
    submission_id UUID REFERENCES submissions(id) ON DELETE CASCADE,
    -- Ключ объекта в приватном бакете. UNIQUE — потому что ключ содержит id строки:
    -- дубль означал бы, что два слота смотрят в один объект.
    object_key    TEXT NOT NULL UNIQUE,
    -- Имя файла — ДАННЫЕ, а не путь: в ключ объекта оно не попадает ни в каком виде,
    -- и вычищено от управляющих символов и разделителей пути ещё до вставки.
    original_name TEXT NOT NULL,
    -- При выдаче слота — заявленный размер (он же уезжает в подпись), при заявлении —
    -- проверенный у хранилища. Разошлись — объект сносится, ответ не принимается.
    size_bytes    BIGINT NOT NULL CHECK (size_bytes > 0),
    content_type  TEXT NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    claimed_at    TIMESTAMPTZ,
    -- Заявление — это ОДНО событие: ответ и отметка времени появляются вместе.
    -- Строка с submission_id, но без claimed_at (или наоборот) означала бы, что одна
    -- из двух половин заявления потерялась, и оба чтения — квота и чистка — начали
    -- бы считать её по-разному.
    CONSTRAINT submission_files_claim_complete
        CHECK ((claimed_at IS NULL) = (submission_id IS NULL))
);

-- Сборка сирот: незаявленные, по возрасту. Частичный — заявленных со временем
-- станет на порядки больше, и в этом индексе им делать нечего.
CREATE INDEX idx_submission_files_pending
    ON submission_files (created_at) WHERE claimed_at IS NULL;

-- Файлы одного ответа: показ автору и удаление вместе с ответом.
CREATE INDEX idx_submission_files_submission
    ON submission_files (submission_id) WHERE submission_id IS NOT NULL;

-- Расход хранилища воркспейса (квота тарифа) — сумма размеров заявленных файлов.
CREATE INDEX idx_submission_files_workspace
    ON submission_files (workspace_id) WHERE claimed_at IS NOT NULL;

-- ⚠ ПОРЯДОК УДАЛЕНИЯ: объект в бакете сносится ДО строки. Каскад здесь —
-- страховка целостности, а не механизм уборки: строка уносит с собой ключ, и
-- объект, переживший её, становится сиротой, которую уже никто не найдёт — ни
-- чистка (она смотрит в эту таблицу), ни человек.

-- Новый ключ тарифа: сколько байт хранилища помещается в пространство. Заводится
-- ВЫКЛЮЧЕННЫМ (null = безлимит) — гейты приезжают на прод выключенными и
-- включаются отдельным UPDATE (решение фазы 17). Каждый план обязан НАЗВАТЬ каждый
-- ключ каталога, иначе краснеет TestPlansCoverCatalog.
UPDATE plans SET limits = jsonb_set(limits, '{storage_per_workspace}', 'null');
