-- 0041: сбор незавершённых ответов становится платным на бесплатных планах
-- (решение владельца 2026-08-29 — «у частичных ответов не работает гейт»).
--
-- Ключ `submissions_partial` завела 0033 ОТКРЫТЫМ всем планам: гейт был написан и
-- поставлен на место выключенным, а закрытие оставлено на потом одним UPDATE'ом —
-- команда выписана прямо в комментарии 0033. Это и есть «потом».
--
-- Решение о платности принято не сейчас: ADR §10 (фаза 23) описывает сбор
-- незавершённых как тумблер ЗА ПЛАТНЫМ ТАРИФОМ, и весь код так и написан — право
-- спрашивается при включении тумблера, при отдаче публичной формы и при листинге
-- черновиков. Расходились с этим только данные.
--
-- legacy_free гейтится вместе с free — как в 0039, и по тому же доводу: ключ был
-- открыт с фазы 23, и у бесплатного автора, включившего сбор, он остановится.
-- Собранное при этом НЕ удаляется: выключить тумблер и удалить черновик можно на
-- любом плане, а листинг ответит 402 с предложением тариф оплатить.
--
-- Обратно — один UPDATE без выкатки, как и всё в plans.limits.
UPDATE plans
SET limits = limits || '{"submissions_partial": false}'::jsonb
WHERE code IN ('free', 'legacy_free');
