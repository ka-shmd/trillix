-- 0021: профиль аккаунта — имя и фамилия человека, адрес аккаунта у провайдера.
-- Фаза 23 (DEV-PLAN), слайс A. Замысел и отвергнутые альтернативы —
-- docs/design/account-settings.md.

-- Имя и фамилия nullable и остаются такими: до этой миграции у аккаунта имени
-- не было вовсе, и заполнить его задним числом нечем — у парольных регистраций
-- этих данных нет ни в одной таблице. Пустое значение хранится как NULL, а не
-- как '': два способа записать «не указано» разъезжаются в первом же запросе,
-- который сравнивает с одним из них.
--
-- Ни одна проверка на них не завязана и не будет: имя показывается в кабинете
-- вместо email, когда есть, и ничего не гейтит.
ALTER TABLE users ADD COLUMN first_name TEXT;
ALTER TABLE users ADD COLUMN last_name  TEXT;

-- Адрес аккаунта У ПРОВАЙДЕРА — подпись под карточкой «Яндекс · ivan@yandex.ru»
-- на экране настроек. Это НЕ users.email: адреса расходятся сразу же, как
-- человек сменит почту у нас (миграция 0022) или привяжет Яндекс с другим
-- ящиком, и именно этим расхождением карточка полезна — по ней видно, какая
-- личность привязана (сюжет TD-34: личность у провайдера сменилась).
--
-- Колонка nullable: у уже привязанных личностей адреса нет и взять его неоткуда
-- (токен провайдера одноразовый — ADR §10), заполнится на ближайшем входе.
--
-- Заводится этой миграцией, а заполняется слайсом E — одна миграция дешевле
-- двух, а колонка без читателя ничего не ломает.
ALTER TABLE user_identities ADD COLUMN provider_email TEXT;
