-- 0030: длительность визита и период наблюдения (спека design/analytics-tally.md
-- §4, §5.1). Две правки одной таблицы, обе ради экранов Insights.

-- updated_at — время последнего бикона визита. Длительность визита = разница с
-- created_at, и больше её брать неоткуда: рендерер шлёт минимум два бикона
-- («открыли» и «ушёл со страницы»), то есть обе границы у сервера уже есть.
-- Клиентскую длительность в теле бикона не принимаем — её подделает тот же, кто
-- подделывает визиты, а серверная не требует ни нового поля, ни правок рендерера.
--
-- DEFAULT now() задним числом означает, что у собранных до этой миграции визитов
-- updated_at = created_at, то есть нулевая длительность. Это не потеря: такие
-- визиты в медиану не входят по тому же правилу, что и визиты с одним биконом
-- (см. queries.sql, VisitInsights).
ALTER TABLE form_visits ADD COLUMN updated_at TIMESTAMPTZ NOT NULL DEFAULT now();

-- Перестройка покрывающего индекса под диапазон по времени.
--
-- Селектор периода (сутки/неделя/месяц/всё время) добавляет во ВСЕ читающие
-- запросы условие по created_at. Старый индекс (form_id, last_block_id, submitted)
-- его не поддерживает: диапазонная колонка не входит в ключ, и запрос с периодом
-- выпал бы в heap-скан — молча, без падения, с деградацией, растущей вместе с
-- числом визитов (ровно тот сценарий, о котором предупреждает ANALYTICS.md §5).
--
-- Порядок колонок: form_id ведущая (по ней фильтруют все), created_at вторая
-- (диапазон), last_block_id и submitted в хвосте — они нужны GROUP BY воронки и
-- держат index-only-скан. Запросы БЕЗ периода этот индекс обслуживает тоже:
-- ведущая колонка та же.
--
-- INCLUDE (updated_at) — ради запроса карточек: он единственный читает обе границы
-- визита (медиана длительности), и без этой колонки уходил в кучу. Замер на 18 000
-- визитов шести форм (EXPLAIN ANALYZE, BUFFERS; VACUUM ANALYZE перед каждым):
--   карточки за сутки, без INCLUDE: 39 буферов, Bitmap Heap Scan;
--   карточки за сутки, с INCLUDE:   14 буферов, Index Only Scan, Heap Fetches: 0.
--   воронка за сутки: 12 → 14 буферов (плата за ширину), Heap Fetches: 0 в обоих.
-- Лишних не-HOT обновлений INCLUDE не создаёт: last_block_id и так в ключе, а
-- updated_at двигается тем же UPDATE'ом, что и он.
DROP INDEX idx_form_visits_form;
CREATE INDEX idx_form_visits_form ON form_visits (form_id, created_at, last_block_id, submitted)
    INCLUDE (updated_at);
