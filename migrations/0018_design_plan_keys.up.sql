-- 0018: три ключа оформления в лимитах всех планов (фаза 22, слайс 6).
--
-- Данные, а не код: какие гейты БЫВАЮТ — в internal/entitlements/catalog.go,
-- а что даёт каждый план — здесь. Молчание плана про известный ключ считается
-- ошибкой конфигурации и краснеет TestPlansCoverCatalog, поэтому ключи ставятся
-- КАЖДОМУ плану, включая legacy_free.
--
-- ВСЕ ТРИ В true — то есть возможности открыты всем, а гейты стоят на своих
-- местах выключенными. Это не забывчивость: раскладка «что входит в Free»
-- упирается в нерешённое (когда вообще включать Free и на скольких ответах),
-- спека design/theme.md §13.3. Включение любого — один UPDATE без выкатки:
--
--   UPDATE plans SET limits = jsonb_set(limits, '{form_design_custom}', 'false')
--    WHERE code IN ('free', 'legacy_free');
--
-- form_custom_css заводится вместе с остальными, хотя точка применения у него
-- появится только слайсом 7: ключ без вызова безвреден (так сегодня живёт
-- analytics_sources), а вот план без ключа — ошибка конфигурации.
--
-- `||` (слияние объектов), а не jsonb_set по одному ключу: добавляем сразу три,
-- и слияние не требует, чтобы путь уже существовал.
UPDATE plans
SET limits = limits || '{
        "form_design_custom": true,
        "form_custom_css": true,
        "form_branding": true
    }'::jsonb;
