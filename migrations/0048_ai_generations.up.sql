-- 1. Счётчик расхода за период — рядом с submissions, в той же таблице и с тем же
--    смыслом: сколько израсходовано с первого числа месяца (МСК). Своя колонка, а
--    не COUNT(*) по журналу вызовов: журнала вызовов нет вовсе, и заводить таблицу
--    ради одного числа дороже, чем колонку.
--
--    Инкремент отдельным UPDATE после удачной генерации, а не внутри INSERT'а
--    формы, как у ответов: там инкремент в том же утверждении обязателен, потому
--    что приём ответа не имеет права ни отказать, ни потерять счёт, а здесь вызов
--    модели может не состояться, и списывать за него квоту не за что.
ALTER TABLE workspace_usage ADD COLUMN ai_generations BIGINT NOT NULL DEFAULT 0
    CHECK (ai_generations >= 0);

-- 2. Ключ квоты в лимитах ВСЕХ планов: молчание плана про известный ключ считается
--    ошибкой конфигурации и краснеет TestPlansCoverCatalog.
--
--    Числа — решение владельца 2026-09-01: 10 генераций в месяц на бесплатных
--    планах, 100 на pro. Не null (безлимита у этого ключа не бывает ни на одном
--    плане): каждый вызов стоит денег снаружи, и «сколько угодно» здесь означало бы
--    открытый счёт. legacy_free держится наравне с free — прецедент 0041.
UPDATE plans SET limits = limits || '{"ai_generations": 100}'::jsonb;
UPDATE plans SET limits = limits || '{"ai_generations": 10}'::jsonb
 WHERE code IN ('free', 'legacy_free');
